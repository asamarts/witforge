#!/usr/bin/env bash
# Build witforge's runner image, register the runner once, and install it as a rootless podman
# quadlet service (see ci/README.md). Safe to re-run: it rebuilds the image and restarts the
# service, and registers only when no registration is stored.
#
# Needs podman and the gh CLI logged in to the GitHub account that owns the repository.
#
# witforge has been public since 0.1.0 and runs CI on GitHub-hosted runners. A self-hosted runner
# must never serve a public repository, where a pull request from a fork could run code on it, so
# this script refuses unless WITFORGE_REPO names a private repository.
set -euo pipefail

CI_DIR="$(cd "$(dirname "$0")/.." && pwd)"
REPO="${WITFORGE_REPO:-asamarts/witforge}"
GH_USER="${WITFORGE_GH_USER:-asamarts}"
NAME=witforge-runner
IMAGE=localhost/witforge-runner:latest
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/containers/systemd"
export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"

private="$(GH_TOKEN="$(gh auth token --user "${GH_USER}")" \
    gh api "repos/${REPO}" --jq .private)"
if [[ "${private}" != true ]]; then
    echo "${REPO} is not a private repository; a self-hosted runner must never serve a public" \
        "one (nothing was changed)" >&2
    exit 1
fi

echo "==> Building ${IMAGE}"
podman build -t "${IMAGE}" -f "${CI_DIR}/Containerfile" "${CI_DIR}"

podman volume create --ignore "${NAME}-config" >/dev/null
podman volume create --ignore "${NAME}-cargo" >/dev/null

# A registration survives container recreates and image rebuilds, so register only when the
# config volume holds none.
if ! podman run --rm -v "${NAME}-config:/home/runner/_config" --entrypoint test "${IMAGE}" \
    -f /home/runner/_config/.runner; then
    echo "==> Registering ${NAME} with ${REPO}"
    # A one-hour registration token, passed through the environment rather than argv.
    RUNNER_TOKEN="$(GH_TOKEN="$(gh auth token --user "${GH_USER}")" \
        gh api -X POST "repos/${REPO}/actions/runners/registration-token" --jq .token)"
    export RUNNER_TOKEN
    podman run --rm \
        -v "${NAME}-config:/home/runner/_config" \
        -e GITHUB_REPO_URL="https://github.com/${REPO}" \
        -e RUNNER_NAME="${NAME}" \
        -e RUNNER_TOKEN \
        "${IMAGE}" register
    unset RUNNER_TOKEN
fi

echo "==> Installing ${UNIT_DIR}/${NAME}.container"
mkdir -p "${UNIT_DIR}"
cat > "${UNIT_DIR}/${NAME}.container" <<UNIT
# Generated by ci/runner/setup.sh in ${REPO}; change that script, not this file.
[Unit]
Description=witforge self-hosted GitHub Actions runner
Documentation=https://github.com/${REPO}/blob/main/ci/README.md
After=network-online.target
Wants=network-online.target
# Give up after repeated failures (for example a registration deleted on the server) instead of
# restarting forever.
StartLimitIntervalSec=600
StartLimitBurst=5

[Container]
ContainerName=${NAME}
Image=${IMAGE}
# A small share of a shared host; witforge's CI builds in well under a minute.
PodmanArgs=--cpus=4 --memory=8g
Volume=${NAME}-config:/home/runner/_config
Volume=${NAME}-cargo:/usr/local/cargo/registry
Environment=GITHUB_REPO_URL=https://github.com/${REPO}
Environment=RUNNER_NAME=${NAME}

[Service]
Restart=always
RestartSec=30s

[Install]
WantedBy=default.target
UNIT

# Quadlet creates a fresh container on every start, so a restart also picks up a rebuilt image.
systemctl --user daemon-reload
systemctl --user restart "${NAME}.service"
echo "==> Started ${NAME}.service; follow it with: journalctl --user -fu ${NAME}"
