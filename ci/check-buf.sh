#!/usr/bin/env bash
# Optional protobuf compatibility check. The lockfile is the normative wire check; `buf
# breaking` is an additional consumer-side safeguard.
#
# Generates the old schema from WIT_ROOT at BASE with BASE's published witforge binary, generates
# the current schema with the candidate binary, then runs `buf breaking` on the candidate against
# the historical output. Without `buf` it skips unless BUF_REQUIRED=1, where it fails.
#
# Usage: [WITFORGE=path/to/candidate] [BASE_WITFORGE=path/to/historical]
#        [BUF=path/to/buf] ci/check-buf.sh [WIT_ROOT] [BASE]
#   WIT_ROOT  WIT root relative to the repository root (default: the versions fixture)
#   BASE      released tag to compare against (default: v0.4.1)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WIT_ROOT="${1:-crates/witforge/tests/fixtures/versions/wit}"
BASE="${2:-v0.4.1}"
BUF="${BUF:-buf}"

if ! command -v "${BUF}" >/dev/null 2>&1; then
    if [[ "${BUF_REQUIRED:-}" == 1 ]]; then
        echo "buf is not installed (BUF=${BUF})" >&2
        exit 1
    fi
    echo "buf is not installed; skipping optional protobuf breaking check (BUF_REQUIRED=1 fails)"
    exit 0
fi

cd "${ROOT}"
base_commit="$(git rev-parse --verify "${BASE}^{commit}")"
scratch="${TMPDIR:-${HOME}/.tmp}"
mkdir -p "${scratch}"
TMP="$(mktemp -d "${scratch}/witforge-buf.XXXXXX")"
trap 'rm -rf "${TMP}"' EXIT
if [[ -n "${WITFORGE:-}" ]]; then
    CANDIDATE_RUN=("${WITFORGE}")
else
    CANDIDATE_RUN=(cargo run --quiet --manifest-path "${ROOT}/crates/witforge-cli/Cargo.toml" --)
fi

if ! git cat-file -e "${base_commit}:${WIT_ROOT}" 2>/dev/null; then
    echo "${WIT_ROOT} does not exist at ${BASE}; nothing to compare"
    exit 0
fi
if [[ -n "${BASE_WITFORGE:-}" ]]; then
    BASELINE_RUN=("${BASE_WITFORGE}")
elif [[ "${BASE}" =~ ^v([0-9]+\.[0-9]+\.[0-9]+)$ ]]; then
    base_version="${BASH_REMATCH[1]}"
    install_root="${WITFORGE_BASE_CACHE:-${scratch}/witforge-baselines}/${base_version}"
    baseline="${install_root}/bin/witforge"
    if [[ ! -x "${baseline}" ]]; then
        cargo install --locked witforge-cli --version "${base_version}" --root "${install_root}"
    fi
    BASELINE_RUN=("${baseline}")
else
    echo "BASE_WITFORGE is required when BASE is not a release tag: ${BASE}" >&2
    exit 1
fi
mkdir -p "${TMP}/base"
git archive "${base_commit}" -- "${WIT_ROOT}" | tar -x -C "${TMP}/base"
"${BASELINE_RUN[@]}" proto "${TMP}/base/${WIT_ROOT}" --out "${TMP}/old"
"${CANDIDATE_RUN[@]}" proto "${WIT_ROOT}" --out "${TMP}/new"
"${BUF}" breaking "${TMP}/new" --against "${TMP}/old"
echo "buf breaking: candidate is compatible with ${WIT_ROOT} generated by ${BASE} (${base_commit:0:12})"
