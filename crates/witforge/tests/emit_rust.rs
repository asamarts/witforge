#[test]
fn generated_files_recognise_the_header_without_reading_files_as_text() {
    use witforge::emit::output::GeneratedFiles;
    let out = std::env::temp_dir().join(format!("witforge-binary-output-{}", std::process::id()));
    let _ = fs::remove_dir_all(&out);
    fs::create_dir_all(&out).unwrap();
    // A file without the header that is not UTF-8, such as a `.DS_Store`, is ignored.
    let binary = out.join(".DS_Store");
    let bytes = [
        0x00, 0x00, 0x00, 0x01, 0x42, 0x75, 0x64, 0x31, 0xff, 0xfe, 0x80,
    ];
    fs::write(&binary, bytes).unwrap();
    // A stale generated file is recognised by its header even when its body is not UTF-8.
    let stale = out.join("stale.rs");
    let mut stale_bytes = format!("{}\n", rust::HEADER).into_bytes();
    stale_bytes.extend([0xff, 0xfe]);
    fs::write(&stale, &stale_bytes).unwrap();

    let mut files = GeneratedFiles::new(rust::HEADER);
    files
        .insert("mod.rs", format!("{}\n", rust::HEADER))
        .unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 2, "{messages:?}");
    assert_eq!(
        messages[0].status,
        witforge::emit::output::GeneratedFileStatus::Extra
    );
    assert!(messages[0].path.ends_with("stale.rs"), "{messages:?}");
    assert_eq!(
        messages[1].status,
        witforge::emit::output::GeneratedFileStatus::Missing
    );

    files.write(&out).unwrap();
    assert!(!stale.exists());
    assert_eq!(fs::read(&binary).unwrap(), bytes);
    assert_eq!(files.check(&out).unwrap(), []);

    // An expected file with binary content is changed output, not an I/O error.
    let mut changed = format!("{}\n", rust::HEADER).into_bytes();
    changed.extend([0xff, 0xfe]);
    fs::write(out.join("mod.rs"), &changed).unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 1, "{messages:?}");
    assert!(matches!(
        messages[0].status,
        witforge::emit::output::GeneratedFileStatus::Changed { .. }
    ));
    // Without the header it is a file generation refuses to overwrite, so --check reports that
    // rather than output that generation would fix.
    fs::write(out.join("mod.rs"), [0xff, 0xfe]).unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 1, "{messages:?}");
    assert_eq!(
        messages[0].status,
        witforge::emit::output::GeneratedFileStatus::Unowned
    );
    fs::remove_dir_all(&out).unwrap();
}

#[test]
fn check_reports_what_generation_refuses_without_reading_special_files() {
    use witforge::emit::output::{GeneratedFileStatus, GeneratedFiles};
    let out = std::env::temp_dir().join(format!("witforge-check-preflight-{}", std::process::id()));
    let _ = fs::remove_dir_all(&out);
    fs::create_dir_all(&out).unwrap();
    let mut files = GeneratedFiles::new(rust::HEADER);
    files
        .insert("mod.rs", format!("{}\n", rust::HEADER))
        .unwrap();

    // A directory where an expected file goes is drift that generation refuses to fix, not an
    // I/O error.
    fs::create_dir(out.join("mod.rs")).unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 1, "{messages:?}");
    assert_eq!(messages[0].status, GeneratedFileStatus::NotRegular);
    assert!(files.write(&out).is_err());
    fs::remove_dir(out.join("mod.rs")).unwrap();

    // A FIFO is reported without being opened, which would block until a writer appeared.
    #[cfg(unix)]
    {
        let fifo = out.join("mod.rs");
        let status = Command::new("mkfifo").arg(&fifo).status().unwrap();
        assert!(status.success());
        let (sender, receiver) = std::sync::mpsc::channel();
        let checked = files.clone();
        let root = out.clone();
        std::thread::spawn(move || {
            let _ = sender.send(checked.check(&root).map_err(|err| format!("{err:#}")));
        });
        let messages = receiver
            .recv_timeout(std::time::Duration::from_secs(20))
            .expect("--check blocked on a FIFO")
            .unwrap();
        assert_eq!(messages.len(), 1, "{messages:?}");
        assert_eq!(messages[0].status, GeneratedFileStatus::NotRegular);
        fs::remove_file(&fifo).unwrap();
    }
    fs::remove_dir_all(&out).unwrap();
}

