#[test]
fn generation_never_overwrites_unowned_files_or_writes_through_symlinks() {
    let root = fixture("versions/wit");
    let base = std::env::temp_dir().join(format!("witforge-ownership-{}", std::process::id()));
    let _ = fs::remove_dir_all(&base);
    let out = base.join("out");
    rust::generate(&root, &out).unwrap();
    // A stale generated file shows whether a refused run changed anything.
    let stale = out.join("stale.rs");
    fs::write(&stale, format!("{}\n", rust::HEADER)).unwrap();

    // A hand-written file where an expected file goes is refused, and nothing is changed.
    fs::write(out.join("mod.rs"), "// hand-written\n").unwrap();
    let message = format!("{:#}", rust::generate(&root, &out).unwrap_err());
    assert!(message.contains("refusing to overwrite"), "{message}");
    assert!(message.contains("mod.rs"), "{message}");
    assert_eq!(
        fs::read_to_string(out.join("mod.rs")).unwrap(),
        "// hand-written\n"
    );
    assert!(stale.exists());
    fs::remove_file(out.join("mod.rs")).unwrap();

    // So is a directory.
    fs::create_dir(out.join("mod.rs")).unwrap();
    let message = format!("{:#}", rust::generate(&root, &out).unwrap_err());
    assert!(message.contains("not a regular file"), "{message}");
    fs::remove_dir(out.join("mod.rs")).unwrap();

    #[cfg(unix)]
    {
        // A symlink is refused even when it points at a generated file, so no write can land
        // outside the output root (here, in a WIT version directory).
        let victim = base.join("contract.wit");
        fs::write(&victim, "package a:b@0.1.0;\n").unwrap();
        fs::remove_file(out.join("v0_2.rs")).unwrap();
        std::os::unix::fs::symlink(&victim, out.join("v0_2.rs")).unwrap();
        let message = format!("{:#}", rust::generate(&root, &out).unwrap_err());
        assert!(message.contains("symlink"), "{message}");
        assert_eq!(fs::read_to_string(&victim).unwrap(), "package a:b@0.1.0;\n");
        let messages = rust::check(&root, &out).unwrap();
        assert!(
            messages.iter().any(|finding| {
                finding.status == witforge::emit::output::GeneratedFileStatus::Symlink
            }),
            "{messages:?}"
        );
        fs::remove_file(out.join("v0_2.rs")).unwrap();
    }

    rust::generate(&root, &out).unwrap();
    assert!(!stale.exists());
    assert_eq!(rust::check(&root, &out).unwrap(), []);
    fs::remove_dir_all(&base).unwrap();
}

#[test]
fn version_directories_refuse_symlinks_and_non_canonical_names() {
    let base = std::env::temp_dir().join(format!("witforge-version-names-{}", std::process::id()));
    let _ = fs::remove_dir_all(&base);
    let root = base.join("wit");
    let store = base.join("store");
    for (version, destination) in [("v0.1", root.join("v0.1")), ("v0.2", store.join("v0.2"))] {
        let source = fixture("versions/wit").join(version);
        fs::create_dir_all(&destination).unwrap();
        for name in ["contract.wit", "wire.lock"] {
            fs::copy(source.join(name), destination.join(name)).unwrap();
        }
    }
    fs::copy(
        fixture("versions/wit").join("released"),
        root.join("released"),
    )
    .unwrap();
    #[cfg(unix)]
    {
        // A symlinked version directory is refused, not followed: a released version must not
        // change through its link's target. Nothing is written, even when the output root is
        // that link (whose target is outside the WIT root).
        std::os::unix::fs::symlink(store.join("v0.2"), root.join("v0.2")).unwrap();
        let message = format!("{:#}", rust::plan(&root).unwrap_err());
        assert!(message.contains("is a symlink"), "{message}");
        let message = format!(
            "{:#}",
            rust::generate(&root, &root.join("v0.2")).unwrap_err()
        );
        assert!(message.contains("is a symlink"), "{message}");
        let mut names: Vec<_> = fs::read_dir(store.join("v0.2"))
            .unwrap()
            .map(|entry| entry.unwrap().file_name())
            .collect();
        names.sort();
        assert_eq!(names, ["contract.wit", "wire.lock"]);
        fs::remove_file(root.join("v0.2")).unwrap();
    }
    // Unrelated names that do not start with `v`/`V` + digit are ignored; near-miss version names
    // and numbers spelled with a sign or leading zeros are refused instead of silently changing
    // which versions are generated.
    fs::create_dir_all(root.join("vendor")).unwrap();
    fs::write(root.join("versions.md"), "# notes\n").unwrap();
    fs::write(root.join(".hidden"), "").unwrap();
    rust::plan(&root).unwrap();
    fs::create_dir_all(root.join("v0.1-old")).unwrap();
    let near_miss = format!("{:#}", rust::plan(&root).unwrap_err());
    assert!(near_miss.contains("v0.1-old"), "{near_miss}");
    fs::remove_dir_all(root.join("v0.1-old")).unwrap();
    for name in ["v00.2", "v0.02", "v+0.2", "V0.2"] {
        fs::rename(store.join("v0.2"), root.join(name)).unwrap();
        let message = format!("{:#}", rust::plan(&root).unwrap_err());
        assert!(
            message.contains("must be spelled `v0.2`"),
            "{name}: {message}"
        );
        fs::rename(root.join(name), store.join("v0.2")).unwrap();
    }
    fs::remove_dir_all(&base).unwrap();
}

#[cfg(unix)]
#[test]
fn generation_leaves_previous_output_when_a_write_fails() {
    use std::os::unix::fs::PermissionsExt;

    let root = fixture("versions/wit");
    let base = std::env::temp_dir().join(format!("witforge-write-failure-{}", std::process::id()));
    let _ = fs::remove_dir_all(&base);
    let out = base.join("out");
    rust::generate(&root, &out).unwrap();
    // Perturb an owned generated file so regeneration must attempt a write instead of skipping
    // unchanged output.
    let mut perturbed = fs::read_to_string(out.join("mod.rs")).unwrap();
    perturbed.push_str("// drifted\n");
    fs::write(out.join("mod.rs"), &perturbed).unwrap();
    let before = fs::read(out.join("mod.rs")).unwrap();

    let mut permissions = fs::metadata(&out).unwrap().permissions();
    permissions.set_mode(0o555);
    fs::set_permissions(&out, permissions.clone()).unwrap();
    let result = rust::generate(&root, &out);
    permissions.set_mode(0o755);
    fs::set_permissions(&out, permissions).unwrap();

    assert!(
        result.is_err(),
        "a read-only output root must fail generation"
    );
    assert_eq!(fs::read(out.join("mod.rs")).unwrap(), before);
    let temporaries = fs::read_dir(&out)
        .unwrap()
        .flatten()
        .filter(|entry| entry.file_name().to_string_lossy().ends_with(".tmp"))
        .count();
    assert_eq!(temporaries, 0);
    fs::remove_dir_all(&base).unwrap();
}

