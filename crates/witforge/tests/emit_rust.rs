#[test]
fn generates_layout_check_drift_and_ownership() {
    let root = fixture("versions/wit");
    let out = std::env::temp_dir().join(format!("witforge-rust-layout-{}", std::process::id()));
    let _ = fs::remove_dir_all(&out);
    let unrelated = out.join("README.txt");
    fs::create_dir_all(&out).unwrap();
    fs::write(&unrelated, "keep me\n").unwrap();

    rust::generate(&root, &out).unwrap();
    for name in ["mod.rs", "v0_1.rs", "v0_2.rs"] {
        assert!(out.join(name).is_file(), "{name}");
    }
    let mod_file = fs::read_to_string(out.join("mod.rs")).unwrap();
    assert!(mod_file.contains("// source: example:evolve"));
    assert!(mod_file.contains("pub mod v0_1;"));
    assert!(mod_file.contains("pub mod v0_2;"));
    assert!(!mod_file.contains('\r'));
    assert_eq!(fs::read_to_string(&unrelated).unwrap(), "keep me\n");
    assert_eq!(rust::check(&root, &out).unwrap(), Vec::<String>::new());

    fs::write(out.join("v0_1.rs"), "changed\n").unwrap();
    let messages = rust::check(&root, &out).unwrap();
    assert!(
        messages
            .iter()
            .any(|message| message.contains("changed generated")),
        "{messages:?}"
    );

    let extra = out.join("stale.rs");
    fs::write(&extra, "// @generated by witforge; do not edit.\n").unwrap();
    let messages = rust::check(&root, &out).unwrap();
    assert!(
        messages
            .iter()
            .any(|message| message.contains("extra generated")),
        "{messages:?}"
    );

    fs::remove_file(out.join("v0_2.rs")).unwrap();
    let messages = rust::check(&root, &out).unwrap();
    assert!(
        messages
            .iter()
            .any(|message| message.contains("missing generated")),
        "{messages:?}"
    );

    rust::generate(&root, &out).unwrap();
    assert!(!extra.exists());
    assert_eq!(fs::read_to_string(&unrelated).unwrap(), "keep me\n");
    assert_eq!(rust::check(&root, &out).unwrap(), Vec::<String>::new());

    let status = Command::new("rustc")
        .args([
            "--edition=2024",
            "--crate-type=lib",
            "--emit=metadata",
            "-o",
        ])
        .arg(out.join("tree.rmeta"))
        .arg(out.join("mod.rs"))
        .status()
        .unwrap();
    assert!(status.success(), "generated tree did not compile");

    assert!(rust::generate(&root, &root.join("out")).is_err());
    fs::remove_dir_all(&out).unwrap();
}

#[test]
fn generated_file_names_reject_dots_and_separators() {
    use witforge::emit::output::GeneratedFiles;
    let mut files = GeneratedFiles::new(rust::HEADER);
    assert!(files.insert(".", "x").is_err());
    assert!(files.insert("..", "x").is_err());
    assert!(files.insert("dir/file.rs", "x").is_err());
    files.insert("ok.rs", "x").unwrap();
}

#[test]
fn generated_files_recognise_the_header_without_reading_files_as_text() {
    use witforge::emit::output::GeneratedFiles;
    let out = std::env::temp_dir().join(format!("witforge-binary-output-{}", std::process::id()));
    let _ = fs::remove_dir_all(&out);
    fs::create_dir_all(&out).unwrap();
    // A file without the header that is not UTF-8, such as a `.DS_Store`, is ignored.
    let binary = out.join(".DS_Store");
    let bytes = [
        0x00, 0x00, 0x00, 0x01, 0x42, 0x75, 0x64, 0x31, 0xff, 0xfe, 0x80,
    ];
    fs::write(&binary, bytes).unwrap();
    // A stale generated file is recognised by its header even when its body is not UTF-8.
    let stale = out.join("stale.rs");
    let mut stale_bytes = format!("{}\n", rust::HEADER).into_bytes();
    stale_bytes.extend([0xff, 0xfe]);
    fs::write(&stale, &stale_bytes).unwrap();

    let mut files = GeneratedFiles::new(rust::HEADER);
    files
        .insert("mod.rs", format!("{}\n", rust::HEADER))
        .unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 2, "{messages:?}");
    assert!(
        messages[0].starts_with("extra generated file"),
        "{messages:?}"
    );
    assert!(messages[0].contains("stale.rs"), "{messages:?}");
    assert!(
        messages[1].starts_with("missing generated file"),
        "{messages:?}"
    );

    files.write(&out).unwrap();
    assert!(!stale.exists());
    assert_eq!(fs::read(&binary).unwrap(), bytes);
    assert_eq!(files.check(&out).unwrap(), Vec::<String>::new());

    // An expected file with binary content is changed output, not an I/O error.
    fs::write(out.join("mod.rs"), [0xff, 0xfe]).unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 1, "{messages:?}");
    assert!(
        messages[0].starts_with("changed generated file"),
        "{messages:?}"
    );
    fs::remove_dir_all(&out).unwrap();
}
