#[test]
fn root_module_and_trait_collisions_are_rejected() {
    let dir = std::env::temp_dir().join(format!("witforge-emit-root-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    fs::write(
        dir.join("contract.wit"),
        "package example:upper@0.1.0;\ninterface FOO { record value { x: u32 } }\n",
    )
    .unwrap();
    let model = model::build(&load(&dir).unwrap()).unwrap();
    let error = rust::emit_version(&model).unwrap_err();
    assert!(format!("{error:#}").contains("FOO"));
    fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn collisions_name_both_interfaces() {
    let dir = std::env::temp_dir().join(format!("witforge-emit-collision-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    fs::write(
        dir.join("contract.wit"),
        "package example:collision@0.1.0;\ninterface analyzer { record analyzer { x: u32 } }\n",
    )
    .unwrap();
    let model = model::build(&load(&dir).unwrap()).unwrap();
    let error = rust::emit_version(&model).unwrap_err();
    let message = format!("{error:#}");
    assert!(message.contains("Analyzer"), "{message}");
    assert!(message.contains("analyzer"), "{message}");
    fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn generates_layout_check_drift_and_ownership() {
    let root = fixture("versions/wit");
    let out = std::env::temp_dir().join(format!("witforge-rust-layout-{}", std::process::id()));
    let _ = fs::remove_dir_all(&out);
    let unrelated = out.join("README.txt");
    fs::create_dir_all(&out).unwrap();
    fs::write(&unrelated, "keep me\n").unwrap();

    rust::generate(&root, &out).unwrap();
    for name in ["mod.rs", "v0_1.rs", "v0_2.rs"] {
        assert!(out.join(name).is_file(), "{name}");
    }
    let mod_file = fs::read_to_string(out.join("mod.rs")).unwrap();
    assert!(mod_file.contains("// source: example:evolve"));
    assert!(mod_file.contains("pub mod v0_1;"));
    assert!(mod_file.contains("pub mod v0_2;"));
    assert!(!mod_file.contains('\r'));
    assert_eq!(fs::read_to_string(&unrelated).unwrap(), "keep me\n");
    assert_eq!(rust::check(&root, &out).unwrap(), Vec::<String>::new());

    fs::write(out.join("v0_1.rs"), "changed\n").unwrap();
    let messages = rust::check(&root, &out).unwrap();
    assert!(
        messages
            .iter()
            .any(|message| message.contains("changed generated")),
        "{messages:?}"
    );

    let extra = out.join("stale.rs");
    fs::write(&extra, "// @generated by witforge; do not edit.\n").unwrap();
    let messages = rust::check(&root, &out).unwrap();
    assert!(
        messages
            .iter()
            .any(|message| message.contains("extra generated")),
        "{messages:?}"
    );

    fs::remove_file(out.join("v0_2.rs")).unwrap();
    let messages = rust::check(&root, &out).unwrap();
    assert!(
        messages
            .iter()
            .any(|message| message.contains("missing generated")),
        "{messages:?}"
    );

    rust::generate(&root, &out).unwrap();
    assert!(!extra.exists());
    assert_eq!(fs::read_to_string(&unrelated).unwrap(), "keep me\n");
    assert_eq!(rust::check(&root, &out).unwrap(), Vec::<String>::new());

    let status = Command::new("rustc")
        .args([
            "--edition=2024",
            "--crate-type=lib",
            "--emit=metadata",
            "-o",
        ])
        .arg(out.join("tree.rmeta"))
        .arg(out.join("mod.rs"))
        .status()
        .unwrap();
    assert!(status.success(), "generated tree did not compile");

    assert!(rust::generate(&root, &root.join("out")).is_err());
    fs::remove_dir_all(&out).unwrap();
}
