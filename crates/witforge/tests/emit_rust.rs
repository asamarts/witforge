//! Rust emitter tests: naming, docs, aliases, traits, collisions, and compilation.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use witforge::emit::rust;
use witforge::load;
use witforge::model;

fn fixture(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures")
        .join(name)
}

fn build(name: &str) -> model::Model {
    model::build(&load(&fixture(name)).unwrap()).unwrap()
}

#[test]
fn emits_version_modules_types_traits_docs_and_aliases() {
    let model = build("ok");
    let code = rust::emit_version(&model).unwrap();
    assert_eq!(rust::version_module_name(&model), "v0_1");
    assert!(
        code.starts_with(
            "// @generated by witforge; do not edit.\n// source: example:plugin@0.1.0\n"
        )
    );
    assert!(code.contains("pub mod types {"), "{code}");
    assert!(code.contains("pub mod analyzer {"), "{code}");
    assert!(code.contains("/// Shared contract types."), "{code}");
    assert!(code.contains("/// A byte range in a resource."), "{code}");
    assert!(code.contains("pub struct Span {"), "{code}");
    assert!(code.contains("pub struct Finding {"), "{code}");
    assert!(code.contains("pub enum Applicability {"), "{code}");
    assert!(code.contains("pub enum Edit {"), "{code}");
    assert!(code.contains("pub struct Caps {"), "{code}");
    assert!(
        code.contains("pub type Finding = super::types::Finding;"),
        "{code}"
    );
    assert!(code.contains("pub trait Analyzer {"), "{code}");
    assert!(
        code.contains(
            "fn analyze(&self, path: ::std::string::String, bytes: ::std::vec::Vec<u8>) -> ::std::result::Result<::std::vec::Vec<Finding>, ::std::string::String>;"
        ),
        "{code}"
    );
    assert!(code.contains("pub use analyzer::Analyzer;"), "{code}");
    assert!(code.ends_with("pub use analyzer::Analyzer;\n"), "{code}");
}

#[test]
fn escapes_keywords_and_compiles_generated_code() {
    let model = build("model");
    let code = rust::emit_version(&model).unwrap();
    assert!(code.contains("pub mod r#type {"), "{code}");
    assert!(code.contains("pub struct Where {"), "{code}");
    assert!(code.contains("pub self_: u32,"), "{code}");
    assert!(
        code.contains("fn func(&self, self_: u32) -> Where;"),
        "{code}"
    );

    let dir = std::env::temp_dir().join(format!("witforge-emit-rust-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    let source = dir.join("generated.rs");
    let output = dir.join("generated.rmeta");
    fs::write(&source, code).unwrap();
    let status = Command::new("rustc")
        .args([
            "--edition=2024",
            "--crate-type=lib",
            "--emit=metadata",
            "-o",
        ])
        .arg(&output)
        .arg(&source)
        .status()
        .unwrap();
    assert!(status.success(), "generated Rust did not compile");
    fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn emits_every_rust_mapping_row_as_a_golden() {
    let model = model::build(&load(&fixture("emit/rust/all")).unwrap()).unwrap();
    let actual = rust::emit_version(&model).unwrap();
    let expected = fs::read_to_string(fixture("emit/rust/all/expected.rs")).unwrap();
    assert_eq!(actual, expected);

    let dir = std::env::temp_dir().join(format!("witforge-emit-golden-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    let source = dir.join("generated.rs");
    let output = dir.join("generated.rmeta");
    fs::write(&source, expected).unwrap();
    let status = Command::new("rustc")
        .args([
            "--edition=2024",
            "--crate-type=lib",
            "--emit=metadata",
            "-o",
        ])
        .arg(&output)
        .arg(&source)
        .status()
        .unwrap();
    assert!(status.success(), "golden Rust did not compile");
    fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn root_module_and_trait_collisions_are_rejected() {
    let dir = std::env::temp_dir().join(format!("witforge-emit-root-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    fs::write(
        dir.join("contract.wit"),
        "package example:upper@0.1.0;\ninterface FOO { record value { x: u32 } }\n",
    )
    .unwrap();
    let model = model::build(&load(&dir).unwrap()).unwrap();
    let error = rust::emit_version(&model).unwrap_err();
    assert!(format!("{error:#}").contains("FOO"));
    fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn collisions_name_both_interfaces() {
    let dir = std::env::temp_dir().join(format!("witforge-emit-collision-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    fs::write(
        dir.join("contract.wit"),
        "package example:collision@0.1.0;\ninterface analyzer { record analyzer { x: u32 } }\n",
    )
    .unwrap();
    let model = model::build(&load(&dir).unwrap()).unwrap();
    let error = rust::emit_version(&model).unwrap_err();
    let message = format!("{error:#}");
    assert!(message.contains("Analyzer"), "{message}");
    assert!(message.contains("analyzer"), "{message}");
    fs::remove_dir_all(&dir).unwrap();
}
