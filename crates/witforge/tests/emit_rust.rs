#[test]
fn generated_files_recognise_the_header_without_reading_files_as_text() {
    use witforge::emit::output::GeneratedFiles;
    let out = std::env::temp_dir().join(format!("witforge-binary-output-{}", std::process::id()));
    let _ = fs::remove_dir_all(&out);
    fs::create_dir_all(&out).unwrap();
    // A file without the header that is not UTF-8, such as a `.DS_Store`, is ignored.
    let binary = out.join(".DS_Store");
    let bytes = [
        0x00, 0x00, 0x00, 0x01, 0x42, 0x75, 0x64, 0x31, 0xff, 0xfe, 0x80,
    ];
    fs::write(&binary, bytes).unwrap();
    // A stale generated file is recognised by its header even when its body is not UTF-8.
    let stale = out.join("stale.rs");
    let mut stale_bytes = format!("{}\n", rust::HEADER).into_bytes();
    stale_bytes.extend([0xff, 0xfe]);
    fs::write(&stale, &stale_bytes).unwrap();

    let mut files = GeneratedFiles::new(rust::HEADER);
    files
        .insert("mod.rs", format!("{}\n", rust::HEADER))
        .unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 2, "{messages:?}");
    assert!(
        messages[0].starts_with("extra generated file"),
        "{messages:?}"
    );
    assert!(messages[0].contains("stale.rs"), "{messages:?}");
    assert!(
        messages[1].starts_with("missing generated file"),
        "{messages:?}"
    );

    files.write(&out).unwrap();
    assert!(!stale.exists());
    assert_eq!(fs::read(&binary).unwrap(), bytes);
    assert_eq!(files.check(&out).unwrap(), Vec::<String>::new());

    // An expected file with binary content is changed output, not an I/O error.
    let mut changed = format!("{}\n", rust::HEADER).into_bytes();
    changed.extend([0xff, 0xfe]);
    fs::write(out.join("mod.rs"), &changed).unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 1, "{messages:?}");
    assert!(
        messages[0].starts_with("changed generated file"),
        "{messages:?}"
    );
    // Without the header it is a file generation refuses to overwrite, so --check reports that
    // rather than output that generation would fix.
    fs::write(out.join("mod.rs"), [0xff, 0xfe]).unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 1, "{messages:?}");
    assert!(messages[0].contains("refuses to overwrite"), "{messages:?}");
    fs::remove_dir_all(&out).unwrap();
}

#[test]
fn check_reports_what_generation_refuses_without_reading_special_files() {
    use witforge::emit::output::GeneratedFiles;
    let out = std::env::temp_dir().join(format!("witforge-check-preflight-{}", std::process::id()));
    let _ = fs::remove_dir_all(&out);
    fs::create_dir_all(&out).unwrap();
    let mut files = GeneratedFiles::new(rust::HEADER);
    files
        .insert("mod.rs", format!("{}\n", rust::HEADER))
        .unwrap();

    // A directory where an expected file goes is drift that generation refuses to fix, not an
    // I/O error.
    fs::create_dir(out.join("mod.rs")).unwrap();
    let messages = files.check(&out).unwrap();
    assert_eq!(messages.len(), 1, "{messages:?}");
    assert!(messages[0].contains("not a regular file"), "{messages:?}");
    assert!(files.write(&out).is_err());
    fs::remove_dir(out.join("mod.rs")).unwrap();

    // A FIFO is reported without being opened, which would block until a writer appeared.
    #[cfg(unix)]
    {
        let fifo = out.join("mod.rs");
        let status = Command::new("mkfifo").arg(&fifo).status().unwrap();
        assert!(status.success());
        let (sender, receiver) = std::sync::mpsc::channel();
        let checked = files.clone();
        let root = out.clone();
        std::thread::spawn(move || {
            let _ = sender.send(checked.check(&root).map_err(|err| format!("{err:#}")));
        });
        let messages = receiver
            .recv_timeout(std::time::Duration::from_secs(20))
            .expect("--check blocked on a FIFO")
            .unwrap();
        assert_eq!(messages.len(), 1, "{messages:?}");
        assert!(messages[0].contains("not a regular file"), "{messages:?}");
        fs::remove_file(&fifo).unwrap();
    }
    fs::remove_dir_all(&out).unwrap();
}

#[test]
fn output_root_guard_resolves_parent_components() {
    use witforge::emit::output::ensure_outside_wit_root;
    let base = std::env::temp_dir().join(format!("witforge-out-guard-{}", std::process::id()));
    let _ = fs::remove_dir_all(&base);
    let root = base.join("wit");
    fs::create_dir_all(root.join("v0.1")).unwrap();
    fs::create_dir_all(base.join("existing")).unwrap();

    for inside in [
        root.clone(),
        base.clone(),
        root.join("gen"),
        root.join("v0.1/gen"),
        root.join("v0.1/deps/shared"),
        base.join("missing/../wit/gen"),
        base.join("missing/../out"),
        base.join("existing/../wit/gen"),
        base.join("existing/../wit"),
        root.join("gen/../../wit/v0.1"),
        root.join("gen/../../out"),
        base.join("missing/../existing/../wit/./gen"),
    ] {
        assert!(
            ensure_outside_wit_root(&root, &inside).is_err(),
            "accepted {}",
            inside.display()
        );
    }
    for outside in [
        base.join("out"),
        base.join("existing/out"),
        base.join("existing/../out"),
        root.join("../out"),
    ] {
        ensure_outside_wit_root(&root, &outside).unwrap();
    }
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(&root, base.join("link")).unwrap();
        std::os::unix::fs::symlink(root.join("v0.1"), base.join("outlink")).unwrap();
        std::os::unix::fs::symlink(root.join("newdir"), base.join("dangling")).unwrap();
        for bad in [
            base.join("link/gen"),
            base.join("missing/../link/v0.1"),
            base.join("existing/../link/v0.1"),
            base.join("outlink"),
            base.join("dangling"),
            base.join("dangling/sub"),
        ] {
            assert!(
                ensure_outside_wit_root(&root, &bad).is_err(),
                "accepted symlinked {}",
                bad.display()
            );
        }
        assert!(ensure_outside_wit_root(&base.join("link"), &root.join("gen")).is_err());
    }
    fs::remove_dir_all(&base).unwrap();
}

#[test]
fn every_generator_requires_each_minor_to_continue_the_previous_lockfile() {
    use witforge::emit::{glue, proto};
    use witforge::is_contract_error;
    use witforge::lock::{LockMode, WireLock};

    let root = std::env::temp_dir().join(format!("witforge-continuity-{}", std::process::id()));
    let _ = fs::remove_dir_all(&root);
    for version in ["v0.1", "v0.2"] {
        let source = fixture("versions/wit").join(version);
        fs::create_dir_all(root.join(version)).unwrap();
        for name in ["contract.wit", "wire.lock"] {
            fs::copy(source.join(name), root.join(version).join(name)).unwrap();
        }
    }
    // `v0.1` is the released legacy fixture whose lockfile predates the order section; keep its
    // manifest so the copied root treats it as released.
    fs::copy(
        fixture("versions/wit").join("released"),
        root.join("released"),
    )
    .unwrap();
    let v03 = root.join("v0.3");
    fs::create_dir_all(&v03).unwrap();
    let source = fs::read_to_string(root.join("v0.2/contract.wit")).unwrap();
    fs::write(v03.join("contract.wit"), source.replace("@0.2.0", "@0.3.0")).unwrap();
    // A lockfile started fresh instead of from a copy of v0.2's: current, but renumbered.
    let members = model::members(&load(&v03).unwrap()).unwrap();
    let mut fresh = WireLock::default();
    fresh.reconcile_with(&members, LockMode::First).unwrap();
    fs::write(v03.join("wire.lock"), fresh.render()).unwrap();

    let errors = [
        rust::plan(&root).unwrap_err(),
        proto::plan(&root).unwrap_err(),
        glue::plan(&root, "crate::plain", "crate::proto").unwrap_err(),
    ];
    for error in errors {
        let message = format!("{error:#}");
        assert!(is_contract_error(&error), "{message}");
        assert!(message.contains("does not continue"), "{message}");
        assert!(message.contains("renumbered"), "{message}");
    }

    // Removing, retyping, or un-reserving a previous entry breaks continuity too.
    let v02_lock = fs::read_to_string(root.join("v0.2/wire.lock")).unwrap();
    for (from, to, expected) in [
        (
            "example:evolve/types/user.removed = 4 field bool reserved\n",
            "",
            "was removed",
        ),
        (
            "example:evolve/types/user.removed = 4 field bool reserved",
            "example:evolve/types/user.removed = 4 field u8 reserved",
            "changed kind or type",
        ),
        (
            "example:evolve/types/user.old-field = 2 field u32 reserved",
            "example:evolve/types/user.old-field = 2 field u32",
            "un-reserved",
        ),
    ] {
        let edited = v02_lock.replace(from, to);
        assert_ne!(edited, v02_lock);
        fs::write(v03.join("wire.lock"), edited).unwrap();
        let error = rust::plan(&root).unwrap_err();
        let message = format!("{error:#}");
        assert!(is_contract_error(&error), "{message}");
        assert!(message.contains(expected), "{message}");
    }

    // A copy of the previous lockfile continues it; a new major starts fresh.
    fs::write(v03.join("wire.lock"), &v02_lock).unwrap();
    rust::plan(&root).unwrap();
    let v10 = root.join("v1.0");
    fs::create_dir_all(&v10).unwrap();
    fs::write(v10.join("contract.wit"), source.replace("@0.2.0", "@1.0.0")).unwrap();
    fs::write(v10.join("wire.lock"), fresh.render()).unwrap();
    rust::plan(&root).unwrap();
    proto::plan(&root).unwrap();
    glue::plan(&root, "crate::plain", "crate::proto").unwrap();
    fs::remove_dir_all(&root).unwrap();
}

