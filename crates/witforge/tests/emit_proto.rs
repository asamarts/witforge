#[allow(clippy::too_many_lines)]
#[test]
fn opt_in_proto_file_options_validate_syntax_and_refuse_collisions_and_unused_overrides() {
    let assert_usage_err = |err: anyhow::Error, needle: &str| {
        assert!(
            !witforge::is_contract_error(&err),
            "expected usage error: {err:#}"
        );
        let diags = witforge::error_diagnostics(&err).expect("structured WF9001 diagnostic");
        assert_eq!(diags[0].code, witforge::diagnostic::codes::CLI_USAGE);
        let msg = format!("{err:#}");
        assert!(msg.contains(needle), "expected {needle:?} in {msg:?}");
    };
    let assert_collision_err = |err: anyhow::Error, needle: &str| {
        assert!(
            witforge::is_contract_error(&err),
            "expected contract error: {err:#}"
        );
        let diags = witforge::error_diagnostics(&err).expect("structured WF1003 diagnostic");
        assert_eq!(
            diags[0].code,
            witforge::diagnostic::codes::IDENTIFIER_COLLISION
        );
        let msg = format!("{err:#}");
        assert!(msg.contains(needle), "expected {needle:?} in {msg:?}");
    };

    // 1. Language-specific syntax & keyword validation refusals (WF9001).
    for (opts, needle) in [
        (
            proto::ProtoOptions::new().with_go_package_prefix(""),
            "must not be empty",
        ),
        (
            proto::ProtoOptions::new().with_go_package_prefix("example.com/a b"),
            "printable ASCII",
        ),
        (
            proto::ProtoOptions::new().with_go_package_prefix("example.com/\"bad\""),
            "printable ASCII",
        ),
        (
            proto::ProtoOptions::new().with_go_package_prefix("example.com/a\\b"),
            "printable ASCII",
        ),
        (
            proto::ProtoOptions::new().with_go_package_prefix("example.com/a\nb"),
            "printable ASCII",
        ),
        (
            proto::ProtoOptions::new().with_go_package_prefix("example.com/a;b;c"),
            "at most one `;`",
        ),
        (
            proto::ProtoOptions::new().with_go_package_prefix("/leading/slash"),
            "start/end with `/`",
        ),
        (
            proto::ProtoOptions::new().with_go_package_prefix("example.com/../up"),
            "empty or dot segment",
        ),
        (
            proto::ProtoOptions::new().with_go_package_prefix("example.com/pkg;func"),
            "valid Go package identifier",
        ),
        (
            proto::ProtoOptions::new().with_java_package_prefix("com.acme;alias"),
            "valid Java identifier",
        ),
        (
            proto::ProtoOptions::new().with_java_package_prefix("com.class.pkg"),
            "valid Java identifier",
        ),
        (
            proto::ProtoOptions::new().with_java_outer_classname("default"),
            "valid Java identifier",
        ),
        (
            proto::ProtoOptions::new().with_java_outer_classname("_"),
            "valid Java identifier",
        ),
        (
            proto::ProtoOptions::new().with_csharp_namespace_prefix("Acme;Alias"),
            "valid C# namespace identifier",
        ),
        (
            proto::ProtoOptions::new().with_csharp_namespace_prefix("Acme.namespace"),
            "valid C# namespace identifier",
        ),
        (
            proto::ProtoOptions::new().with_package_options(
                "bad..pkg",
                proto::ProtoPackageOptions::new().with_java_multiple_files(true),
            ),
            "valid protobuf package identifier",
        ),
        (
            proto::ProtoOptions::new().with_package_options(
                "1bad.pkg",
                proto::ProtoPackageOptions::new().with_java_multiple_files(true),
            ),
            "valid protobuf package identifier",
        ),
    ] {
        assert_usage_err(opts.validate().unwrap_err(), needle);
    }

    // 2. Unused `packages` override key refused (WF9001).
    let ok_model = model::build(&load(&fixture("ok")).unwrap()).unwrap();
    let ok_lock = lock_for(&ok_model);
    let unused = proto::ProtoOptions::new().with_package_options(
        "example.other.v0",
        proto::ProtoPackageOptions::new().with_java_multiple_files(true),
    );
    assert_usage_err(
        proto::emit_major_with_options(&ok_model, &ok_lock, &unused).unwrap_err(),
        "does not match any emitted proto package",
    );

    // 3. `java_outer_classname` collisions with generated message, enum, and synthesized wrapper.
    for colliding in ["Empty", "TypesSpan", "TypesApplicability"] {
        let opts = proto::ProtoOptions::new().with_java_outer_classname(colliding);
        assert_collision_err(
            proto::emit_major_with_options(&ok_model, &ok_lock, &opts).unwrap_err(),
            colliding,
        );
    }
    let wrap_contract = load_sources(vec![SourceFile::new(
        "contract.wit".into(),
        "package ex:wrap@0.1.0;\ninterface api { record r { items: option<list<string>> } }\n"
            .into(),
    )])
    .unwrap();
    let wrap_model = model::build(&wrap_contract).unwrap();
    let wrap_lock = lock_for(&wrap_model);
    assert_collision_err(
        proto::emit_major_with_options(
            &wrap_model,
            &wrap_lock,
            &proto::ProtoOptions::new().with_java_outer_classname("WitforgeListOfString"),
        )
        .unwrap_err(),
        "WitforgeListOfString",
    );

    // 4. Multi-file collisions: `go_package` with `;alias`, duplicate `go_package` import path,
    //    and duplicate `java_outer_classname` in the same effective Java package.
    let deps_root = fixture("deps/wit");
    assert_collision_err(
        proto::plan_with_options(
            &deps_root,
            None,
            &proto::ProtoOptions::new().with_go_package_prefix("example.com/shared;shared"),
        )
        .unwrap_err(),
        "includes an explicit `;alias`",
    );

    let deps_plan = proto::plan(&deps_root).unwrap();
    let dep_pkgs: Vec<String> = deps_plan
        .files()
        .values()
        .map(|text| {
            text.lines()
                .find_map(|line| line.strip_prefix("package ")?.strip_suffix(';'))
                .unwrap()
                .to_string()
        })
        .collect();
    assert!(dep_pkgs.len() >= 2, "{dep_pkgs:?}");
    let p0 = &dep_pkgs[0];
    let p1 = &dep_pkgs[1];

    let dup_go = proto::ProtoOptions::new()
        .with_package_options(
            p0.clone(),
            proto::ProtoPackageOptions::new().with_go_package("example.com/same;a"),
        )
        .with_package_options(
            p1.clone(),
            proto::ProtoPackageOptions::new().with_go_package("example.com/same;b"),
        );
    assert_collision_err(
        proto::plan_with_options(&deps_root, None, &dup_go).unwrap_err(),
        "option go_package import path `example.com/same` collides",
    );

    let dup_java_outer = proto::ProtoOptions::new()
        .with_java_outer_classname("SharedProto")
        .with_package_options(
            p0.clone(),
            proto::ProtoPackageOptions::new().with_java_package("com.acme.same"),
        )
        .with_package_options(
            p1.clone(),
            proto::ProtoPackageOptions::new().with_java_package("com.acme.same"),
        );
    assert_collision_err(
        proto::plan_with_options(&deps_root, None, &dup_java_outer).unwrap_err(),
        "option java_outer_classname `SharedProto` collides in Java package `com.acme.same`",
    );

    // Same `java_outer_classname` in DISTINCT effective Java packages succeeds cleanly.
    let distinct_java_outer = proto::ProtoOptions::new()
        .with_java_package_prefix("com.acme.distinct")
        .with_java_outer_classname("ContractProto");
    assert!(proto::plan_with_options(&deps_root, None, &distinct_java_outer).is_ok());
}
