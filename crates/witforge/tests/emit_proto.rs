//! Protobuf type/wrapper mapping tests.

use std::fs;
use std::path::{Path, PathBuf};

use witforge::emit::proto;
use witforge::load;
use witforge::lock::WireLock;
use witforge::model;

fn fixture(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures")
        .join(name)
}

fn lock_for(model: &model::Model) -> WireLock {
    let members = model.members().unwrap();
    let mut lock = WireLock::default();
    lock.reconcile(&members).unwrap();
    lock
}

#[test]
fn emits_interface_prefixed_types_fields_enums_flags_and_presence() {
    let model = model::build(&load(&fixture("ok")).unwrap()).unwrap();
    let schema = proto::emit_major(&model, &lock_for(&model)).unwrap();
    assert!(schema.starts_with(
        "// @generated by witforge; do not edit.\n// source: example:plugin@0.1.0\n\nsyntax = \"proto3\";\n\npackage example.plugin.v0;\n"
    ));
    assert!(schema.contains("message Empty {}"), "{schema}");
    assert!(
        schema.contains(
            "message TypesSpan {\n  optional uint64 start = 1;\n  optional uint64 end = 2;\n}"
        ),
        "{schema}"
    );
    assert!(schema.contains("enum TypesApplicability {"), "{schema}");
    assert!(
        schema.contains("TYPES_APPLICABILITY_UNSPECIFIED = 0;"),
        "{schema}"
    );
    assert!(schema.contains("TYPES_APPLICABILITY_SAFE = 1;"), "{schema}");
    assert!(
        schema.contains("message TypesCaps {\n  bool git = 1;\n  bool environment = 2;\n}"),
        "{schema}"
    );
    assert!(schema.contains("message TypesEdit {"), "{schema}");
    assert!(schema.contains("oneof witforge_value {"), "{schema}");
    assert!(schema.contains("TypesSpan replace = 1;"), "{schema}");
    assert!(schema.contains("Empty delete_file = 2;"), "{schema}");
    assert!(
        schema.contains("message TypesFinding {\n  optional string message = 1;"),
        "{schema}"
    );
    assert!(schema.contains("TypesSpan primary = 2;"), "{schema}");
    assert!(
        schema.contains("repeated TypesSpan related = 3;"),
        "{schema}"
    );
    assert!(schema.contains("optional bytes payload = 4;"), "{schema}");
}

#[test]
fn emits_direct_singular_wrappers_and_nested_options() {
    let dir = std::env::temp_dir().join(format!("witforge-proto-wrappers-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    fs::write(
        dir.join("contract.wit"),
        r"package example:wrappers@0.1.0;

interface types {
    record payload {
        name: string,
    }
    enum kind {
        one,
        two,
    }
    record nested {
        list-option: list<option<string>>,
        option-list: option<list<string>>,
        option-option: option<option<string>>,
        option-bytes: option<list<u8>>,
        result-value: result<list<payload>, string>,
        bare-result: result,
        option-record: option<payload>,
        option-enum: option<kind>,
    }
}
",
    )
    .unwrap();
    let model = model::build(&load(&dir).unwrap()).unwrap();
    let schema = proto::emit_major(&model, &lock_for(&model)).unwrap();
    assert!(
        schema.contains("message WitforgeOptionOfString {"),
        "{schema}"
    );
    assert!(
        schema.contains("message WitforgeListOfString {"),
        "{schema}"
    );
    assert!(
        schema.contains("message WitforgeResultOfListOfTypesPayloadAndString {"),
        "{schema}"
    );
    assert!(
        schema.contains("message WitforgeResultOfEmptyAndEmpty {"),
        "{schema}"
    );
    assert!(
        schema.contains("repeated WitforgeOptionOfString list_option = 1;"),
        "{schema}"
    );
    assert!(
        schema.contains("WitforgeListOfString option_list = 2;"),
        "{schema}"
    );
    assert!(
        schema.contains("WitforgeOptionOfString option_option = 3;"),
        "{schema}"
    );
    assert!(
        schema.contains("optional bytes option_bytes = 4;"),
        "{schema}"
    );
    assert!(
        schema.contains("WitforgeResultOfListOfTypesPayloadAndString result_value = 5;"),
        "{schema}"
    );
    assert!(
        schema.contains("WitforgeResultOfEmptyAndEmpty bare_result = 6;"),
        "{schema}"
    );
    assert!(
        schema.contains("TypesPayload option_record = 7;"),
        "{schema}"
    );
    assert!(
        schema.contains("optional TypesKind option_enum = 8;"),
        "{schema}"
    );
    fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn named_result_messages_are_interface_prefixed() {
    let model = model::build(&load(&fixture("model")).unwrap()).unwrap();
    let schema = proto::emit_major(&model, &lock_for(&model)).unwrap();
    assert!(schema.contains("message PrimitivesOutcome {"), "{schema}");
    assert!(schema.contains("PrimitivesAll ok = 1;"), "{schema}");
    assert!(schema.contains("string err = 2;"), "{schema}");
    assert!(schema.contains("message PrimitivesBare {"), "{schema}");
    assert!(schema.contains("Empty ok = 1;"), "{schema}");
    assert!(schema.contains("Empty err = 2;"), "{schema}");
    assert!(schema.contains("message PrimitivesOnlyOk {"), "{schema}");
    assert!(schema.contains("message PrimitivesOnlyErr {"), "{schema}");
}
