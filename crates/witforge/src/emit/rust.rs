fn map_type(
    model: &Model,
    current_interface: &str,
    ty: &TypeExpr,
    no_std: bool,
    foreign_resolver: &dyn Fn(&str, &str) -> Result<String>,
) -> Result<String> {
    match ty {
        TypeExpr::Bool => Ok("bool".to_string()),
        TypeExpr::U8 => Ok("u8".to_string()),
        TypeExpr::U16 => Ok("u16".to_string()),
        TypeExpr::U32 => Ok("u32".to_string()),
        TypeExpr::U64 => Ok("u64".to_string()),
        TypeExpr::S8 => Ok("i8".to_string()),
        TypeExpr::S16 => Ok("i16".to_string()),
        TypeExpr::S32 => Ok("i32".to_string()),
        TypeExpr::S64 => Ok("i64".to_string()),
        TypeExpr::F32 => Ok("f32".to_string()),
        TypeExpr::F64 => Ok("f64".to_string()),
        TypeExpr::Char => Ok("char".to_string()),
        TypeExpr::String => Ok(string_path(no_std).to_string()),
        TypeExpr::Named(name) => {
            if let Some((namespace, package)) = name.package() {
                let package_path = foreign_resolver(namespace, package)?;
                let interface = rust_ident(
                    &snake_case(name.interface_name()),
                    "dependency interface module",
                )?;
                let type_name = rust_ident(&pascal_case(&name.name), "type")?;
                return Ok(format!("{package_path}::{interface}::{type_name}"));
            }
            model.type_def(name).with_context(|| {
                format!(
                    "named type `{}/{}` is not in the model",
                    name.interface, name.name
                )
            })?;
            let type_name = rust_ident(&pascal_case(&name.name), "type")?;
            if name.interface == current_interface {
                Ok(type_name)
            } else {
                let module = rust_ident(&snake_case(&name.interface), "interface module")?;
                Ok(format!("super::{module}::{type_name}"))
            }
        }
        TypeExpr::List(element) => {
            let vec_ty = vec_path(no_std);
            if model.resolves_to_u8(element) {
                Ok(format!("{vec_ty}<u8>"))
            } else {
                Ok(format!(
                    "{vec_ty}<{}>",
                    map_type(model, current_interface, element, no_std, foreign_resolver)?
                ))
            }
        }
        TypeExpr::FixedLengthList(element, len) => {
            let elem_ty = if model.resolves_to_u8(element) {
                "u8".to_string()
            } else {
                map_type(model, current_interface, element, no_std, foreign_resolver)?
            };
            Ok(format!("[{elem_ty}; {len}]"))
        }
        TypeExpr::Option(payload) => Ok(format!(
            "{}<{}>",
            option_path(no_std),
            map_type(model, current_interface, payload, no_std, foreign_resolver)?
        )),
        TypeExpr::Result(result) => {
            let ok = result.ok.as_ref().map_or_else(
                || Ok("()".to_string()),
                |ty| map_type(model, current_interface, ty, no_std, foreign_resolver),
            )?;
            let err = result.err.as_ref().map_or_else(
                || Ok("()".to_string()),
                |ty| map_type(model, current_interface, ty, no_std, foreign_resolver),
            )?;
            Ok(format!("{}<{ok}, {err}>", result_path(no_std)))
        }
        TypeExpr::Map(key, value) => {
            let key_ty = map_type(model, current_interface, key, no_std, foreign_resolver)?;
            let val_ty = map_type(model, current_interface, value, no_std, foreign_resolver)?;
            Ok(format!("{}<{key_ty}, {val_ty}>", btree_map_path(no_std)))
        }
    }
}

/// Emit the additive shared world metadata for every version.
///
/// Worlds are not traits: the metadata records each world's name and its imported and exported
/// interface names in source order. Each version gets its own `WORLDS` constant, so adding a
/// version changes only this shared file; per-version Rust modules stay frozen.
fn emit_worlds(versions: &[Version]) -> Result<String> {
    let Some(first) = versions.first() else {
        bail!("no version directories found under WIT root");
    };
    let mut out = String::new();
    writeln!(
        out,
        "{}",
        header_for(&first.model.package.namespace, &first.model.package.name)
    )?;
    writeln!(
        out,
        "// source: {}:{}",
        first.model.package.namespace, first.model.package.name
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "/// One contract world and the interfaces it imports and exports."
    )?;
    writeln!(out, "pub struct World {{")?;
    writeln!(out, "    /// The WIT world name.")?;
    writeln!(out, "    pub name: &'static str,")?;
    writeln!(out, "    /// Imported interface names, in source order.")?;
    writeln!(out, "    pub imports: &'static [&'static str],")?;
    writeln!(out, "    /// Exported interface names, in source order.")?;
    writeln!(out, "    pub exports: &'static [&'static str],")?;
    writeln!(out, "}}")?;
    for version in versions {
        let module = version_module_name(&version.model);
        writeln!(out)?;
        writeln!(out, "/// World metadata for `{module}`.")?;
        writeln!(out, "pub mod {module} {{")?;
        writeln!(
            out,
            "    /// The worlds of {}.",
            version.model.package.version
        )?;
        for world in &version.model.worlds {
            let world_lines = docs::sanitize_rust_lines(&world.docs);
            if !world_lines.is_empty() {
                writeln!(out, "    ///")?;
                writeln!(out, "    /// World `{}`:", world.name)?;
                writeln!(out, "    ///")?;
                for line in world_lines {
                    if line.is_empty() {
                        writeln!(out, "    ///")?;
                    } else {
                        writeln!(out, "    /// {line}")?;
                    }
                }
            }
            if let Some(stability) = stability_doc(&world.stability) {
                writeln!(out, "    ///")?;
                writeln!(out, "    /// World `{}` stability: {stability}", world.name)?;
            }
            for (side, interfaces) in [("import", &world.imports), ("export", &world.exports)] {
                for interface in interfaces {
                    if let Some(stability) = stability_doc(&interface.stability) {
                        writeln!(out, "    ///")?;
                        writeln!(
                            out,
                            "    /// World `{}` {side} `{}` stability: {stability}",
                            world.name,
                            interface.qualified_name()
                        )?;
                    }
                }
            }
        }
        match version.model.worlds.as_slice() {
            [] => {
                writeln!(out, "    pub const WORLDS: &[super::World] = &[];")?;
            }
            [world] => {
                writeln!(
                    out,
                    "    pub const WORLDS: &[super::World] = &[super::World {{"
                )?;
                write_world_fields(&mut out, 8, world)?;
                writeln!(out, "    }}];")?;
            }
            worlds => {
                writeln!(out, "    pub const WORLDS: &[super::World] = &[")?;
                for world in worlds {
                    writeln!(out, "        super::World {{")?;
                    write_world_fields(&mut out, 12, world)?;
                    writeln!(out, "        }},")?;
                }
                writeln!(out, "    ];")?;
            }
        }
        writeln!(out, "}}")?;
    }
    Ok(out)
}

fn write_world_fields(out: &mut String, indent: usize, world: &crate::model::World) -> Result<()> {
    let prefix = " ".repeat(indent);
    writeln!(out, "{prefix}name: {:?},", world.name)?;
    let imports: Vec<String> = world
        .imports
        .iter()
        .map(|interface| format!("{:?}", interface.qualified_name()))
        .collect();
    let imports_rendered =
        rustfmt::fmt_string_slice(indent, &imports, indent + "imports: ".len(), 1);
    writeln!(out, "{prefix}imports: {imports_rendered},")?;
    let exports: Vec<String> = world
        .exports
        .iter()
        .map(|interface| format!("{:?}", interface.qualified_name()))
        .collect();
    let exports_rendered =
        rustfmt::fmt_string_slice(indent, &exports, indent + "exports: ".len(), 1);
    writeln!(out, "{prefix}exports: {exports_rendered},")?;
    Ok(())
}

fn write_stability_doc(
    out: &mut String,
    indent: usize,
    stability: &crate::model::Stability,
) -> Result<()> {
    if let Some(doc) = stability_doc(stability) {
        writeln!(out, "{}/// {doc}", " ".repeat(indent))?;
    }
    Ok(())
}

fn write_deprecated_attribute(
    out: &mut String,
    indent: usize,
    stability: &crate::model::Stability,
) -> Result<()> {
    if let Some(attribute) = rust_deprecated_attribute(stability) {
        writeln!(out, "{}{attribute}", " ".repeat(indent))?;
    }
    Ok(())
}

fn insert_name(
    names: &mut BTreeMap<String, String>,
    ident: &str,
    source: &str,
    scope: &str,
) -> Result<()> {
    if let Some(previous) = names.insert(ident.to_string(), source.to_string()) {
        contract_bail!(
            "{scope}: Rust name `{ident}` is produced by both `{previous}` and `{source}`"
        );
    }
    Ok(())
}
