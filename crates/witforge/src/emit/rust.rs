//! Deterministic Rust source generation from the owned model.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::ContractError;
use crate::emit::output::{GeneratedFiles, ensure_outside_wit_root};
use crate::emit::versions::{Version, load_versions};
use crate::model::{Model, TypeDef, TypeDefKind, TypeExpr};

/// The ownership header on every generated Rust file.
pub const HEADER: &str = "// @generated by witforge; do not edit.";

/// Plan the complete Rust output for a WIT root without writing anything.
///
/// Every `v<major>.<minor>` directory is loaded, checked against the subset, modelled, and
/// checked against its committed v2 lockfile. All versions must share one package namespace and
/// name.
///
/// # Errors
///
/// Returns an error for a missing, duplicate, or symlinked version directory, or an unreadable or
/// invalid lockfile, and a [`ContractError`] for an inconsistent package, subset violations, a
/// stale lockfile, or generated-name collisions.
pub fn plan(wit_root: &Path) -> Result<GeneratedFiles> {
    plan_with_serde(wit_root, false)
}

/// Plan the Rust output for `wit_root`, optionally adding serde derives.
///
/// Serde is opt-in because it changes generated source and requires the consumer to depend on
/// `serde` with the `derive` feature.
///
/// # Errors
///
/// Returns the same errors as [`plan`].
pub fn plan_with_serde(wit_root: &Path, serde: bool) -> Result<GeneratedFiles> {
    plan_versions_with_serde(&load_versions(wit_root)?, serde)
}

/// Plan the Rust output for validated `versions`, which [`load_versions`] returns.
///
/// An emitter error is passed on as the emitter classified it: a contract violation stays a
/// [`ContractError`] and an internal error stays a plain error.
pub(crate) fn plan_versions_with_serde(
    versions: &[Version],
    serde: bool,
) -> Result<GeneratedFiles> {
    let mut modules = BTreeMap::new();
    let mut files = GeneratedFiles::new(HEADER);
    let mut module_lines = Vec::new();
    for version in versions {
        let module = version_module_name(&version.model);
        if let Some(previous) = modules.insert(module.clone(), &version.directory) {
            bail!(ContractError::new(format!(
                "version module `{module}` is produced by both {} and {}",
                previous.display(),
                version.directory.display()
            )));
        }
        let generated = emit_version_with_serde(&version.model, serde)
            .with_context(|| version.directory.display().to_string())?;
        files.insert(format!("{module}.rs"), generated)?;
        module_lines.push(format!("pub mod {module};"));
    }
    if let Some(converted) = super::convert::plan(versions)? {
        files.insert("convert.rs", converted)?;
        module_lines.push("pub mod convert;".to_string());
    }
    let first_dependencies = &versions
        .first()
        .context("no version directories found under WIT root")?
        .model
        .dependencies;
    if versions
        .iter()
        .any(|version| version.model.dependencies != *first_dependencies)
    {
        contract_bail!("versions disagree about their dependency packages");
    }
    if !first_dependencies.is_empty() {
        let dependency_source = emit_dependency_bindings(first_dependencies, serde)?;
        files.insert("witforge_deps.rs", dependency_source)?;
        module_lines.push("pub mod witforge_deps;".to_string());
    }
    if versions
        .iter()
        .any(|version| !version.model.worlds.is_empty())
    {
        files.insert("worlds.rs", emit_worlds(versions)?)?;
        module_lines.push("pub mod worlds;".to_string());
    }
    let package = &versions
        .first()
        .context("no version directories found under WIT root")?
        .model
        .package;
    let mut complete = String::new();
    writeln!(complete, "{HEADER}")?;
    writeln!(
        complete,
        "// source: {}:{}",
        package.namespace, package.name
    )?;
    writeln!(complete)?;
    for line in module_lines {
        writeln!(complete, "{line}")?;
    }
    files.insert("mod.rs", complete)?;
    Ok(files)
}

/// Generate Rust output under `out`.
///
/// # Errors
///
/// Returns an error for invalid input, an output root inside the WIT tree, or an I/O failure.
pub fn generate(wit_root: &Path, out: &Path) -> Result<()> {
    generate_with_serde(wit_root, out, false)
}

/// Generate Rust output under `out`, optionally adding serde derives.
///
/// # Errors
///
/// Returns the same errors as [`generate`].
pub fn generate_with_serde(wit_root: &Path, out: &Path, serde: bool) -> Result<()> {
    ensure_outside_wit_root(wit_root, out)?;
    plan_with_serde(wit_root, serde)?.write(out)
}

/// Check generated Rust output under `out` without writing.
///
/// Returns one message per missing, changed, or extra generated file.
///
/// # Errors
///
/// Returns an error for invalid input, an output root inside the WIT tree, or an I/O failure.
pub fn check(wit_root: &Path, out: &Path) -> Result<Vec<String>> {
    check_with_serde(wit_root, out, false)
}

/// Check Rust output under `out`, optionally expecting serde derives.
///
/// # Errors
///
/// Returns the same errors as [`check`].
pub fn check_with_serde(wit_root: &Path, out: &Path, serde: bool) -> Result<Vec<String>> {
    ensure_outside_wit_root(wit_root, out)?;
    plan_with_serde(wit_root, serde)?.check(out)
}

/// The Rust module name for one contract version: `v<major>_<minor>`.
#[must_use]
pub fn version_module_name(model: &Model) -> String {
    format!(
        "v{}_{}",
        model.package.version.major, model.package.version.minor
    )
}

/// Emit one version module.
///
/// The result is a complete Rust source file containing one inline module per interface and
/// re-exports of the interface traits at the version root. Worlds and package metadata produce
/// no code.
///
/// # Errors
///
/// Returns a [`ContractError`] when a WIT name cannot be represented in Rust or a generated name
/// collides, and a plain error when a named type is missing from the model, which a model built
/// by [`crate::model::build`] never produces.
pub fn emit_version(model: &Model) -> Result<String> {
    emit_version_with_serde(model, false)
}

/// Emit one version module, optionally adding serde derives to generated records, enums,
/// variants, and flags.
///
/// Serde derives require the consumer's `serde` crate with the `derive` feature. Type aliases
/// themselves cannot derive; their target types do.
///
/// # Errors
///
/// Returns the same errors as [`emit_version`].
pub fn emit_version_with_serde(model: &Model, serde: bool) -> Result<String> {
    let mut out = String::new();
    writeln!(out, "// @generated by witforge; do not edit.")?;
    writeln!(
        out,
        "// source: {}:{}@{}",
        model.package.namespace, model.package.name, model.package.version
    )?;
    if serde {
        writeln!(
            out,
            "// serde derives require the consumer's `serde` crate with `derive`."
        )?;
    }
    writeln!(out)?;

    let mut modules = BTreeMap::new();
    let mut traits = BTreeMap::new();
    for interface in &model.interfaces {
        let module = rust_ident(&snake_case(&interface.name), "interface module")?;
        if let Some(previous) = modules.insert(module.clone(), interface.name.clone()) {
            contract_bail!(
                "interface modules `{previous}` and `{}` both map to Rust module `{module}`",
                interface.name
            );
        }
        let trait_name = rust_ident(&pascal_case(&interface.name), "interface trait")?;
        if let Some(previous) = traits.insert(trait_name.clone(), interface.name.clone()) {
            contract_bail!(
                "interfaces `{previous}` and `{}` both map to Rust trait `{trait_name}`",
                interface.name
            );
        }
    }

    let mut root_names: BTreeMap<String, String> = BTreeMap::new();
    for (module, interface) in &modules {
        root_names.insert(module.clone(), format!("module {interface}"));
    }
    for (trait_name, interface) in &traits {
        if let Some(previous) = root_names.insert(trait_name.clone(), format!("trait {interface}"))
        {
            contract_bail!(
                "Rust root name `{trait_name}` is produced by {previous} and trait {interface}"
            );
        }
    }

    for interface in &model.interfaces {
        let module = rust_ident(&snake_case(&interface.name), "interface module")?;
        write_docs(&mut out, 0, &interface.docs)?;
        writeln!(out, "pub mod {module} {{")?;
        emit_interface(
            &mut out,
            model,
            interface,
            serde,
            "super::super::witforge_deps",
        )?;
        writeln!(out, "}}\n")?;
    }
    for interface in &model.interfaces {
        let module = rust_ident(&snake_case(&interface.name), "interface module")?;
        let trait_name = rust_ident(&pascal_case(&interface.name), "interface trait")?;
        writeln!(out, "pub use {module}::{trait_name};")?;
    }
    Ok(out)
}

fn emit_interface(
    out: &mut String,
    model: &Model,
    interface: &crate::model::Interface,
    serde: bool,
    foreign_base: &str,
) -> Result<()> {
    let trait_name = rust_ident(&pascal_case(&interface.name), "interface trait")?;
    let mut type_names: BTreeMap<String, String> = BTreeMap::new();
    type_names.insert(trait_name.clone(), format!("trait {}", interface.name));

    for def in &interface.types {
        let name = rust_ident(&pascal_case(&def.name), "type")?;
        insert_name(
            &mut type_names,
            &name,
            &format!("type {}/{}", interface.name, def.name),
            "interface scope",
        )?;
    }
    for def in &interface.types {
        emit_type_def(out, model, interface, def, serde, foreign_base)?;
    }
    emit_trait(out, model, interface, &trait_name, foreign_base)?;
    Ok(())
}

fn emit_dependency_bindings(
    dependencies: &[crate::model::Dependency],
    serde: bool,
) -> Result<String> {
    let mut out = String::new();
    writeln!(out, "{HEADER}")?;
    writeln!(out, "// source: wit/deps")?;
    if serde {
        writeln!(
            out,
            "// serde derives require the consumer's `serde` crate with `derive`."
        )?;
    }
    writeln!(out)?;
    let mut module_names = BTreeMap::new();
    for dependency in dependencies {
        let module = rust_ident(
            &format!(
                "{}_{}",
                snake_case(&dependency.package.namespace),
                snake_case(&dependency.package.name)
            ),
            "dependency package module",
        )?;
        if let Some(previous) = module_names.insert(module.clone(), dependency.package.name.clone())
        {
            contract_bail!(
                "dependency packages `{previous}` and `{}` both map to Rust module `{module}`",
                dependency.package.name
            );
        }
        writeln!(out, "pub mod {module} {{")?;
        for interface in &dependency.interfaces {
            let interface_module =
                rust_ident(&snake_case(&interface.name), "dependency interface module")?;
            writeln!(out, "    pub mod {interface_module} {{")?;
            let mut body = String::new();
            emit_interface(
                &mut body,
                &dependency_model(dependency, dependencies),
                interface,
                serde,
                "super::super",
            )?;
            for line in body.lines() {
                if line.is_empty() {
                    out.push('\n');
                } else {
                    writeln!(out, "    {line}")?;
                }
            }
            writeln!(out, "    }}")?;
        }
        writeln!(out, "}}")?;
        writeln!(out)?;
    }
    Ok(out)
}

fn dependency_model(
    dependency: &crate::model::Dependency,
    dependencies: &[crate::model::Dependency],
) -> Model {
    Model {
        package: dependency.package.clone(),
        interfaces: dependency.interfaces.clone(),
        worlds: Vec::new(),
        dependencies: dependencies
            .iter()
            .filter(|other| {
                other.package.namespace != dependency.package.namespace
                    || other.package.name != dependency.package.name
            })
            .cloned()
            .collect(),
    }
}

fn write_derives(out: &mut String, serde: bool) -> Result<()> {
    if serde {
        writeln!(
            out,
            "    #[derive(Debug, Clone, PartialEq, ::serde::Serialize, ::serde::Deserialize)]"
        )?;
    } else {
        writeln!(out, "    #[derive(Debug, Clone, PartialEq)]")?;
    }
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn emit_record(
    out: &mut String,
    model: &Model,
    interface: &crate::model::Interface,
    def: &TypeDef,
    name: &str,
    fields: &[crate::model::Field],
    serde: bool,
    foreign_base: &str,
) -> Result<()> {
    write_derives(out, serde)?;
    writeln!(out, "    pub struct {name} {{")?;
    let mut field_names = BTreeMap::new();
    for field in fields {
        let field_name = rust_ident(&snake_case(&field.name), "record field")?;
        insert_name(
            &mut field_names,
            &field_name,
            &format!("field {}", field.name),
            &format!("{}/{}", interface.name, def.name),
        )?;
        write_docs(out, 8, &field.docs)?;
        let ty = map_type(model, &interface.name, &field.ty, foreign_base)?;
        writeln!(out, "        pub {field_name}: {ty},")?;
    }
    writeln!(out, "    }}")?;
    Ok(())
}

fn emit_type_def(
    out: &mut String,
    model: &Model,
    interface: &crate::model::Interface,
    def: &TypeDef,
    serde: bool,
    foreign_base: &str,
) -> Result<()> {
    let name = rust_ident(&pascal_case(&def.name), "type")?;
    write_docs(out, 4, &def.docs)?;
    match &def.kind {
        TypeDefKind::Record(fields) => {
            emit_record(
                out,
                model,
                interface,
                def,
                &name,
                fields,
                serde,
                foreign_base,
            )?;
        }
        TypeDefKind::Variant(cases) => {
            write_derives(out, serde)?;
            writeln!(out, "    pub enum {name} {{")?;
            let mut case_names = BTreeMap::new();
            for case in cases {
                let case_name = rust_ident(&pascal_case(&case.name), "variant case")?;
                insert_name(
                    &mut case_names,
                    &case_name,
                    &format!("case {}", case.name),
                    &format!("{}/{}", interface.name, def.name),
                )?;
                write_docs(out, 8, &case.docs)?;
                if let Some(payload) = &case.payload {
                    let ty = map_type(model, &interface.name, payload, foreign_base)?;
                    writeln!(out, "        {case_name}({ty}),")?;
                } else {
                    writeln!(out, "        {case_name},")?;
                }
            }
            writeln!(out, "    }}")?;
        }
        TypeDefKind::Enum(cases) => {
            write_derives(out, serde)?;
            writeln!(out, "    pub enum {name} {{")?;
            let mut case_names = BTreeMap::new();
            for case in cases {
                let case_name = rust_ident(&pascal_case(&case.name), "enum case")?;
                insert_name(
                    &mut case_names,
                    &case_name,
                    &format!("case {}", case.name),
                    &format!("{}/{}", interface.name, def.name),
                )?;
                write_docs(out, 8, &case.docs)?;
                writeln!(out, "        {case_name},")?;
            }
            writeln!(out, "    }}")?;
        }
        TypeDefKind::Flags(flags) => {
            write_derives(out, serde)?;
            writeln!(out, "    pub struct {name} {{")?;
            let mut flag_names = BTreeMap::new();
            for flag in flags {
                let flag_name = rust_ident(&snake_case(&flag.name), "flag")?;
                insert_name(
                    &mut flag_names,
                    &flag_name,
                    &format!("flag {}", flag.name),
                    &format!("{}/{}", interface.name, def.name),
                )?;
                write_docs(out, 8, &flag.docs)?;
                writeln!(out, "        pub {flag_name}: bool,")?;
            }
            writeln!(out, "    }}")?;
        }
        TypeDefKind::Alias(target) => {
            let ty = map_type(model, &interface.name, target, foreign_base)?;
            writeln!(out, "    pub type {name} = {ty};")?;
        }
        TypeDefKind::List(element) => {
            let ty = map_type(model, &interface.name, element, foreign_base)?;
            writeln!(out, "    pub type {name} = ::std::vec::Vec<{ty}>;")?;
        }
        TypeDefKind::Option(payload) => {
            let ty = map_type(model, &interface.name, payload, foreign_base)?;
            writeln!(out, "    pub type {name} = ::std::option::Option<{ty}>;")?;
        }
        TypeDefKind::Result(result) => {
            let ok = result.ok.as_ref().map_or_else(
                || Ok("()".to_string()),
                |ty| map_type(model, &interface.name, ty, foreign_base),
            )?;
            let err = result.err.as_ref().map_or_else(
                || Ok("()".to_string()),
                |ty| map_type(model, &interface.name, ty, foreign_base),
            )?;
            writeln!(
                out,
                "    pub type {name} = ::std::result::Result<{ok}, {err}>;"
            )?;
        }
    }
    Ok(())
}

fn emit_trait(
    out: &mut String,
    model: &Model,
    interface: &crate::model::Interface,
    trait_name: &str,
    foreign_base: &str,
) -> Result<()> {
    writeln!(out, "    pub trait {trait_name} {{")?;
    let mut function_names = BTreeMap::new();
    for function in &interface.functions {
        let name = rust_ident(&snake_case(&function.name), "function")?;
        insert_name(
            &mut function_names,
            &name,
            &format!("function {}", function.name),
            &format!("trait {}", interface.name),
        )?;
        write_docs(out, 8, &function.docs)?;
        write!(out, "        fn {name}(&self")?;
        let mut param_names = BTreeMap::new();
        for param in &function.params {
            let param_name = rust_ident(&snake_case(&param.name), "parameter")?;
            insert_name(
                &mut param_names,
                &param_name,
                &format!("parameter {}", param.name),
                &format!("function {}/{}", interface.name, function.name),
            )?;
            let ty = map_type(model, &interface.name, &param.ty, foreign_base)?;
            write!(out, ", {param_name}: {ty}")?;
        }
        write!(out, ")")?;
        if let Some(result) = &function.result {
            let ty = map_type(model, &interface.name, result, foreign_base)?;
            write!(out, " -> {ty}")?;
        } else {
            write!(out, " -> ()")?;
        }
        writeln!(out, ";")?;
    }
    writeln!(out, "    }}")?;
    Ok(())
}

fn map_type(
    model: &Model,
    current_interface: &str,
    ty: &TypeExpr,
    foreign_base: &str,
) -> Result<String> {
    match ty {
        TypeExpr::Bool => Ok("bool".to_string()),
        TypeExpr::U8 => Ok("u8".to_string()),
        TypeExpr::U16 => Ok("u16".to_string()),
        TypeExpr::U32 => Ok("u32".to_string()),
        TypeExpr::U64 => Ok("u64".to_string()),
        TypeExpr::S8 => Ok("i8".to_string()),
        TypeExpr::S16 => Ok("i16".to_string()),
        TypeExpr::S32 => Ok("i32".to_string()),
        TypeExpr::S64 => Ok("i64".to_string()),
        TypeExpr::F32 => Ok("f32".to_string()),
        TypeExpr::F64 => Ok("f64".to_string()),
        TypeExpr::String => Ok("::std::string::String".to_string()),
        TypeExpr::Named(name) => {
            if let Some((namespace, package)) = name.package() {
                let package = rust_ident(
                    &format!("{}_{}", snake_case(namespace), snake_case(package)),
                    "dependency package module",
                )?;
                let interface = rust_ident(
                    &snake_case(name.interface_name()),
                    "dependency interface module",
                )?;
                let type_name = rust_ident(&pascal_case(&name.name), "type")?;
                return Ok(format!(
                    "{foreign_base}::{package}::{interface}::{type_name}"
                ));
            }
            model.type_def(name).with_context(|| {
                format!(
                    "named type `{}/{}` is not in the model",
                    name.interface, name.name
                )
            })?;
            let type_name = rust_ident(&pascal_case(&name.name), "type")?;
            if name.interface == current_interface {
                Ok(type_name)
            } else {
                let module = rust_ident(&snake_case(&name.interface), "interface module")?;
                Ok(format!("super::{module}::{type_name}"))
            }
        }
        TypeExpr::List(element) => Ok(format!(
            "::std::vec::Vec<{}>",
            map_type(model, current_interface, element, foreign_base)?
        )),
        TypeExpr::Option(payload) => Ok(format!(
            "::std::option::Option<{}>",
            map_type(model, current_interface, payload, foreign_base)?
        )),
        TypeExpr::Result(result) => {
            let ok = result.ok.as_ref().map_or_else(
                || Ok("()".to_string()),
                |ty| map_type(model, current_interface, ty, foreign_base),
            )?;
            let err = result.err.as_ref().map_or_else(
                || Ok("()".to_string()),
                |ty| map_type(model, current_interface, ty, foreign_base),
            )?;
            Ok(format!("::std::result::Result<{ok}, {err}>"))
        }
    }
}

/// Emit the additive shared world metadata for every version.
///
/// Worlds are not traits: the metadata records each world's name and its imported and exported
/// interface names in source order. Each version gets its own `WORLDS` constant, so adding a
/// version changes only this shared file; per-version Rust modules stay frozen.
fn emit_worlds(versions: &[Version]) -> Result<String> {
    let Some(first) = versions.first() else {
        bail!("no version directories found under WIT root");
    };
    let mut out = String::new();
    writeln!(out, "{HEADER}")?;
    writeln!(
        out,
        "// source: {}:{}",
        first.model.package.namespace, first.model.package.name
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "/// One contract world and the interfaces it imports and exports."
    )?;
    writeln!(out, "pub struct World {{")?;
    writeln!(out, "    /// The WIT world name.")?;
    writeln!(out, "    pub name: &'static str,")?;
    writeln!(out, "    /// Imported interface names, in source order.")?;
    writeln!(out, "    pub imports: &'static [&'static str],")?;
    writeln!(out, "    /// Exported interface names, in source order.")?;
    writeln!(out, "    pub exports: &'static [&'static str],")?;
    writeln!(out, "}}")?;
    for version in versions {
        let module = version_module_name(&version.model);
        writeln!(out)?;
        writeln!(out, "/// World metadata for `{module}`.")?;
        writeln!(out, "pub mod {module} {{")?;
        writeln!(
            out,
            "    /// The worlds of {}.",
            version.model.package.version
        )?;
        writeln!(out, "    pub const WORLDS: &[super::World] = &[")?;
        for world in &version.model.worlds {
            let imports = world
                .imports
                .iter()
                .map(|interface| format!("{:?}", interface.qualified_name()))
                .collect::<Vec<_>>()
                .join(", ");
            let exports = world
                .exports
                .iter()
                .map(|interface| format!("{:?}", interface.qualified_name()))
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(
                out,
                "        super::World {{ name: {:?}, imports: &[{imports}], exports: &[{exports}] }},",
                world.name
            )?;
        }
        writeln!(out, "    ];")?;
        writeln!(out, "}}")?;
    }
    Ok(out)
}

fn write_docs(out: &mut String, indent: usize, docs: &str) -> Result<()> {
    if docs.is_empty() {
        return Ok(());
    }
    let prefix = " ".repeat(indent);
    for line in docs.lines() {
        writeln!(out, "{prefix}/// {line}")?;
    }
    Ok(())
}

fn insert_name(
    names: &mut BTreeMap<String, String>,
    ident: &str,
    source: &str,
    scope: &str,
) -> Result<()> {
    if let Some(previous) = names.insert(ident.to_string(), source.to_string()) {
        contract_bail!(
            "{scope}: Rust name `{ident}` is produced by both `{previous}` and `{source}`"
        );
    }
    Ok(())
}

pub(crate) fn snake_case(name: &str) -> String {
    name.replace('-', "_")
}

pub(crate) fn pascal_case(name: &str) -> String {
    let mut out = String::new();
    for part in name.split('-') {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.push(first.to_ascii_uppercase());
            out.extend(chars);
        }
    }
    out
}

pub(crate) fn rust_ident(name: &str, what: &str) -> Result<String> {
    if name.is_empty() || name == "_" {
        contract_bail!("{what} has no Rust-compatible name");
    }
    if name.chars().next().is_some_and(|ch| ch.is_ascii_digit()) {
        contract_bail!("{what} `{name}` starts with a digit");
    }
    let suffix = ["crate", "self", "super", "Self"];
    let raw = [
        "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern",
        "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move",
        "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe",
        "use", "where", "while", "abstract", "become", "box", "do", "final", "macro", "override",
        "priv", "try", "typeof", "union", "unsized", "virtual", "yield",
    ];
    if suffix.contains(&name) {
        Ok(format!("{name}_"))
    } else if raw.contains(&name) {
        Ok(format!("r#{name}"))
    } else {
        Ok(name.to_string())
    }
}
