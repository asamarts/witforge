/// Plan glue output for a WIT root without writing anything.
///
/// Every `v<major>.<minor>` directory is validated against the subset and its committed lockfile.
/// Only the highest minor of each major contributes output; lower minors are still validated so
/// the plan cannot silently accept a broken released contract.
///
/// # Errors
///
/// Returns an error for an invalid module root, a missing or symlinked version directory, or an
/// unreadable or invalid lockfile, and a [`ContractError`](crate::ContractError) for an
/// inconsistent package, subset violations, a stale lockfile, generated-name collisions, or a
/// contract the [protobuf emitter](crate::emit::proto) refuses.
pub fn plan(wit_root: &Path, plain_root: &str, proto_root: &str) -> Result<GeneratedFiles> {
    validate_module_root(plain_root)?;
    validate_module_root(proto_root)?;
    plan_versions(&load_versions(wit_root)?, plain_root, proto_root)
}

/// Plan glue output for `wit_root`, using an optional explicit released-version manifest path
/// (`--released`) when determining retired versions.
///
/// # Errors
///
/// Returns the same errors as [`plan`].
pub fn plan_with_released(
    wit_root: &Path,
    plain_root: &str,
    proto_root: &str,
    released: Option<&Path>,
) -> Result<GeneratedFiles> {
    plan_with_options(
        wit_root,
        plain_root,
        proto_root,
        released,
        &GlueOptions::default(),
    )
}

/// Plan glue output for `wit_root`, using an optional explicit released-version manifest path
/// (`--released`) and [`GlueOptions`] (such as `no_std` + `alloc` paths).
///
/// # Errors
///
/// Returns the same errors as [`plan`].
pub fn plan_with_options(
    wit_root: &Path,
    plain_root: &str,
    proto_root: &str,
    released: Option<&Path>,
    options: &GlueOptions,
) -> Result<GeneratedFiles> {
    validate_module_root(plain_root)?;
    validate_module_root(proto_root)?;
    plan_versions_with_options(
        &load_versions_with_released(wit_root, released)?,
        plain_root,
        proto_root,
        options,
    )
}

/// Plan the glue output for validated `versions`, which [`load_versions`] returns, and validated
/// module roots.
///
/// Glue converts to and from the types generated from the protobuf schema, so it refuses every
/// contract [`proto::emit_major`](crate::emit::proto::emit_major) refuses, such as two WIT names
/// that map to one proto message. An emitter error is passed on as the emitter classified it: a
/// contract violation stays a [`ContractError`](crate::ContractError) and an internal error
/// stays a plain error.
pub(crate) fn plan_versions(
    versions: &[Version],
    plain_root: &str,
    proto_root: &str,
) -> Result<GeneratedFiles> {
    plan_versions_with_options(versions, plain_root, proto_root, &GlueOptions::default())
}

pub(crate) fn plan_versions_with_options(
    versions: &[Version],
    plain_root: &str,
    proto_root: &str,
    options: &GlueOptions,
) -> Result<GeneratedFiles> {
    let dep_layout = DepLayout::from_versions(versions)?;
    // Versions are in ascending order, so the last one of each major is its highest minor.
    let mut highest: BTreeMap<u64, &Version> = BTreeMap::new();
    for version in versions {
        highest.insert(version.major, version);
    }
    let all_deps: Vec<Dependency> = dep_layout.by_major.values().flatten().cloned().collect();
    let generated_modules = collect_plan_module_names(&highest, &all_deps);
    validate_module_root_against_generated(plain_root, &generated_modules)?;
    validate_module_root_against_generated(proto_root, &generated_modules)?;
    // Glue converts to and from the prost types produced from `proto`, so run the proto emitter's
    // full validation (root majors, every dependency, and dependency file collisions) first.
    crate::emit::proto::plan_versions(versions)?;
    let first = versions
        .first()
        .context("no version directories found under WIT root")?;
    let package = &first.model.package;
    let header = header_for(&package.namespace, &package.name);
    let mut files = GeneratedFiles::new(&header);
    if !dep_layout.is_empty() {
        files.insert(
            "witforge_deps.rs",
            emit_dependency_glue_layout(
                &header,
                &dep_layout,
                plain_root,
                proto_root,
                options.no_std,
            )?,
        )?;
    }
    let mut majors = Vec::new();
    for (major, version) in &highest {
        let mut emitter = Emitter::new(&version.model, &version.lock, plain_root, proto_root)?;
        emitter.no_std = options.no_std;
        emitter.root_major = *major;
        emitter.dep_layout = Some(&dep_layout);
        if !dep_layout.is_empty() {
            emitter.proto_base_override = Some(dependency_proto_base(
                proto_root,
                &version.model.package.namespace,
                &version.model.package.name,
                *major,
            ));
        }
        let generated = emitter
            .emit()
            .with_context(|| version.directory.display().to_string())?;
        files.insert(format!("v{major}.rs"), generated)?;
        majors.push(*major);
    }
    files.insert(
        "mod.rs",
        root_source(
            &package.namespace,
            &package.name,
            &majors,
            !dep_layout.is_empty(),
            options.no_std,
        )?,
    )?;
    Ok(files)
}

/// Generate glue output under `out`.
///
/// # Errors
///
/// Returns an error for invalid input, an output root inside the WIT tree, or an I/O failure.
pub fn generate(wit_root: &Path, out: &Path, plain_root: &str, proto_root: &str) -> Result<()> {
    ensure_outside_wit_root(wit_root, out)?;
    plan(wit_root, plain_root, proto_root)?.write(out)
}

/// Check generated glue output under `out` without writing.
///
/// Returns one structured finding per missing, changed, or extra generated file.
///
/// # Errors
///
/// Returns an error for invalid input, an output root inside the WIT tree, or an I/O failure.
pub fn check(
    wit_root: &Path,
    out: &Path,
    plain_root: &str,
    proto_root: &str,
) -> Result<Vec<GeneratedFileFinding>> {
    ensure_outside_wit_root(wit_root, out)?;
    plan(wit_root, plain_root, proto_root)?.check(out)
}

fn emit_dependency_glue(
    header: &str,
    dependencies: &[Dependency],
    plain_root: &str,
    proto_root: &str,
) -> Result<String> {
    let mut layout = DepLayout::default();
    for dep in dependencies {
        layout.shared.insert(
            (dep.package.namespace.clone(), dep.package.name.clone()),
            dep.clone(),
        );
    }
    emit_dependency_glue_layout(header, &layout, plain_root, proto_root, false)
}

#[allow(clippy::too_many_lines)]
fn emit_dependency_glue_layout(
    header: &str,
    layout: &DepLayout,
    plain_root: &str,
    proto_root: &str,
    no_std: bool,
) -> Result<String> {
    let mut out = String::new();
    writeln!(out, "{header}")?;
    writeln!(out, "// source: wit/deps")?;
    if no_std {
        writeln!(
            out,
            "// no_std output requires `extern crate alloc;` in the consuming crate."
        )?;
    }
    if layout
        .by_major
        .values()
        .flatten()
        .any(dependency_has_deprecation)
        || layout.shared.values().any(dependency_has_deprecation)
    {
        writeln!(out, "#![allow(deprecated)]")?;
    }
    writeln!(out)?;
    writeln!(out, "pub use super::GlueError;")?;
    let shared_slice: Vec<Dependency> = layout.shared.values().cloned().collect();
    emit_dep_glue_group(
        &mut out,
        0,
        "witforge_deps",
        &shared_slice,
        &shared_slice,
        plain_root,
        proto_root,
        0,
        layout,
        false,
        no_std,
    )?;
    for (&major, scoped_deps) in &layout.per_major {
        let major_mod = format!("v{major}");
        writeln!(out)?;
        writeln!(
            out,
            "/// Protobuf glue for dependencies pinned by major version `{major_mod}`."
        )?;
        writeln!(out, "pub mod {major_mod} {{")?;
        writeln!(out, "    pub use super::GlueError;")?;
        let all_in_major = layout
            .by_major
            .get(&major)
            .map_or(scoped_deps.as_slice(), Vec::as_slice);
        emit_dep_glue_group(
            &mut out,
            4,
            &major_mod,
            scoped_deps,
            all_in_major,
            plain_root,
            proto_root,
            major,
            layout,
            true,
            no_std,
        )?;
        writeln!(out, "}}")?;
    }
    Ok(out)
}

#[allow(clippy::too_many_arguments)]
fn emit_dep_glue_group(
    out: &mut String,
    indent: usize,
    parent_mod: &str,
    targets: &[Dependency],
    all_in_scope: &[Dependency],
    plain_root: &str,
    proto_root: &str,
    root_major: u64,
    layout: &DepLayout,
    scoped: bool,
    no_std: bool,
) -> Result<()> {
    let prefix = " ".repeat(indent);
    let mut modules = BTreeMap::new();
    for dependency in targets {
        let module =
            dependency_module_name(&dependency.package.namespace, &dependency.package.name)?;
        if let Some(previous) = modules.insert(module.clone(), dependency.package.clone()) {
            contract_bail!(
                "dependency packages `{}:{}` and `{}:{}` both map to glue module `{module}`",
                previous.namespace,
                previous.name,
                dependency.package.namespace,
                dependency.package.name
            );
        }
        if scoped {
            let owner = layout.canonical_owner_major(
                root_major,
                &dependency.package.namespace,
                &dependency.package.name,
            );
            if owner < root_major {
                writeln!(out)?;
                writeln!(out, "{prefix}pub use super::v{owner}::{module};")?;
                continue;
            }
        }
        let model = Model {
            package: dependency.package.clone(),
            interfaces: dependency.interfaces.clone(),
            worlds: Vec::new(),
            dependencies: all_in_scope
                .iter()
                .filter(|other| {
                    other.package.namespace != dependency.package.namespace
                        || other.package.name != dependency.package.name
                })
                .cloned()
                .collect(),
        };
        let members = model.members()?;
        let mut lock = WireLock::default();
        lock.reconcile(&members)?;
        let mut emitter = Emitter::new_dependency(
            &model,
            &lock,
            plain_root,
            proto_root,
            dependency,
            indent + 4,
            root_major,
            Some(layout),
            scoped,
        )?;
        emitter.no_std = no_std;
        let body = emitter.emit_body()?;
        writeln!(out)?;
        let fallback = format!(
            "Protobuf glue for dependency package `{}:{}`.",
            dependency.package.namespace, dependency.package.name
        );
        rustfmt::write_docs_or(out, indent, &dependency.package.docs, &fallback)?;
        if module == parent_mod {
            writeln!(out, "{prefix}#[allow(clippy::module_inception)]")?;
        }
        if body.is_empty() {
            writeln!(out, "{prefix}pub mod {module} {{}}")?;
        } else {
            writeln!(out, "{prefix}pub mod {module} {{")?;
            out.push_str(&body);
            writeln!(out, "{prefix}}}")?;
        }
    }
    Ok(())
}

/// Validate a Rust module path used as a generated reference root.
///
/// Generated glue pastes `--plain-root` and `--proto-root` into nested modules at several depths,
/// so relative roots starting with `self` or `super` are refused. Accepted forms are `crate`,
/// `crate::...`, `::crate_name::...`, or an external crate name (`other::...`).
///
/// # Errors
///
/// Returns an error for an empty path, a relative root (`self` or `super`), a reserved generated
/// module root, empty or trailing segments, whitespace, generics, an invalid identifier, or a
/// bare Rust keyword.
pub fn validate_module_root(root: &str) -> Result<()> {
    validate_module_root_inner(root).map_err(|err| {
        crate::operational_error(
            crate::diagnostic::codes::CLI_USAGE,
            format!("{err:#}"),
            None,
        )
    })
}

fn validate_module_root_inner(root: &str) -> Result<()> {
    if root.is_empty() {
        bail!("module root is empty");
    }
    if root.trim() != root || root.chars().any(char::is_whitespace) {
        bail!("module root `{root}` contains whitespace");
    }
    let (global, rest) = root
        .strip_prefix("::")
        .map_or((false, root), |stripped| (true, stripped));
    if rest.is_empty() {
        bail!("module root `{root}` has an empty segment");
    }
    let segments: Vec<&str> = rest.split("::").collect();
    if segments.iter().any(|segment| segment.is_empty()) {
        bail!("module root `{root}` has an empty segment");
    }
    for (index, raw_segment) in segments.iter().enumerate() {
        let segment = *raw_segment;
        if matches!(segment, "crate" | "self" | "super") {
            if index == 0 {
                if global {
                    bail!(
                        "module root `{root}` cannot start with `::{segment}`; use `crate::...`, \
                         `::crate_name::...`, or an external crate name"
                    );
                }
                if segment == "crate" {
                    continue;
                }
                bail!(
                    "module root `{root}` is relative (`{segment}` cannot resolve identically at \
                     every generated module depth); use `crate::...`, `::crate_name::...`, or an \
                     external crate name"
                );
            }
            bail!("module root `{root}` has `{segment}` outside the leading module path");
        }
        let identifier = segment.strip_prefix("r#").unwrap_or(segment);
        if identifier.is_empty()
            || identifier == "_"
            || identifier
                .chars()
                .next()
                .is_some_and(|ch| ch.is_ascii_digit())
            || !identifier
                .chars()
                .all(|ch| ch.is_ascii_alphanumeric() || ch == '_')
        {
            bail!("module root `{root}` has invalid identifier `{segment}`");
        }
        if segment == identifier && RUST_KEYWORDS.contains(&identifier) {
            bail!("module root `{root}` uses bare Rust keyword `{identifier}`");
        }
        if segment != identifier && matches!(identifier, "crate" | "self" | "super" | "Self") {
            bail!("module root `{root}` has invalid raw identifier `{segment}`");
        }
        if index == 0 && !global && matches!(segment, "witforge_deps" | "functions" | "GlueError") {
            bail!(
                "module root `{root}` starts with generated item `{segment}`; prefix an external \
                 crate with `::` (for example `::{root}`) or use `crate::...`"
            );
        }
    }
    Ok(())
}

fn validate_module_root_against_generated(
    root: &str,
    generated_modules: &BTreeSet<String>,
) -> Result<()> {
    validate_module_root(root)?;
    if root.starts_with("::") {
        return Ok(());
    }
    let first = root.split("::").next().unwrap_or_default();
    if first != "crate" && generated_modules.contains(first) {
        return Err(crate::operational_error(
            crate::diagnostic::codes::CLI_USAGE,
            format!(
                "module root `{root}` starts with generated module `{first}`; prefix an external \
                 crate with `::` (for example `::{root}`) or use `crate::...`"
            ),
            None,
        ));
    }
    Ok(())
}

fn collect_interface_module_names(interfaces: &[Interface], out: &mut BTreeSet<String>) {
    for interface in interfaces {
        if let Ok(module) = rust_ident(&snake_case(&interface.name), "interface module") {
            out.insert(module);
        }
        for def in &interface.types {
            if let Ok(module) = rust_ident(&snake_case(&def.name), "type module") {
                out.insert(module);
            }
        }
        for function in &interface.functions {
            if let Ok(module) = rust_ident(&snake_case(&function.name), "function module") {
                out.insert(module);
            }
        }
    }
}

fn collect_model_module_names(model: &Model, out: &mut BTreeSet<String>) {
    out.insert(format!("v{}", model.package.version.major));
    out.insert("witforge_deps".to_string());
    out.insert("functions".to_string());
    collect_interface_module_names(&model.interfaces, out);
    for dependency in &model.dependencies {
        if let Ok(module) =
            dependency_module_name(&dependency.package.namespace, &dependency.package.name)
        {
            out.insert(module);
        }
        collect_interface_module_names(&dependency.interfaces, out);
    }
}

fn collect_plan_module_names(
    highest: &BTreeMap<u64, &Version>,
    dependencies: &[Dependency],
) -> BTreeSet<String> {
    let mut names = BTreeSet::new();
    names.insert("witforge_deps".to_string());
    names.insert("functions".to_string());
    for (&major, version) in highest {
        names.insert(format!("v{major}"));
        collect_model_module_names(&version.model, &mut names);
    }
    for dependency in dependencies {
        if let Ok(module) =
            dependency_module_name(&dependency.package.namespace, &dependency.package.name)
        {
            names.insert(module);
        }
        collect_interface_module_names(&dependency.interfaces, &mut names);
    }
    names
}

fn dependency_pkg_prefix(dependency: &Dependency) -> String {
    format!(
        "{}{}",
        ident::proto_pascal(&dependency.package.namespace),
        ident::proto_pascal(&dependency.package.name)
    )
}

fn dependency_shape_name(dependency: &Dependency, name: &QualifiedName) -> String {
    ident::proto_dependency_shape_name(
        &dependency.package.namespace,
        &dependency.package.name,
        name.interface_name(),
        &name.name,
    )
}

fn dependency_module_name(namespace: &str, package: &str) -> Result<String> {
    rust_ident(
        &format!("{}_{}", snake_case(namespace), snake_case(package)),
        "dependency module",
    )
}

fn dependency_proto_base(proto_root: &str, namespace: &str, package: &str, major: u64) -> String {
    format!(
        "{proto_root}::{}::{}::v{major}",
        ident::prost_package_segment(namespace),
        ident::prost_package_segment(package)
    )
}

fn qualify_type(dependency: Option<&Dependency>, ty: &TypeExpr) -> TypeExpr {
    let Some(dependency) = dependency else {
        return ty.clone();
    };
    match ty {
        TypeExpr::Named(name) if name.package().is_none() => TypeExpr::Named(QualifiedName {
            interface: format!(
                "{}:{}/{}",
                dependency.package.namespace,
                dependency.package.name,
                name.interface_name()
            ),
            name: name.name.clone(),
        }),
        TypeExpr::List(element) => {
            TypeExpr::List(Box::new(qualify_type(Some(dependency), element)))
        }
        TypeExpr::Option(payload) => {
            TypeExpr::Option(Box::new(qualify_type(Some(dependency), payload)))
        }
        TypeExpr::Result(result) => TypeExpr::Result(ResultExpr {
            ok: result
                .ok
                .as_ref()
                .map(|ty| Box::new(qualify_type(Some(dependency), ty))),
            err: result
                .err
                .as_ref()
                .map(|ty| Box::new(qualify_type(Some(dependency), ty))),
        }),
        _ => ty.clone(),
    }
}

/// Emit the glue root module containing the generated `GlueError` and the major modules.
///
/// # Errors
///
/// Returns an error when a generated module name is invalid.
pub fn emit_root(model: &Model, majors: &[u64]) -> Result<String> {
    emit_root_with_options(model, majors, &GlueOptions::default())
}

/// Emit the glue root module with explicit [`GlueOptions`] (such as `no_std` + `alloc` paths).
///
/// # Errors
///
/// Returns an error when a generated module name is invalid.
pub fn emit_root_with_options(
    model: &Model,
    majors: &[u64],
    options: &GlueOptions,
) -> Result<String> {
    root_source(
        &model.package.namespace,
        &model.package.name,
        majors,
        !model.dependencies.is_empty(),
        options.no_std,
    )
}

fn root_source(
    namespace: &str,
    name: &str,
    majors: &[u64],
    dependencies: bool,
    no_std: bool,
) -> Result<String> {
    let mut out = String::new();
    writeln!(out, "{}", header_for(namespace, name))?;
    writeln!(out, "// source: {namespace}:{name}")?;
    if no_std {
        writeln!(
            out,
            "// no_std output requires `extern crate alloc;` in the consuming crate."
        )?;
    }
    writeln!(out)?;
    out.push_str(GLUE_ERROR_BODY);
    writeln!(out)?;
    let error_trait = if no_std {
        "::core::error::Error"
    } else {
        "::std::error::Error"
    };
    writeln!(out, "impl {error_trait} for GlueError {{}}")?;
    for major in majors {
        writeln!(out)?;
        writeln!(out, "/// Protobuf glue for major version `v{major}`.")?;
        writeln!(out, "pub mod v{major};")?;
    }
    if dependencies {
        writeln!(out)?;
        writeln!(out, "/// Protobuf glue for pinned dependencies.")?;
        writeln!(out, "pub mod witforge_deps;")?;
    }
    Ok(out)
}

/// Validate that `model` (root package and pinned dependencies) satisfies glue-specific naming
/// constraints (such as the reserved `functions` type module and dependency module collisions).
pub(crate) fn validate_model(model: &Model) -> Result<()> {
    let members = model.members()?;
    let mut lock = WireLock::default();
    lock.reconcile(&members)?;
    let emitter = Emitter::new(model, &lock, "crate::plain", "crate::proto")?;
    emitter.check_module_names()?;
    for interface in &model.interfaces {
        for function in &interface.functions {
            let mut request_fields = BTreeMap::new();
            for param in &function.params {
                let name = rust_ident(&snake_case(&param.name), "parameter")?;
                if let Some(previous) = request_fields.insert(name.clone(), param.name.clone()) {
                    contract_bail!(
                        "parameters `{previous}` and `{}` of `{}#{}` both map to `{name}`",
                        param.name,
                        interface.name,
                        function.name
                    );
                }
            }
        }
    }
    if !model.dependencies.is_empty() {
        let header = header_for(&model.package.namespace, &model.package.name);
        let _ = emit_dependency_glue(&header, &model.dependencies, "crate::plain", "crate::proto")?;
    }
    Ok(())
}

/// Emit one major's glue module.
///
/// # Errors
///
/// Returns a [`ContractError`](crate::ContractError) for a generated module name collision or a
/// WIT name with no Rust spelling, and a plain error for an invalid module root or a missing
/// lockfile entry.
pub fn emit_version(
    model: &Model,
    lock: &WireLock,
    plain_root: &str,
    proto_root: &str,
) -> Result<String> {
    emit_version_with_options(model, lock, plain_root, proto_root, &GlueOptions::default())
}

/// Emit one major's glue module with explicit [`GlueOptions`] (such as `no_std` + `alloc` paths).
///
/// # Errors
///
/// Returns the same errors as [`emit_version`].
pub fn emit_version_with_options(
    model: &Model,
    lock: &WireLock,
    plain_root: &str,
    proto_root: &str,
    options: &GlueOptions,
) -> Result<String> {
    let mut emitter = Emitter::new(model, lock, plain_root, proto_root)?;
    emitter.no_std = options.no_std;
    crate::emit::proto::emit_major(model, lock)?;
    emitter.emit()
}

struct Emitter<'a> {
    model: &'a Model,
    lock: &'a WireLock,
    plain_root: String,
    proto_root: String,
    major: u64,
    minor: u64,
    root_major: u64,
    dep_layout: Option<&'a DepLayout>,
    dep_scoped: bool,
    type_prefix: String,
    plain_base_override: Option<String>,
    proto_base_override: Option<String>,
    dependency: bool,
    base_indent: usize,
    no_std: bool,
}

impl<'a> Emitter<'a> {
    const fn string_ty(&self) -> &'static str {
        if self.no_std {
            "::alloc::string::String"
        } else {
            "::std::string::String"
        }
    }

    const fn vec_ty(&self) -> &'static str {
        if self.no_std {
            "::alloc::vec::Vec"
        } else {
            "::std::vec::Vec"
        }
    }

    fn new(
        model: &'a Model,
        lock: &'a WireLock,
        plain_root: &str,
        proto_root: &str,
    ) -> Result<Self> {
        let mut generated_modules = BTreeSet::new();
        collect_model_module_names(model, &mut generated_modules);
        validate_module_root_against_generated(plain_root, &generated_modules)?;
        validate_module_root_against_generated(proto_root, &generated_modules)?;
        let proto_base_override = if model.dependencies.is_empty() {
            None
        } else {
            Some(dependency_proto_base(
                proto_root,
                &model.package.namespace,
                &model.package.name,
                model.package.version.major,
            ))
        };
        Ok(Self {
            model,
            lock,
            plain_root: plain_root.to_string(),
            proto_root: proto_root.to_string(),
            major: model.package.version.major,
            minor: model.package.version.minor,
            root_major: model.package.version.major,
            dep_layout: None,
            dep_scoped: false,
            type_prefix: "super::super".to_string(),
            plain_base_override: None,
            proto_base_override,
            dependency: false,
            base_indent: 0,
            no_std: false,
        })
    }

    #[allow(clippy::too_many_arguments)]
    fn new_dependency(
        model: &'a Model,
        lock: &'a WireLock,
        plain_root: &str,
        proto_root: &str,
        dependency: &Dependency,
        base_indent: usize,
        root_major: u64,
        dep_layout: Option<&'a DepLayout>,
        dep_scoped: bool,
    ) -> Result<Self> {
        let mut emitter = Self::new(model, lock, plain_root, proto_root)?;
        let dep_mod =
            dependency_module_name(&dependency.package.namespace, &dependency.package.name)?;
        emitter.plain_base_override = Some(if dep_scoped {
            format!(
                "{}::witforge_deps::v{root_major}::{dep_mod}",
                emitter.plain_root
            )
        } else {
            format!("{}::witforge_deps::{dep_mod}", emitter.plain_root)
        });
        emitter.proto_base_override = Some(dep_layout.map_or_else(
            || {
                dependency_proto_base(
                    &emitter.proto_root,
                    &dependency.package.namespace,
                    &dependency.package.name,
                    dependency.package.version.major,
                )
            },
            |layout| layout.prost_base(&emitter.proto_root, root_major, dependency),
        ));
        emitter.root_major = root_major;
        emitter.dep_layout = dep_layout;
        emitter.dep_scoped = dep_scoped;
        emitter.dependency = true;
        emitter.base_indent = base_indent;
        Ok(emitter)
    }

    fn is_dep_scoped(&self, namespace: &str, package: &str) -> bool {
        self.dep_layout
            .is_some_and(|layout| layout.is_scoped(namespace, package))
    }

    fn dep_prost_base(&self, dependency: &Dependency) -> String {
        self.dep_layout.map_or_else(
            || {
                dependency_proto_base(
                    &self.proto_root,
                    &dependency.package.namespace,
                    &dependency.package.name,
                    dependency.package.version.major,
                )
            },
            |layout| layout.prost_base(&self.proto_root, self.root_major, dependency),
        )
    }

    fn with_type_prefix(&self, prefix: &str) -> Self {
        Self {
            model: self.model,
            lock: self.lock,
            plain_root: self.plain_root.clone(),
            proto_root: self.proto_root.clone(),
            major: self.major,
            minor: self.minor,
            root_major: self.root_major,
            dep_layout: self.dep_layout,
            dep_scoped: self.dep_scoped,
            type_prefix: prefix.to_string(),
            plain_base_override: self.plain_base_override.clone(),
            proto_base_override: self.proto_base_override.clone(),
            dependency: self.dependency,
            base_indent: self.base_indent,
            no_std: self.no_std,
        }
    }

    fn emit(&self) -> Result<String> {
        let mut out = String::new();
        writeln!(
            out,
            "{}",
            header_for(&self.model.package.namespace, &self.model.package.name)
        )?;
        writeln!(
            out,
            "// source: {}:{}@{}",
            self.model.package.namespace, self.model.package.name, self.model.package.version
        )?;
        if self.no_std {
            writeln!(
                out,
                "// no_std output requires `extern crate alloc;` in the consuming crate."
            )?;
        }
        if model_has_deprecation(self.model) {
            writeln!(out, "#![allow(deprecated)]")?;
        }
        let body = self.emit_body()?;
        let has_docs = !docs::sanitize_rust_lines(&self.model.package.docs).is_empty();
        if has_docs {
            writeln!(out)?;
            docs::write_rust_inner(&mut out, &self.model.package.docs)?;
        }
        if !body.is_empty() {
            writeln!(out)?;
            out.push_str(&body);
        }
        if !out.ends_with('\n') {
            out.push('\n');
        }
        Ok(out)
    }

    fn emit_body(&self) -> Result<String> {
        self.check_module_names()?;
        let mut out = String::new();
        let pad = " ".repeat(self.base_indent);
        let iface_pad = " ".repeat(self.base_indent + 4);
        let type_pad = " ".repeat(self.base_indent + 8);
        let needs_error = self
            .model
            .interfaces
            .iter()
            .any(|interface| !interface.types.is_empty() || !interface.functions.is_empty());
        let mut wrote_item = false;
        if needs_error {
            writeln!(out, "{pad}use super::GlueError;")?;
            wrote_item = true;
        }
        for interface in &self.model.interfaces {
            let module = rust_ident(&snake_case(&interface.name), "interface module")?;
            if wrote_item {
                writeln!(out)?;
            }
            wrote_item = true;
            let fallback = format!("Protobuf glue for interface `{}`.", interface.name);
            rustfmt::write_docs_or(&mut out, self.base_indent, &interface.docs, &fallback)?;
            let parent_module = if self.dependency {
                dependency_module_name(&self.model.package.namespace, &self.model.package.name)?
            } else {
                format!("v{}", self.major)
            };
            if module == parent_module {
                writeln!(out, "{pad}#[allow(clippy::module_inception)]")?;
            }
            if interface.types.is_empty() && interface.functions.is_empty() {
                writeln!(out, "{pad}pub mod {module} {{}}")?;
                continue;
            }
            writeln!(out, "{pad}pub mod {module} {{")?;
            writeln!(out, "{iface_pad}use super::GlueError;")?;
            for def in &interface.types {
                let type_module = rust_ident(&snake_case(&def.name), "type module")?;
                writeln!(out)?;
                let fallback = format!("Protobuf glue for `{}/{}`.", interface.name, def.name);
                rustfmt::write_docs_or(&mut out, self.base_indent + 4, &def.docs, &fallback)?;
                if type_module == module {
                    writeln!(out, "{iface_pad}#[allow(clippy::module_inception)]")?;
                }
                writeln!(out, "{iface_pad}pub mod {type_module} {{")?;
                writeln!(out, "{type_pad}use super::GlueError;")?;
                self.emit_type(&mut out, interface, def)?;
                writeln!(out, "{iface_pad}}}")?;
            }
            if !interface.functions.is_empty() {
                self.emit_functions(&mut out, interface)?;
            }
            writeln!(out, "{pad}}}")?;
        }
        Ok(out)
    }

    fn check_module_names(&self) -> Result<()> {
        let mut interfaces = BTreeMap::new();
        for interface in &self.model.interfaces {
            let module = rust_ident(&snake_case(&interface.name), "interface module")?;
            if let Some(previous) = interfaces.insert(module.clone(), interface.name.clone()) {
                contract_bail!(
                    "glue interface modules `{previous}` and `{}` both map to `{module}`",
                    interface.name
                );
            }
            let mut types = BTreeMap::new();
            for def in &interface.types {
                let module = rust_ident(&snake_case(&def.name), "type module")?;
                if module == "functions" {
                    contract_bail!(
                        "type `{}/{}` maps to reserved glue module `functions`",
                        interface.name,
                        def.name
                    );
                }
                if let Some(previous) = types.insert(module.clone(), def.name.clone()) {
                    contract_bail!(
                        "type modules `{previous}` and `{}` in interface `{}` both map to `{module}`",
                        def.name,
                        interface.name
                    );
                }
            }
            let mut functions = BTreeMap::new();
            for function in &interface.functions {
                let module = rust_ident(&snake_case(&function.name), "function module")?;
                if let Some(previous) = functions.insert(module.clone(), function.name.clone()) {
                    contract_bail!(
                        "function modules `{previous}` and `{}` in interface `{}` both map to `{module}`",
                        function.name,
                        interface.name
                    );
                }
            }
        }
        Ok(())
    }

    fn plain_base(&self) -> String {
        self.plain_base_override
            .clone()
            .unwrap_or_else(|| format!("{}::v{}_{}", self.plain_root, self.major, self.minor))
    }

    fn proto_base(&self) -> String {
        self.proto_base_override
            .clone()
            .unwrap_or_else(|| format!("{}::v{}", self.proto_root, self.major))
    }

    fn plain_type(&self, ty: &TypeExpr) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok("bool".to_string()),
            TypeExpr::U8 => Ok("u8".to_string()),
            TypeExpr::U16 => Ok("u16".to_string()),
            TypeExpr::U32 => Ok("u32".to_string()),
            TypeExpr::U64 => Ok("u64".to_string()),
            TypeExpr::S8 => Ok("i8".to_string()),
            TypeExpr::S16 => Ok("i16".to_string()),
            TypeExpr::S32 => Ok("i32".to_string()),
            TypeExpr::S64 => Ok("i64".to_string()),
            TypeExpr::F32 => Ok("f32".to_string()),
            TypeExpr::F64 => Ok("f64".to_string()),
            TypeExpr::String => Ok(self.string_ty().to_string()),
            TypeExpr::Named(name) => self.plain_named(name),
            TypeExpr::List(element) => {
                if self.model.resolves_to_u8(element) {
                    Ok(format!("{}<u8>", self.vec_ty()))
                } else {
                    Ok(format!("{}<{}>", self.vec_ty(), self.plain_type(element)?))
                }
            }
            TypeExpr::Option(payload) => Ok(format!(
                "::core::option::Option<{}>",
                self.plain_type(payload)?
            )),
            TypeExpr::Result(result) => Ok(format!(
                "::core::result::Result<{}, {}>",
                self.plain_slot(result.ok.as_deref())?,
                self.plain_slot(result.err.as_deref())?
            )),
        }
    }

    fn plain_slot(&self, slot: Option<&TypeExpr>) -> Result<String> {
        slot.map_or_else(|| Ok("()".to_string()), |ty| self.plain_type(ty))
    }

    fn foreign_type_def<'b>(
        &'b self,
        context: Option<&'b Dependency>,
        name: &QualifiedName,
    ) -> Result<Option<(&'b Dependency, &'b TypeDef)>> {
        if let Some((namespace, package)) = name.package() {
            let dependency = self
                .model
                .dependency_package(namespace, package)
                .with_context(|| {
                    format!("dependency `{namespace}:{package}` is not in the model")
                })?;
            let def = dependency
                .interfaces
                .iter()
                .find(|interface| interface.name == name.interface_name())
                .and_then(|interface| interface.types.iter().find(|def| def.name == name.name))
                .with_context(|| format!("named type `{name}` is not in the dependency model"))?;
            return Ok(Some((dependency, def)));
        }
        let Some(dependency) = context else {
            return Ok(None);
        };
        let def = dependency
            .interfaces
            .iter()
            .find(|interface| interface.name == name.interface_name())
            .and_then(|interface| interface.types.iter().find(|def| def.name == name.name))
            .with_context(|| format!("named type `{name}` is not in the dependency model"))?;
        Ok(Some((dependency, def)))
    }

    fn is_same_package(&self, a: Option<&Dependency>, b: Option<&Dependency>) -> bool {
        let pkg_a = a.map_or(&self.model.package, |dep| &dep.package);
        let pkg_b = b.map_or(&self.model.package, |dep| &dep.package);
        pkg_a.namespace == pkg_b.namespace && pkg_a.name == pkg_b.name
    }

    fn dependency_proto_path(&self, dependency: &Dependency, proto_name: &str) -> String {
        let rust_name = ident::prost_type_ident(proto_name);
        format!("{}::{rust_name}", self.dep_prost_base(dependency))
    }

    fn resolve_type_def<'b>(
        &'b self,
        context: Option<&'b Dependency>,
        name: &QualifiedName,
    ) -> Result<(Option<&'b Dependency>, &'b TypeDef)> {
        if let Some((dep, def)) = self.foreign_type_def(context, name)? {
            return Ok((Some(dep), def));
        }
        Ok((None, self.named(name)?))
    }

    fn resolve_foreign_named(
        &self,
        ty: &TypeExpr,
    ) -> Result<Option<(Dependency, QualifiedName, TypeDefKind)>> {
        match ty {
            TypeExpr::Named(name) => {
                if name.is_foreign() {
                    let (dep, def) = self
                        .foreign_type_def(None, name)?
                        .context("foreign type needs a dependency package")?;
                    match &def.kind {
                        TypeDefKind::Alias(target) => {
                            let qualified = qualify_type(Some(dep), target);
                            self.resolve_foreign_named(&qualified)
                        }
                        other => Ok(Some((dep.clone(), name.clone(), other.clone()))),
                    }
                } else {
                    match &self.named(name)?.kind {
                        TypeDefKind::Alias(target) => self.resolve_foreign_named(target),
                        _ => Ok(None),
                    }
                }
            }
            _ => Ok(None),
        }
    }

    /// Resolve the singular prost Rust type emitted inside `owner`'s own proto package for `ty`
    /// (written inside `owner`), matching `proto.rs::dependency_defined_singular`.
    #[allow(clippy::too_many_lines)]
    fn dependency_defined_proto_singular(
        &self,
        owner: &Dependency,
        ty: &TypeExpr,
    ) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok("bool".to_string()),
            TypeExpr::U8 | TypeExpr::U16 | TypeExpr::U32 => Ok("u32".to_string()),
            TypeExpr::U64 => Ok("u64".to_string()),
            TypeExpr::S8 | TypeExpr::S16 | TypeExpr::S32 => Ok("i32".to_string()),
            TypeExpr::S64 => Ok("i64".to_string()),
            TypeExpr::F32 => Ok("f32".to_string()),
            TypeExpr::F64 => Ok("f64".to_string()),
            TypeExpr::String => Ok(self.string_ty().to_string()),
            TypeExpr::List(element) if self.model.resolves_to_u8_in(Some(owner), element) => {
                Ok(format!("{}<u8>", self.vec_ty()))
            }
            TypeExpr::List(element) => {
                let name = format!(
                    "WitforgeListOf{}",
                    self.owner_shape_name_ty(Some(owner), element)?
                );
                Ok(self.dependency_proto_path(owner, &name))
            }
            TypeExpr::Option(payload) => {
                let name = format!(
                    "WitforgeOptionOf{}",
                    self.owner_shape_name_ty(Some(owner), payload)?
                );
                Ok(self.dependency_proto_path(owner, &name))
            }
            TypeExpr::Result(result) => {
                let name = format!(
                    "Witforge{}",
                    self.owner_result_shape_name(Some(owner), result)?
                );
                Ok(self.dependency_proto_path(owner, &name))
            }
            TypeExpr::Named(name) => {
                let (target_dep, def) = self.resolve_type_def(Some(owner), name)?;
                if self.is_same_package(Some(owner), target_dep) {
                    match &def.kind {
                        TypeDefKind::Alias(target) => {
                            self.dependency_defined_proto_singular(owner, target)
                        }
                        TypeDefKind::Enum(_) => Ok("i32".to_string()),
                        TypeDefKind::Record(_)
                        | TypeDefKind::Variant(_)
                        | TypeDefKind::Flags(_)
                        | TypeDefKind::Result(_) => Ok(self.dependency_proto_type(name, owner)),
                        TypeDefKind::List(element)
                            if self.model.resolves_to_u8_in(Some(owner), element) =>
                        {
                            Ok(format!("{}<u8>", self.vec_ty()))
                        }
                        TypeDefKind::List(element) => {
                            let wrapper = format!(
                                "WitforgeListOf{}",
                                self.owner_shape_name_ty(Some(owner), element)?
                            );
                            Ok(self.dependency_proto_path(owner, &wrapper))
                        }
                        TypeDefKind::Option(payload) => {
                            let wrapper = if matches!(
                                self.foreign_form_expr(Some(owner), payload)?,
                                Form::List | Form::Option
                            ) {
                                format!(
                                    "WitforgeOptionOf{}",
                                    ident::proto_type_name(name.interface_name(), &name.name)
                                )
                            } else {
                                format!(
                                    "WitforgeOptionOf{}",
                                    self.owner_shape_name_ty(Some(owner), payload)?
                                )
                            };
                            Ok(self.dependency_proto_path(owner, &wrapper))
                        }
                    }
                } else {
                    let other = target_dep.context("foreign type has no dependency context")?;
                    match &def.kind {
                        TypeDefKind::Alias(target) => {
                            let qualified = qualify_type(Some(other), target);
                            self.dependency_defined_proto_singular(owner, &qualified)
                        }
                        TypeDefKind::Enum(_) => Ok("i32".to_string()),
                        TypeDefKind::Record(_)
                        | TypeDefKind::Variant(_)
                        | TypeDefKind::Flags(_)
                        | TypeDefKind::Result(_) => Ok(self.dependency_proto_type(name, other)),
                        TypeDefKind::List(element)
                            if self.model.resolves_to_u8_in(Some(other), element) =>
                        {
                            Ok(format!("{}<u8>", self.vec_ty()))
                        }
                        TypeDefKind::List(_) | TypeDefKind::Option(_) => {
                            let shape = self.foreign_shape_name_for_caller(
                                Some(owner),
                                other,
                                name,
                                &def.kind,
                            )?;
                            let wrapper = format!("Witforge{shape}");
                            Ok(self.dependency_proto_path(owner, &wrapper))
                        }
                    }
                }
            }
        }
    }

    fn element_uses_dependency_wrapper(&self, owner: &Dependency, ty: &TypeExpr) -> Result<bool> {
        match ty {
            TypeExpr::Bool
            | TypeExpr::U8
            | TypeExpr::U16
            | TypeExpr::U32
            | TypeExpr::U64
            | TypeExpr::S8
            | TypeExpr::S16
            | TypeExpr::S32
            | TypeExpr::S64
            | TypeExpr::F32
            | TypeExpr::F64
            | TypeExpr::String => Ok(false),
            TypeExpr::List(element) => Ok(!self.model.resolves_to_u8_in(Some(owner), element)),
            TypeExpr::Option(_) | TypeExpr::Result(_) => Ok(true),
            TypeExpr::Named(name) => {
                let (resolved_dep, def) = self.resolve_type_def(Some(owner), name)?;
                match &def.kind {
                    TypeDefKind::Alias(target) => {
                        let next_owner = resolved_dep.unwrap_or(owner);
                        self.element_uses_dependency_wrapper(next_owner, target)
                    }
                    TypeDefKind::List(element) => {
                        Ok(!self.model.resolves_to_u8_in(resolved_dep, element))
                    }
                    TypeDefKind::Option(_) => Ok(true),
                    TypeDefKind::Record(_)
                    | TypeDefKind::Variant(_)
                    | TypeDefKind::Enum(_)
                    | TypeDefKind::Flags(_)
                    | TypeDefKind::Result(_) => Ok(false),
                }
            }
        }
    }

    fn foreign_proto_type(&self, name: &QualifiedName) -> Result<String> {
        let (dependency, def) = self
            .foreign_type_def(None, name)?
            .context("foreign type needs a dependency package")?;
        self.foreign_proto_type_in(Some(dependency), name, &def.kind)
    }

    fn foreign_proto_type_in(
        &self,
        context: Option<&Dependency>,
        name: &QualifiedName,
        kind: &TypeDefKind,
    ) -> Result<String> {
        let owner = context.context("foreign type has no dependency context")?;
        match kind {
            TypeDefKind::Enum(_) => Ok("i32".to_string()),
            TypeDefKind::Alias(target) => self.foreign_proto_type_expr(Some(owner), target),
            TypeDefKind::List(element) if self.model.resolves_to_u8_in(Some(owner), element) => {
                Ok(format!("{}<u8>", self.vec_ty()))
            }
            TypeDefKind::List(element) => Ok(format!(
                "{}<{}>",
                self.vec_ty(),
                self.dependency_defined_proto_singular(owner, element)?
            )),
            TypeDefKind::Option(payload) => {
                let inner = match self.foreign_form_expr(Some(owner), payload)? {
                    Form::List | Form::Option => self.dependency_proto_type(name, owner),
                    Form::Scalar | Form::Bytes | Form::Enum | Form::Message => {
                        self.dependency_defined_proto_singular(owner, payload)?
                    }
                };
                Ok(format!("::core::option::Option<{inner}>"))
            }
            TypeDefKind::Record(_)
            | TypeDefKind::Variant(_)
            | TypeDefKind::Flags(_)
            | TypeDefKind::Result(_) => Ok(self.dependency_proto_type(name, owner)),
        }
    }

    fn foreign_proto_type_expr(
        &self,
        context: Option<&Dependency>,
        ty: &TypeExpr,
    ) -> Result<String> {
        let owner = context.context("foreign type expression has no dependency context")?;
        match ty {
            TypeExpr::Named(name) => {
                if name.package().is_some() {
                    self.foreign_proto_type(name)
                } else {
                    let (dependency, def) = self
                        .foreign_type_def(Some(owner), name)?
                        .context("foreign alias target has no dependency context")?;
                    self.foreign_proto_type_in(Some(dependency), name, &def.kind)
                }
            }
            TypeExpr::List(element) if self.model.resolves_to_u8_in(Some(owner), element) => {
                Ok(format!("{}<u8>", self.vec_ty()))
            }
            TypeExpr::List(element) => Ok(format!(
                "{}<{}>",
                self.vec_ty(),
                self.dependency_defined_proto_singular(owner, element)?
            )),
            TypeExpr::Option(payload) => Ok(format!(
                "::core::option::Option<{}>",
                self.dependency_defined_proto_singular(owner, payload)?
            )),
            TypeExpr::Bool => Ok("bool".to_string()),
            TypeExpr::U8 | TypeExpr::U16 | TypeExpr::U32 => Ok("u32".to_string()),
            TypeExpr::U64 => Ok("u64".to_string()),
            TypeExpr::S8 | TypeExpr::S16 | TypeExpr::S32 => Ok("i32".to_string()),
            TypeExpr::S64 => Ok("i64".to_string()),
            TypeExpr::F32 => Ok("f32".to_string()),
            TypeExpr::F64 => Ok("f64".to_string()),
            TypeExpr::String => Ok(self.string_ty().to_string()),
            TypeExpr::Result(result) => {
                let name = format!(
                    "Witforge{}",
                    self.owner_result_shape_name(Some(owner), result)?
                );
                Ok(self.dependency_proto_path(owner, &name))
            }
        }
    }

    fn foreign_proto_singular(&self, name: &QualifiedName) -> Result<String> {
        let (dependency, def) = self
            .foreign_type_def(None, name)?
            .context("foreign type needs a dependency package")?;
        self.foreign_proto_singular_in(Some(dependency), name, &def.kind)
    }

    fn foreign_proto_singular_in(
        &self,
        context: Option<&Dependency>,
        name: &QualifiedName,
        kind: &TypeDefKind,
    ) -> Result<String> {
        let owner = context.context("foreign type has no dependency context")?;
        match kind {
            TypeDefKind::Enum(_) => Ok("i32".to_string()),
            TypeDefKind::Alias(target) => {
                let qualified = qualify_type(Some(owner), target);
                self.proto_singular_type(&qualified)
            }
            TypeDefKind::List(element) if self.model.resolves_to_u8_in(Some(owner), element) => {
                Ok(format!("{}<u8>", self.vec_ty()))
            }
            TypeDefKind::List(_) | TypeDefKind::Option(_) => {
                let shape = self.foreign_shape_name_for_caller(None, owner, name, kind)?;
                let wrapper_name = format!("Witforge{shape}");
                Ok(self.proto_user_type_path(&wrapper_name))
            }
            TypeDefKind::Record(_)
            | TypeDefKind::Variant(_)
            | TypeDefKind::Flags(_)
            | TypeDefKind::Result(_) => Ok(self.dependency_proto_type(name, owner)),
        }
    }

    fn foreign_shape_name(&self, name: &QualifiedName) -> Result<String> {
        let (dependency, def) = self
            .foreign_type_def(None, name)?
            .context("foreign type needs a dependency package")?;
        self.foreign_shape_name_for_caller(None, dependency, name, &def.kind)
    }

    fn owner_shape_name_ty(&self, owner: Option<&Dependency>, ty: &TypeExpr) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok("Bool".to_string()),
            TypeExpr::U8 => Ok("U8".to_string()),
            TypeExpr::U16 => Ok("U16".to_string()),
            TypeExpr::U32 => Ok("U32".to_string()),
            TypeExpr::U64 => Ok("U64".to_string()),
            TypeExpr::S8 => Ok("S8".to_string()),
            TypeExpr::S16 => Ok("S16".to_string()),
            TypeExpr::S32 => Ok("S32".to_string()),
            TypeExpr::S64 => Ok("S64".to_string()),
            TypeExpr::F32 => Ok("F32".to_string()),
            TypeExpr::F64 => Ok("F64".to_string()),
            TypeExpr::String => Ok("String".to_string()),
            TypeExpr::List(element) => Ok(format!(
                "ListOf{}",
                self.owner_shape_name_ty(owner, element)?
            )),
            TypeExpr::Option(payload) => Ok(format!(
                "OptionOf{}",
                self.owner_shape_name_ty(owner, payload)?
            )),
            TypeExpr::Result(result) => self.owner_result_shape_name(owner, result),
            TypeExpr::Named(name) => {
                let (target_dep, def) = self.resolve_type_def(owner, name)?;
                if self.is_same_package(owner, target_dep) {
                    match &def.kind {
                        TypeDefKind::Alias(target) => self.owner_shape_name_ty(owner, target),
                        TypeDefKind::List(element) => Ok(format!(
                            "ListOf{}",
                            self.owner_shape_name_ty(owner, element)?
                        )),
                        TypeDefKind::Option(payload) => {
                            if matches!(
                                self.foreign_form_expr(owner, payload)?,
                                Form::List | Form::Option
                            ) {
                                Ok(format!(
                                    "OptionOf{}",
                                    ident::proto_type_name(name.interface_name(), &name.name)
                                ))
                            } else {
                                Ok(format!(
                                    "OptionOf{}",
                                    self.owner_shape_name_ty(owner, payload)?
                                ))
                            }
                        }
                        TypeDefKind::Result(result) => self.owner_result_shape_name(owner, result),
                        TypeDefKind::Record(_)
                        | TypeDefKind::Variant(_)
                        | TypeDefKind::Enum(_)
                        | TypeDefKind::Flags(_) => {
                            Ok(ident::proto_type_name(name.interface_name(), &name.name))
                        }
                    }
                } else {
                    let dep = target_dep.context("foreign type has no dependency context")?;
                    self.foreign_shape_name_for_caller(owner, dep, name, &def.kind)
                }
            }
        }
    }

    fn owner_result_shape_name(
        &self,
        owner: Option<&Dependency>,
        result: &ResultExpr,
    ) -> Result<String> {
        let ok = match &result.ok {
            Some(ty) => self.owner_shape_name_ty(owner, ty)?,
            None => "Empty".to_string(),
        };
        let err = match &result.err {
            Some(ty) => self.owner_shape_name_ty(owner, ty)?,
            None => "Empty".to_string(),
        };
        Ok(format!("ResultOf{ok}And{err}"))
    }

    fn foreign_shape_name_for_caller(
        &self,
        caller: Option<&Dependency>,
        owner: &Dependency,
        name: &QualifiedName,
        kind: &TypeDefKind,
    ) -> Result<String> {
        match kind {
            TypeDefKind::Alias(target) => self.foreign_shape_name_expr(caller, owner, target),
            TypeDefKind::List(element) => {
                if self.element_uses_dependency_wrapper(owner, element)? {
                    Ok(format!(
                        "ListOf{}{}",
                        dependency_pkg_prefix(owner),
                        self.owner_shape_name_ty(Some(owner), element)?
                    ))
                } else {
                    Ok(format!(
                        "ListOf{}",
                        self.foreign_shape_name_expr(caller, owner, element)?
                    ))
                }
            }
            TypeDefKind::Option(payload) => {
                if matches!(
                    self.foreign_form_expr(Some(owner), payload)?,
                    Form::List | Form::Option
                ) {
                    Ok(format!("OptionOf{}", dependency_shape_name(owner, name)))
                } else {
                    Ok(format!(
                        "OptionOf{}",
                        self.foreign_shape_name_expr(caller, owner, payload)?
                    ))
                }
            }
            TypeDefKind::Result(result) => self.foreign_result_shape_name(caller, owner, result),
            TypeDefKind::Record(_)
            | TypeDefKind::Variant(_)
            | TypeDefKind::Enum(_)
            | TypeDefKind::Flags(_) => Ok(dependency_shape_name(owner, name)),
        }
    }

    fn foreign_shape_name_expr(
        &self,
        caller: Option<&Dependency>,
        owner: &Dependency,
        ty: &TypeExpr,
    ) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok("Bool".to_string()),
            TypeExpr::U8 => Ok("U8".to_string()),
            TypeExpr::U16 => Ok("U16".to_string()),
            TypeExpr::U32 => Ok("U32".to_string()),
            TypeExpr::U64 => Ok("U64".to_string()),
            TypeExpr::S8 => Ok("S8".to_string()),
            TypeExpr::S16 => Ok("S16".to_string()),
            TypeExpr::S32 => Ok("S32".to_string()),
            TypeExpr::S64 => Ok("S64".to_string()),
            TypeExpr::F32 => Ok("F32".to_string()),
            TypeExpr::F64 => Ok("F64".to_string()),
            TypeExpr::String => Ok("String".to_string()),
            TypeExpr::List(element) => Ok(format!(
                "ListOf{}",
                self.foreign_shape_name_expr(caller, owner, element)?
            )),
            TypeExpr::Option(payload) => Ok(format!(
                "OptionOf{}",
                self.foreign_shape_name_expr(caller, owner, payload)?
            )),
            TypeExpr::Result(result) => self.foreign_result_shape_name(caller, owner, result),
            TypeExpr::Named(name) => {
                let (target_dep, def) = self.resolve_type_def(Some(owner), name)?;
                let dep = target_dep.context("foreign type has no dependency context")?;
                self.foreign_shape_name_for_caller(caller, dep, name, &def.kind)
            }
        }
    }

    fn foreign_result_shape_name(
        &self,
        caller: Option<&Dependency>,
        owner: &Dependency,
        result: &ResultExpr,
    ) -> Result<String> {
        let ok = match &result.ok {
            Some(ty) => self.foreign_shape_name_expr(caller, owner, ty)?,
            None => "Empty".to_string(),
        };
        let err = match &result.err {
            Some(ty) => self.foreign_shape_name_expr(caller, owner, ty)?,
            None => "Empty".to_string(),
        };
        Ok(format!("ResultOf{ok}And{err}"))
    }

    fn dependency_proto_type(&self, name: &QualifiedName, dependency: &Dependency) -> String {
        let proto_name = ident::proto_type_name(name.interface_name(), &name.name);
        let rust_name = ident::prost_type_ident(&proto_name);
        format!("{}::{rust_name}", self.dep_prost_base(dependency))
    }

    fn foreign_form(&self, name: &QualifiedName) -> Result<Form> {
        let (dependency, def) = self
            .foreign_type_def(None, name)?
            .context("foreign type needs a dependency package")?;
        self.foreign_form_kind(Some(dependency), &def.kind)
    }

    fn foreign_form_kind(&self, context: Option<&Dependency>, kind: &TypeDefKind) -> Result<Form> {
        match kind {
            TypeDefKind::Alias(target) => self.foreign_form_expr(context, target),
            TypeDefKind::Enum(_) => Ok(Form::Enum),
            TypeDefKind::List(element) if self.model.resolves_to_u8_in(context, element) => {
                Ok(Form::Bytes)
            }
            TypeDefKind::List(_) => Ok(Form::List),
            TypeDefKind::Option(_) => Ok(Form::Option),
            TypeDefKind::Record(_)
            | TypeDefKind::Variant(_)
            | TypeDefKind::Flags(_)
            | TypeDefKind::Result(_) => Ok(Form::Message),
        }
    }

    fn foreign_form_expr(&self, context: Option<&Dependency>, ty: &TypeExpr) -> Result<Form> {
        match ty {
            TypeExpr::Named(name) => {
                if name.package().is_some() {
                    self.foreign_form(name)
                } else {
                    let (dependency, def) = self
                        .foreign_type_def(context, name)?
                        .context("foreign alias target has no dependency context")?;
                    self.foreign_form_kind(Some(dependency), &def.kind)
                }
            }
            TypeExpr::List(element) if self.model.resolves_to_u8_in(context, element) => {
                Ok(Form::Bytes)
            }
            TypeExpr::List(_) => Ok(Form::List),
            TypeExpr::Option(_) => Ok(Form::Option),
            TypeExpr::Result(_) => Ok(Form::Message),
            TypeExpr::Bool
            | TypeExpr::U8
            | TypeExpr::U16
            | TypeExpr::U32
            | TypeExpr::U64
            | TypeExpr::S8
            | TypeExpr::S16
            | TypeExpr::S32
            | TypeExpr::S64
            | TypeExpr::F32
            | TypeExpr::F64
            | TypeExpr::String => Ok(Form::Scalar),
        }
    }

    fn plain_named(&self, name: &QualifiedName) -> Result<String> {
        self.model.type_def(name).with_context(|| {
            format!(
                "named type `{}/{}` is not in the model",
                name.interface, name.name
            )
        })?;
        if let Some((namespace, package)) = name.package() {
            let pkg_mod = dependency_module_name(namespace, package)?;
            let interface = rust_ident(&snake_case(name.interface_name()), "interface module")?;
            let ty = rust_ident(&pascal_case(&name.name), "type")?;
            if self.is_dep_scoped(namespace, package) {
                return Ok(format!(
                    "{}::witforge_deps::v{}::{pkg_mod}::{interface}::{ty}",
                    self.plain_root, self.root_major
                ));
            }
            return Ok(format!(
                "{}::witforge_deps::{pkg_mod}::{interface}::{ty}",
                self.plain_root
            ));
        }
        let interface = rust_ident(&snake_case(&name.interface), "interface module")?;
        let ty = rust_ident(&pascal_case(&name.name), "type")?;
        Ok(format!("{}::{interface}::{ty}", self.plain_base()))
    }

    fn plain_type_module(&self, interface: &str, ty: &str) -> Result<String> {
        let interface = rust_ident(&snake_case(interface), "interface module")?;
        let ty = rust_ident(&snake_case(ty), "type module")?;
        Ok(format!("{}::{interface}::{ty}", self.type_prefix))
    }

    fn foreign_type_module(&self, name: &QualifiedName) -> Result<String> {
        let (namespace, package) = name
            .package()
            .context("foreign type module needs a dependency package")?;
        let pkg_mod = dependency_module_name(namespace, package)?;
        let interface = rust_ident(&snake_case(name.interface_name()), "interface module")?;
        let ty = rust_ident(&snake_case(&name.name), "type module")?;
        let target_scoped = self.is_dep_scoped(namespace, package);
        let base = if !self.dependency {
            if target_scoped {
                format!(
                    "{}::super::witforge_deps::v{}",
                    self.type_prefix, self.root_major
                )
            } else {
                format!("{}::super::witforge_deps", self.type_prefix)
            }
        } else if self.dep_scoped {
            if target_scoped {
                format!("{}::super", self.type_prefix)
            } else {
                format!("{}::super::super", self.type_prefix)
            }
        } else {
            format!("{}::super", self.type_prefix)
        };
        Ok(format!("{base}::{pkg_mod}::{interface}::{ty}"))
    }

    fn proto_type(&self, ty: &TypeExpr) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok("bool".to_string()),
            TypeExpr::U8 | TypeExpr::U16 | TypeExpr::U32 => Ok("u32".to_string()),
            TypeExpr::U64 => Ok("u64".to_string()),
            TypeExpr::S8 | TypeExpr::S16 | TypeExpr::S32 => Ok("i32".to_string()),
            TypeExpr::S64 => Ok("i64".to_string()),
            TypeExpr::F32 => Ok("f32".to_string()),
            TypeExpr::F64 => Ok("f64".to_string()),
            TypeExpr::String => Ok(self.string_ty().to_string()),
            TypeExpr::List(element) if self.model.resolves_to_u8(element) => {
                Ok(format!("{}<u8>", self.vec_ty()))
            }
            TypeExpr::List(element) => Ok(format!(
                "{}<{}>",
                self.vec_ty(),
                self.proto_singular_type(element)?
            )),
            TypeExpr::Option(payload) => Ok(format!(
                "::core::option::Option<{}>",
                self.proto_singular_type(payload)?
            )),
            TypeExpr::Result(_) => self.proto_wrapper_name(ty),
            TypeExpr::Named(name) => {
                if name.is_foreign() {
                    return self.foreign_proto_type(name);
                }
                let def = self.named(name)?;
                match &def.kind {
                    TypeDefKind::Alias(target) => self.proto_type(target),
                    TypeDefKind::Record(_)
                    | TypeDefKind::Variant(_)
                    | TypeDefKind::Flags(_)
                    | TypeDefKind::Result(_) => {
                        Ok(self.proto_user_type(&name.interface, &name.name))
                    }
                    TypeDefKind::Enum(_) => Ok("i32".to_string()),
                    TypeDefKind::List(element) if self.model.resolves_to_u8(element) => {
                        Ok(format!("{}<u8>", self.vec_ty()))
                    }
                    TypeDefKind::List(element) => Ok(format!(
                        "{}<{}>",
                        self.vec_ty(),
                        self.proto_singular_type(element)?
                    )),
                    TypeDefKind::Option(payload) => {
                        let inner = if matches!(self.form(payload)?, Form::List | Form::Option) {
                            self.proto_direct_wrapper(name)
                        } else {
                            self.proto_singular_type(payload)?
                        };
                        Ok(format!("::core::option::Option<{inner}>"))
                    }
                }
            }
        }
    }

    fn proto_singular_type(&self, ty: &TypeExpr) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok("bool".to_string()),
            TypeExpr::U8 | TypeExpr::U16 | TypeExpr::U32 => Ok("u32".to_string()),
            TypeExpr::U64 => Ok("u64".to_string()),
            TypeExpr::S8 | TypeExpr::S16 | TypeExpr::S32 => Ok("i32".to_string()),
            TypeExpr::S64 => Ok("i64".to_string()),
            TypeExpr::F32 => Ok("f32".to_string()),
            TypeExpr::F64 => Ok("f64".to_string()),
            TypeExpr::String => Ok(self.string_ty().to_string()),
            TypeExpr::List(element) if self.model.resolves_to_u8(element) => {
                Ok(format!("{}<u8>", self.vec_ty()))
            }
            TypeExpr::List(element) => {
                let name = format!("WitforgeListOf{}", self.shape_name(element)?);
                Ok(self.proto_user_type_path(&name))
            }
            TypeExpr::Option(payload) => {
                let name = format!("WitforgeOptionOf{}", self.shape_name(payload)?);
                Ok(self.proto_user_type_path(&name))
            }
            TypeExpr::Result(_) => self.proto_wrapper_name(ty),
            TypeExpr::Named(name) => {
                if name.is_foreign() {
                    return self.foreign_proto_singular(name);
                }
                let def = self.named(name)?;
                match &def.kind {
                    TypeDefKind::Alias(target) => self.proto_singular_type(target),
                    TypeDefKind::Record(_)
                    | TypeDefKind::Variant(_)
                    | TypeDefKind::Flags(_)
                    | TypeDefKind::Result(_) => {
                        Ok(self.proto_user_type(&name.interface, &name.name))
                    }
                    TypeDefKind::Enum(_) => Ok("i32".to_string()),
                    TypeDefKind::List(element) if self.model.resolves_to_u8(element) => {
                        Ok(format!("{}<u8>", self.vec_ty()))
                    }
                    TypeDefKind::List(element) => {
                        let name = format!("WitforgeListOf{}", self.shape_name(element)?);
                        Ok(self.proto_user_type_path(&name))
                    }
                    TypeDefKind::Option(payload) => {
                        let name = if matches!(self.form(payload)?, Form::List | Form::Option) {
                            format!("WitforgeOptionOf{}", Self::proto_direct_wrapper_name(name))
                        } else {
                            format!("WitforgeOptionOf{}", self.shape_name(payload)?)
                        };
                        Ok(self.proto_user_type_path(&name))
                    }
                }
            }
        }
    }

    fn proto_user_type(&self, interface: &str, ty: &str) -> String {
        let proto_name = ident::proto_type_name(interface, ty);
        self.proto_user_type_path(&proto_name)
    }

    fn proto_user_type_path(&self, proto_name: &str) -> String {
        let rust_name = ident::prost_type_ident(proto_name);
        format!("{}::{rust_name}", self.proto_base())
    }

    fn proto_direct_wrapper_name(name: &QualifiedName) -> String {
        ident::proto_type_name(&name.interface, &name.name)
    }

    fn proto_direct_wrapper(&self, name: &QualifiedName) -> String {
        self.proto_user_type(&name.interface, &name.name)
    }

    fn proto_wrapper_name(&self, ty: &TypeExpr) -> Result<String> {
        let name = match ty {
            TypeExpr::Result(result) => {
                format!(
                    "WitforgeResultOf{}And{}",
                    self.shape_slot(result.ok.as_deref())?,
                    self.shape_slot(result.err.as_deref())?
                )
            }
            _ => bail!("type `{ty:?}` has no anonymous proto wrapper"),
        };
        Ok(self.proto_user_type_path(&name))
    }

    fn proto_oneof(&self, proto_message: &str, proto_oneof: &str) -> String {
        let module = ident::prost_oneof_module(proto_message);
        let oneof = ident::prost_oneof_enum(proto_oneof);
        format!("{}::{module}::{oneof}", self.proto_base())
    }

    fn proto_empty(&self) -> String {
        self.proto_user_type_path("Empty")
    }

    fn form(&self, ty: &TypeExpr) -> Result<Form> {
        match ty {
            TypeExpr::Bool
            | TypeExpr::U8
            | TypeExpr::U16
            | TypeExpr::U32
            | TypeExpr::U64
            | TypeExpr::S8
            | TypeExpr::S16
            | TypeExpr::S32
            | TypeExpr::S64
            | TypeExpr::F32
            | TypeExpr::F64
            | TypeExpr::String => Ok(Form::Scalar),
            TypeExpr::List(element) if self.model.resolves_to_u8(element) => Ok(Form::Bytes),
            TypeExpr::List(_) => Ok(Form::List),
            TypeExpr::Option(_) => Ok(Form::Option),
            TypeExpr::Result(_) => Ok(Form::Message),
            TypeExpr::Named(name) => {
                if name.is_foreign() {
                    return self.foreign_form(name);
                }
                let def = self.named(name)?;
                match &def.kind {
                    TypeDefKind::Alias(target) => self.form(target),
                    TypeDefKind::Enum(_) => Ok(Form::Enum),
                    TypeDefKind::List(element) if self.model.resolves_to_u8(element) => {
                        Ok(Form::Bytes)
                    }
                    TypeDefKind::List(_) => Ok(Form::List),
                    TypeDefKind::Option(_) => Ok(Form::Option),
                    TypeDefKind::Record(_)
                    | TypeDefKind::Variant(_)
                    | TypeDefKind::Flags(_)
                    | TypeDefKind::Result(_) => Ok(Form::Message),
                }
            }
        }
    }

    fn shape_name(&self, ty: &TypeExpr) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok("Bool".to_string()),
            TypeExpr::U8 => Ok("U8".to_string()),
            TypeExpr::U16 => Ok("U16".to_string()),
            TypeExpr::U32 => Ok("U32".to_string()),
            TypeExpr::U64 => Ok("U64".to_string()),
            TypeExpr::S8 => Ok("S8".to_string()),
            TypeExpr::S16 => Ok("S16".to_string()),
            TypeExpr::S32 => Ok("S32".to_string()),
            TypeExpr::S64 => Ok("S64".to_string()),
            TypeExpr::F32 => Ok("F32".to_string()),
            TypeExpr::F64 => Ok("F64".to_string()),
            TypeExpr::String => Ok("String".to_string()),
            TypeExpr::List(element) => Ok(format!("ListOf{}", self.shape_name(element)?)),
            TypeExpr::Option(payload) => Ok(format!("OptionOf{}", self.shape_name(payload)?)),
            TypeExpr::Result(result) => Ok(format!(
                "ResultOf{}And{}",
                self.shape_slot(result.ok.as_deref())?,
                self.shape_slot(result.err.as_deref())?
            )),
            TypeExpr::Named(name) => {
                if name.is_foreign() {
                    return self.foreign_shape_name(name);
                }
                let def = self.named(name)?;
                match &def.kind {
                    TypeDefKind::Alias(target) => self.shape_name(target),
                    TypeDefKind::List(element) => {
                        Ok(format!("ListOf{}", self.shape_name(element)?))
                    }
                    TypeDefKind::Option(payload) => {
                        Ok(format!("OptionOf{}", self.shape_name(payload)?))
                    }
                    TypeDefKind::Result(result) => Ok(format!(
                        "ResultOf{}And{}",
                        self.shape_slot(result.ok.as_deref())?,
                        self.shape_slot(result.err.as_deref())?
                    )),
                    TypeDefKind::Record(_)
                    | TypeDefKind::Variant(_)
                    | TypeDefKind::Enum(_)
                    | TypeDefKind::Flags(_) => {
                        Ok(ident::proto_type_name(&name.interface, &name.name))
                    }
                }
            }
        }
    }

    fn shape_slot(&self, slot: Option<&TypeExpr>) -> Result<String> {
        slot.map_or_else(|| Ok("Empty".to_string()), |ty| self.shape_name(ty))
    }

    fn named(&self, name: &QualifiedName) -> Result<&TypeDef> {
        self.model.type_def(name).with_context(|| {
            format!(
                "named type `{}/{}` is not in the model",
                name.interface, name.name
            )
        })
    }

    fn number(&self, interface: &str, ty: &str, member: &str) -> Result<u32> {
        let key = format!(
            "{}:{}/{interface}/{ty}.{member}",
            self.model.package.namespace, self.model.package.name
        );
        self.lock
            .get(&key)
            .map(|entry| entry.number)
            .with_context(|| format!("lockfile has no number for `{key}`"))
    }
}

