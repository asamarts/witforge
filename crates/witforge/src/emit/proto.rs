//! Deterministic protobuf schema generation from the owned model.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use anyhow::{Context, Result, bail};

use crate::lock::{MemberKey, WireLock};
use crate::model::{
    Case, Field, Function, MemberKind, Model, QualifiedName, ResultExpr, TypeDef, TypeDefKind,
    TypeExpr,
};

/// The ownership header on every generated protobuf file.
pub const HEADER: &str = "// @generated by witforge; do not edit.";

const EMPTY: &str = "Empty";
const ONEOF_VALUE: &str = "witforge_value";

/// Emit one protobuf file for a model's major version.
///
/// Record, variant, enum, flags, named result, and synthesized list/option/result wrappers are
/// generated; functions are added by the function emitter.
///
/// # Errors
///
/// Returns an error for a missing lockfile entry, an invalid or colliding proto name, an unknown
/// named type, or a generated wrapper collision.
pub fn emit_major(model: &Model, lock: &WireLock) -> Result<String> {
    Emitter::new(model, lock)?.emit()
}

struct Emitter<'a> {
    model: &'a Model,
    lock: &'a WireLock,
    package: String,
    top_names: BTreeMap<String, String>,
    enum_values: BTreeMap<String, String>,
    wrappers: BTreeMap<String, String>,
    live_keys: BTreeSet<String>,
}

#[derive(Clone)]
enum WrapperKind {
    List(TypeExpr),
    OptionValue(String),
    Result(ResultExpr),
}

impl<'a> Emitter<'a> {
    fn new(model: &'a Model, lock: &'a WireLock) -> Result<Self> {
        let namespace = proto_ident(&model.package.namespace.replace('-', "_"), "namespace")?;
        let name = proto_ident(&model.package.name.replace('-', "_"), "package")?;
        let package = format!("{namespace}.{name}.v{}", model.package.version.major);
        let mut top_names = BTreeMap::new();
        top_names.insert(EMPTY.to_string(), "shared Empty message".to_string());
        let live_keys = model
            .members()?
            .into_iter()
            .map(|member| member.key())
            .collect();
        Ok(Self {
            model,
            lock,
            package,
            top_names,
            enum_values: BTreeMap::new(),
            wrappers: BTreeMap::new(),
            live_keys,
        })
    }

    fn emit(mut self) -> Result<String> {
        let mut out = String::new();
        writeln!(out, "{HEADER}")?;
        writeln!(
            out,
            "// source: {}:{}@{}",
            self.model.package.namespace, self.model.package.name, self.model.package.version
        )?;
        writeln!(out)?;
        writeln!(out, "syntax = \"proto3\";")?;
        writeln!(out)?;
        writeln!(out, "package {};", self.package)?;
        writeln!(out)?;
        writeln!(out, "message {EMPTY} {{}}")?;

        for interface in &self.model.interfaces {
            if !interface.docs.is_empty() {
                writeln!(out)?;
                write_docs(&mut out, 0, &interface.docs)?;
            }
            for def in &interface.types {
                self.emit_type(&mut out, &interface.name, def)?;
            }
        }

        for interface in &self.model.interfaces {
            for function in &interface.functions {
                self.emit_function(&mut out, &interface.name, function)?;
            }
            self.emit_method_enum(&mut out, &interface.name)?;
        }

        for body in self.wrappers.values() {
            writeln!(out)?;
            out.push_str(body);
        }
        if !out.ends_with('\n') {
            out.push('\n');
        }
        Ok(out)
    }

    fn emit_type(&mut self, out: &mut String, interface: &str, def: &TypeDef) -> Result<()> {
        match &def.kind {
            TypeDefKind::Record(fields) => self.emit_record(out, interface, def, fields),
            TypeDefKind::Variant(cases) => self.emit_variant(out, interface, def, cases),
            TypeDefKind::Enum(cases) => self.emit_enum(out, interface, def, cases),
            TypeDefKind::Flags(flags) => self.emit_flags(out, interface, def, flags),
            TypeDefKind::Result(result) => self.emit_result(out, interface, def, result),
            TypeDefKind::Alias(_) | TypeDefKind::List(_) | TypeDefKind::Option(_) => Ok(()),
        }
    }

    fn emit_record(
        &mut self,
        out: &mut String,
        interface: &str,
        def: &TypeDef,
        fields: &[Field],
    ) -> Result<()> {
        let name = self.user_name(interface, &def.name)?;
        writeln!(out)?;
        write_docs(out, 0, &def.docs)?;
        writeln!(out, "message {name} {{")?;
        let reserved = self.reserved_type(interface, &def.name, &[MemberKind::Field])?;
        let reserved_names: BTreeSet<String> =
            reserved.iter().map(|(_, name)| name.clone()).collect();
        let mut field_names = BTreeSet::new();
        let mut numbers = BTreeSet::new();
        for field in fields {
            let field_name = field_name(&field.name)?;
            if reserved_names.contains(&field_name) {
                bail!(
                    "record `{interface}/{}`: field `{field_name}` collides with a reserved name",
                    def.name
                );
            }
            if !field_names.insert(field_name.clone()) {
                bail!(
                    "record `{interface}/{}`: duplicate proto field `{field_name}`",
                    def.name
                );
            }
            let number = self.number(interface, &def.name, &field.name)?;
            if !numbers.insert(number) {
                bail!(
                    "record `{interface}/{}`: duplicate field number {number}",
                    def.name
                );
            }
            write_docs(out, 2, &field.docs)?;
            let ty = self.direct(&field.ty, true)?;
            writeln!(out, "  {ty} {field_name} = {number};")?;
        }
        Self::emit_reserved(out, 2, &reserved);
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_variant(
        &mut self,
        out: &mut String,
        interface: &str,
        def: &TypeDef,
        cases: &[Case],
    ) -> Result<()> {
        let name = self.user_name(interface, &def.name)?;
        writeln!(out)?;
        write_docs(out, 0, &def.docs)?;
        writeln!(out, "message {name} {{")?;
        writeln!(out, "  oneof {ONEOF_VALUE} {{")?;
        let reserved = self.reserved_type(interface, &def.name, &[MemberKind::VariantCase])?;
        let reserved_names: BTreeSet<String> =
            reserved.iter().map(|(_, name)| name.clone()).collect();
        let mut field_names = BTreeSet::new();
        let mut numbers = BTreeSet::new();
        for case in cases {
            let case_name = field_name(&case.name)?;
            if reserved_names.contains(&case_name) {
                bail!(
                    "variant `{interface}/{}`: case `{case_name}` collides with a reserved name",
                    def.name
                );
            }
            if case_name == ONEOF_VALUE {
                bail!(
                    "variant `{interface}/{}`: case `{case_name}` collides with oneof name",
                    def.name
                );
            }
            if !field_names.insert(case_name.clone()) {
                bail!(
                    "variant `{interface}/{}`: duplicate proto field `{case_name}`",
                    def.name
                );
            }
            let number = self.number(interface, &def.name, &case.name)?;
            if !numbers.insert(number) {
                bail!(
                    "variant `{interface}/{}`: duplicate field number {number}",
                    def.name
                );
            }
            write_docs(out, 4, &case.docs)?;
            let ty = match &case.payload {
                Some(payload) => self.singular(payload)?,
                None => EMPTY.to_string(),
            };
            writeln!(out, "    {ty} {case_name} = {number};")?;
        }
        writeln!(out, "  }}")?;
        Self::emit_reserved(out, 2, &reserved);
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_enum(
        &mut self,
        out: &mut String,
        interface: &str,
        def: &TypeDef,
        cases: &[Case],
    ) -> Result<()> {
        let name = self.user_name(interface, &def.name)?;
        let prefix = upper_snake(&name);
        writeln!(out)?;
        write_docs(out, 0, &def.docs)?;
        writeln!(out, "enum {name} {{")?;
        self.register_enum_value(&format!("{prefix}_UNSPECIFIED"))?;
        writeln!(out, "  {prefix}_UNSPECIFIED = 0;")?;
        let reserved = self.reserved_type(interface, &def.name, &[MemberKind::EnumCase])?;
        let reserved_names: BTreeSet<String> =
            reserved.iter().map(|(_, name)| name.clone()).collect();
        for case in cases {
            let case_name = upper_snake(&case.name);
            if reserved_names.contains(&case_name) {
                bail!(
                    "enum `{interface}/{}`: case `{case_name}` collides with a reserved name",
                    def.name
                );
            }
            if case_name == "UNSPECIFIED" {
                bail!("enum `{interface}/{}`: case maps to UNSPECIFIED", def.name);
            }
            let value = format!("{prefix}_{case_name}");
            self.register_enum_value(&value)?;
            let number = self.number(interface, &def.name, &case.name)?;
            write_docs(out, 2, &case.docs)?;
            writeln!(out, "  {value} = {number};")?;
        }
        let reserved: Vec<(u32, String)> = reserved
            .into_iter()
            .map(|(number, name)| (number, format!("{prefix}_{name}")))
            .collect();
        Self::emit_reserved(out, 2, &reserved);
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_flags(
        &mut self,
        out: &mut String,
        interface: &str,
        def: &TypeDef,
        flags: &[crate::model::Flag],
    ) -> Result<()> {
        let name = self.user_name(interface, &def.name)?;
        writeln!(out)?;
        write_docs(out, 0, &def.docs)?;
        writeln!(out, "message {name} {{")?;
        let reserved = self.reserved_type(interface, &def.name, &[MemberKind::Flag])?;
        let reserved_names: BTreeSet<String> =
            reserved.iter().map(|(_, name)| name.clone()).collect();
        let mut field_names = BTreeSet::new();
        let mut numbers = BTreeSet::new();
        for flag in flags {
            let field_name = field_name(&flag.name)?;
            if reserved_names.contains(&field_name) {
                bail!(
                    "flags `{interface}/{}`: field `{field_name}` collides with a reserved name",
                    def.name
                );
            }
            if !field_names.insert(field_name.clone()) {
                bail!(
                    "flags `{interface}/{}`: duplicate proto field `{field_name}`",
                    def.name
                );
            }
            let number = self.number(interface, &def.name, &flag.name)?;
            if !numbers.insert(number) {
                bail!(
                    "flags `{interface}/{}`: duplicate field number {number}",
                    def.name
                );
            }
            write_docs(out, 2, &flag.docs)?;
            writeln!(out, "  bool {field_name} = {number};")?;
        }
        Self::emit_reserved(out, 2, &reserved);
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_result(
        &mut self,
        out: &mut String,
        interface: &str,
        def: &TypeDef,
        result: &ResultExpr,
    ) -> Result<()> {
        let name = self.user_name(interface, &def.name)?;
        writeln!(out)?;
        write_docs(out, 0, &def.docs)?;
        writeln!(out, "message {name} {{")?;
        writeln!(out, "  oneof value {{")?;
        let ok = match &result.ok {
            Some(ok) => self.singular(ok)?,
            None => EMPTY.to_string(),
        };
        let err = match &result.err {
            Some(err) => self.singular(err)?,
            None => EMPTY.to_string(),
        };
        writeln!(out, "    {ok} ok = 1;")?;
        writeln!(out, "    {err} err = 2;")?;
        writeln!(out, "  }}")?;
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_function(
        &mut self,
        out: &mut String,
        interface: &str,
        function: &Function,
    ) -> Result<()> {
        let request_name = self.function_name(interface, function, "Request")?;
        write_docs(out, 0, &function.docs)?;
        writeln!(out, "message {request_name} {{")?;
        let mut field_names = BTreeSet::new();
        let mut numbers = BTreeSet::new();
        let reserved = self.reserved_params(interface, &function.name);
        let reserved_names: BTreeSet<String> =
            reserved.iter().map(|(_, name)| name.clone()).collect();
        for param in &function.params {
            let name = field_name(&param.name)?;
            if reserved_names.contains(&name) || !field_names.insert(name.clone()) {
                bail!(
                    "function `{interface}#{}`: proto field `{name}` collides with another or a reserved name",
                    function.name
                );
            }
            let number = self.parameter_number(interface, &function.name, &param.name)?;
            if !numbers.insert(number) {
                bail!(
                    "function `{interface}#{}`: duplicate parameter number {number}",
                    function.name
                );
            }
            let ty = self.direct(&param.ty, true)?;
            writeln!(out, "  {ty} {name} = {number};")?;
        }
        Self::emit_reserved(out, 2, &reserved);
        writeln!(out, "}}")?;

        let response_name = self.function_name(interface, function, "Response")?;
        writeln!(out)?;
        writeln!(out, "message {response_name} {{")?;
        if let Some(result) = &function.result {
            let ty = self.direct(result, true)?;
            writeln!(out, "  {ty} result = 1;")?;
        }
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_method_enum(&mut self, out: &mut String, interface: &str) -> Result<()> {
        let name = proto_ident(&format!("{}Method", pascal_case(interface)), "method enum")?;
        self.register_top(&name, format!("method enum {interface}"))?;
        let enum_prefix = upper_snake(&name);
        let prefix = upper_snake(&pascal_case(interface));
        writeln!(out)?;
        writeln!(out, "enum {name} {{")?;
        self.register_enum_value(&format!("{enum_prefix}_UNSPECIFIED"))?;
        writeln!(out, "  {enum_prefix}_UNSPECIFIED = 0;")?;
        let reserved = self.reserved_methods(interface);
        let reserved_names: BTreeSet<String> =
            reserved.iter().map(|(_, name)| name.clone()).collect();
        let mut numbers = BTreeSet::new();
        for function in &self.model.interface(interface).unwrap().functions {
            let value = upper_snake(&function.name);
            if value == "UNSPECIFIED" || reserved_names.contains(&value) {
                bail!(
                    "function `{interface}.{}` maps to a reserved or UNSPECIFIED method value",
                    function.name
                );
            }
            let number = self.method_number(interface, &function.name)?;
            if !numbers.insert(number) {
                bail!("interface `{interface}`: duplicate method number {number}");
            }
            let value = format!("{prefix}_METHOD_{value}");
            self.register_enum_value(&value)?;
            writeln!(out, "  {value} = {number};")?;
        }
        let reserved: Vec<(u32, String)> = reserved
            .into_iter()
            .map(|(number, name)| (number, format!("{prefix}_METHOD_{name}")))
            .collect();
        Self::emit_reserved(out, 2, &reserved);
        writeln!(out, "}}")?;
        Ok(())
    }

    fn emit_reserved(out: &mut String, indent: usize, reserved: &[(u32, String)]) {
        if reserved.is_empty() {
            return;
        }
        let prefix = " ".repeat(indent);
        let mut numbers: Vec<u32> = reserved.iter().map(|(number, _)| *number).collect();
        numbers.sort_unstable();
        numbers.dedup();
        let mut names: Vec<&str> = reserved.iter().map(|(_, name)| name.as_str()).collect();
        names.sort_unstable();
        names.dedup();
        writeln!(
            out,
            "{prefix}reserved {};",
            numbers
                .iter()
                .map(ToString::to_string)
                .collect::<Vec<_>>()
                .join(", ")
        )
        .unwrap();
        let quoted: Vec<String> = names.iter().map(|name| format!("\"{name}\"")).collect();
        writeln!(out, "{prefix}reserved {};", quoted.join(", ")).unwrap();
    }

    fn function_name(
        &mut self,
        interface: &str,
        function: &Function,
        suffix: &str,
    ) -> Result<String> {
        let name = format!(
            "{}{}{suffix}",
            pascal_case(interface),
            pascal_case(&function.name)
        );
        let name = proto_ident(&name, "function message")?;
        self.register_top(
            &name,
            format!("function {interface}/{} {suffix}", function.name),
        )?;
        Ok(name)
    }

    fn parameter_number(&self, interface: &str, function: &str, parameter: &str) -> Result<u32> {
        let key = format!(
            "{}:{}/{interface}#{function}.{parameter}",
            self.model.package.namespace, self.model.package.name
        );
        self.lock
            .get(&key)
            .map(|entry| entry.number)
            .with_context(|| format!("lockfile has no number for `{key}`"))
    }

    fn method_number(&self, interface: &str, function: &str) -> Result<u32> {
        let key = format!(
            "{}:{}/{interface}.{function}",
            self.model.package.namespace, self.model.package.name
        );
        self.lock
            .get(&key)
            .map(|entry| entry.number)
            .with_context(|| format!("lockfile has no number for `{key}`"))
    }

    fn reserved_type(
        &self,
        interface: &str,
        type_name: &str,
        kinds: &[MemberKind],
    ) -> Result<Vec<(u32, String)>> {
        let mut reserved = Vec::new();
        for (key, entry) in self.lock.entries() {
            if !entry.reserved {
                continue;
            }
            let MemberKey::TypeMember {
                interface: key_interface,
                type_name: key_type,
                member,
                ..
            } = key
            else {
                continue;
            };
            if key_interface != interface || key_type != type_name || !kinds.contains(&entry.kind) {
                continue;
            }
            if self.live_keys.contains(&key.key()) {
                bail!("reserved member `{key}` is live in the model");
            }
            let name = if entry.kind == MemberKind::EnumCase {
                upper_snake(member)
            } else {
                field_name(member)?
            };
            reserved.push((entry.number, name));
        }
        Ok(reserved)
    }

    fn reserved_params(&self, interface: &str, function: &str) -> Vec<(u32, String)> {
        self.lock
            .entries()
            .filter_map(|(key, entry)| match key {
                MemberKey::Parameter {
                    interface: i,
                    function: f,
                    parameter,
                    ..
                } if entry.reserved && i == interface && f == function => {
                    Some((entry.number, field_name(parameter).ok()?))
                }
                _ => None,
            })
            .collect()
    }

    fn reserved_methods(&self, interface: &str) -> Vec<(u32, String)> {
        self.lock
            .entries()
            .filter_map(|(key, entry)| match key {
                MemberKey::Method {
                    interface: i,
                    function,
                    ..
                } if entry.reserved && i == interface => {
                    Some((entry.number, upper_snake(function)))
                }
                _ => None,
            })
            .collect()
    }

    fn direct(&mut self, ty: &TypeExpr, required: bool) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok(optional("bool", required)),
            TypeExpr::U8 | TypeExpr::U16 | TypeExpr::U32 => Ok(optional("uint32", required)),
            TypeExpr::U64 => Ok(optional("uint64", required)),
            TypeExpr::S8 | TypeExpr::S16 | TypeExpr::S32 => Ok(optional("sint32", required)),
            TypeExpr::S64 => Ok(optional("sint64", required)),
            TypeExpr::F32 => Ok(optional("float", required)),
            TypeExpr::F64 => Ok(optional("double", required)),
            TypeExpr::String => Ok(optional("string", required)),
            TypeExpr::List(element) if is_u8(element) => Ok(optional("bytes", required)),
            TypeExpr::List(element) => Ok(format!("repeated {}", self.singular(element)?)),
            TypeExpr::Option(payload) => self.direct_option(payload),
            TypeExpr::Result(result) => self.ensure_result_wrapper(result),
            TypeExpr::Named(name) => {
                let kind = self.named(name)?.kind.clone();
                match &kind {
                    TypeDefKind::Alias(target) => self.direct(target, required),
                    TypeDefKind::Enum(_) => Ok(optional(
                        &self.user_name(&name.interface, &name.name)?,
                        required,
                    )),
                    TypeDefKind::Record(_)
                    | TypeDefKind::Variant(_)
                    | TypeDefKind::Flags(_)
                    | TypeDefKind::Result(_) => self.singular(ty),
                    TypeDefKind::List(element) if is_u8(element) => Ok(optional("bytes", required)),
                    TypeDefKind::List(element) => {
                        Ok(format!("repeated {}", self.singular(element)?))
                    }
                    TypeDefKind::Option(payload) => self.direct_named_option(name, payload),
                }
            }
        }
    }

    fn singular(&mut self, ty: &TypeExpr) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok("bool".to_string()),
            TypeExpr::U8 | TypeExpr::U16 | TypeExpr::U32 => Ok("uint32".to_string()),
            TypeExpr::U64 => Ok("uint64".to_string()),
            TypeExpr::S8 | TypeExpr::S16 | TypeExpr::S32 => Ok("sint32".to_string()),
            TypeExpr::S64 => Ok("sint64".to_string()),
            TypeExpr::F32 => Ok("float".to_string()),
            TypeExpr::F64 => Ok("double".to_string()),
            TypeExpr::String => Ok("string".to_string()),
            TypeExpr::List(element) if is_u8(element) => Ok("bytes".to_string()),
            TypeExpr::List(element) => self.list_wrapper(element),
            TypeExpr::Option(payload) => self.option_wrapper(None, payload),
            TypeExpr::Result(result) => self.ensure_result_wrapper(result),
            TypeExpr::Named(name) => {
                let kind = self.named(name)?.kind.clone();
                match &kind {
                    TypeDefKind::Alias(target) => self.singular(target),
                    TypeDefKind::Record(_)
                    | TypeDefKind::Variant(_)
                    | TypeDefKind::Enum(_)
                    | TypeDefKind::Flags(_)
                    | TypeDefKind::Result(_) => self.user_name(&name.interface, &name.name),
                    TypeDefKind::List(element) if is_u8(element) => Ok("bytes".to_string()),
                    TypeDefKind::List(element) => self.list_wrapper(element),
                    TypeDefKind::Option(payload) => self.option_wrapper(Some(name), payload),
                }
            }
        }
    }

    fn direct_option(&mut self, payload: &TypeExpr) -> Result<String> {
        match self.shape(payload)? {
            Shape::Scalar | Shape::Bytes => Ok(format!("optional {}", self.singular(payload)?)),
            Shape::Message | Shape::List | Shape::Option => self.singular(payload),
        }
    }

    fn direct_named_option(&mut self, name: &QualifiedName, payload: &TypeExpr) -> Result<String> {
        if let Some(wrapper) = self.named_option_wrapper(name, payload)? {
            Ok(wrapper)
        } else {
            self.direct_option(payload)
        }
    }

    fn option_wrapper(
        &mut self,
        named: Option<&QualifiedName>,
        payload: &TypeExpr,
    ) -> Result<String> {
        let wrapper_name = if let Some(name) = named {
            if let Some(direct) = self.named_option_wrapper(name, payload)? {
                let wrapper = format!("WitforgeOptionOf{direct}");
                return self.ensure_wrapper(
                    wrapper,
                    WrapperKind::OptionValue(direct),
                    format!("option {name}"),
                );
            }
            format!("WitforgeOptionOf{}", self.shape_name(payload)?)
        } else {
            format!("WitforgeOptionOf{}", self.shape_name(payload)?)
        };
        let some = self.singular(payload)?;
        self.ensure_wrapper(
            wrapper_name,
            WrapperKind::OptionValue(some),
            "anonymous option".to_string(),
        )
    }

    fn named_option_wrapper(
        &mut self,
        name: &QualifiedName,
        payload: &TypeExpr,
    ) -> Result<Option<String>> {
        match self.shape(payload)? {
            Shape::List => {
                let element = self.list_element(payload)?;
                let wrapper = Self::type_ident(&name.interface, &name.name)?;
                self.ensure_wrapper(
                    wrapper.clone(),
                    WrapperKind::List(element),
                    format!("option {name}"),
                )?;
                Ok(Some(wrapper))
            }
            Shape::Option => {
                let inner = self.option_payload(payload)?;
                let wrapper = Self::type_ident(&name.interface, &name.name)?;
                let some = self.singular(&inner)?;
                self.ensure_wrapper(
                    wrapper.clone(),
                    WrapperKind::OptionValue(some),
                    format!("option {name}"),
                )?;
                Ok(Some(wrapper))
            }
            _ => Ok(None),
        }
    }

    fn list_element(&self, ty: &TypeExpr) -> Result<TypeExpr> {
        match ty {
            TypeExpr::List(element) => Ok((**element).clone()),
            TypeExpr::Named(name) => {
                let kind = self.named(name)?.kind.clone();
                match kind {
                    TypeDefKind::List(element) => Ok(element),
                    TypeDefKind::Alias(target) => self.list_element(&target),
                    _ => bail!("named option `{name}` has a non-list shape"),
                }
            }
            _ => bail!("named option has a non-list shape"),
        }
    }

    fn option_payload(&self, ty: &TypeExpr) -> Result<TypeExpr> {
        match ty {
            TypeExpr::Option(payload) => Ok((**payload).clone()),
            TypeExpr::Named(name) => {
                let kind = self.named(name)?.kind.clone();
                match kind {
                    TypeDefKind::Option(payload) => Ok(payload),
                    TypeDefKind::Alias(target) => self.option_payload(&target),
                    _ => bail!("named option `{name}` has a non-option shape"),
                }
            }
            _ => bail!("named option has a non-option shape"),
        }
    }

    fn list_wrapper(&mut self, element: &TypeExpr) -> Result<String> {
        let name = format!("WitforgeListOf{}", self.shape_name(element)?);
        self.ensure_wrapper(
            name.clone(),
            WrapperKind::List(element.clone()),
            "anonymous list".to_string(),
        )
    }

    fn ensure_result_wrapper(&mut self, result: &ResultExpr) -> Result<String> {
        let name = format!(
            "Witforge{}",
            self.shape_name(&TypeExpr::Result(result.clone()))?
        );
        self.ensure_wrapper(
            name.clone(),
            WrapperKind::Result(result.clone()),
            "anonymous result".to_string(),
        )
    }

    fn ensure_wrapper(
        &mut self,
        name: String,
        kind: WrapperKind,
        source: String,
    ) -> Result<String> {
        if self.wrappers.contains_key(&name) {
            return Ok(name);
        }
        self.register_top(&name, source)?;
        let body = match kind {
            WrapperKind::List(element) => {
                let ty = self.singular(&element)?;
                format!("message {name} {{\n  repeated {ty} values = 1;\n}}")
            }
            WrapperKind::OptionValue(some) => {
                format!(
                    "message {name} {{\n  oneof value {{\n    Empty none = 1;\n    {some} some = 2;\n  }}\n}}"
                )
            }
            WrapperKind::Result(result) => {
                let ok = match &result.ok {
                    Some(ok) => self.singular(ok)?,
                    None => EMPTY.to_string(),
                };
                let err = match &result.err {
                    Some(err) => self.singular(err)?,
                    None => EMPTY.to_string(),
                };
                format!(
                    "message {name} {{\n  oneof value {{\n    {ok} ok = 1;\n    {err} err = 2;\n  }}\n}}"
                )
            }
        };
        self.wrappers.insert(name.clone(), body);
        Ok(name)
    }

    fn shape(&self, ty: &TypeExpr) -> Result<Shape> {
        match ty {
            TypeExpr::Bool
            | TypeExpr::U8
            | TypeExpr::U16
            | TypeExpr::U32
            | TypeExpr::U64
            | TypeExpr::S8
            | TypeExpr::S16
            | TypeExpr::S32
            | TypeExpr::S64
            | TypeExpr::F32
            | TypeExpr::F64
            | TypeExpr::String => Ok(Shape::Scalar),
            TypeExpr::List(element) if is_u8(element) => Ok(Shape::Bytes),
            TypeExpr::List(_) => Ok(Shape::List),
            TypeExpr::Option(_) => Ok(Shape::Option),
            TypeExpr::Result(_) => Ok(Shape::Message),
            TypeExpr::Named(name) => {
                let def = self.named(name)?;
                match &def.kind {
                    TypeDefKind::Alias(target) => self.shape(target),
                    TypeDefKind::Enum(_) => Ok(Shape::Scalar),
                    TypeDefKind::List(element) if is_u8(element) => Ok(Shape::Bytes),
                    TypeDefKind::List(_) => Ok(Shape::List),
                    TypeDefKind::Option(_) => Ok(Shape::Option),
                    TypeDefKind::Record(_)
                    | TypeDefKind::Variant(_)
                    | TypeDefKind::Flags(_)
                    | TypeDefKind::Result(_) => Ok(Shape::Message),
                }
            }
        }
    }

    fn shape_name(&self, ty: &TypeExpr) -> Result<String> {
        match ty {
            TypeExpr::Bool => Ok("Bool".to_string()),
            TypeExpr::U8 => Ok("U8".to_string()),
            TypeExpr::U16 => Ok("U16".to_string()),
            TypeExpr::U32 => Ok("U32".to_string()),
            TypeExpr::U64 => Ok("U64".to_string()),
            TypeExpr::S8 => Ok("S8".to_string()),
            TypeExpr::S16 => Ok("S16".to_string()),
            TypeExpr::S32 => Ok("S32".to_string()),
            TypeExpr::S64 => Ok("S64".to_string()),
            TypeExpr::F32 => Ok("F32".to_string()),
            TypeExpr::F64 => Ok("F64".to_string()),
            TypeExpr::String => Ok("String".to_string()),
            TypeExpr::List(element) => Ok(format!("ListOf{}", self.shape_name(element)?)),
            TypeExpr::Option(payload) => Ok(format!("OptionOf{}", self.shape_name(payload)?)),
            TypeExpr::Result(result) => self.result_shape_name(result),
            TypeExpr::Named(name) => {
                let def = self.named(name)?;
                match &def.kind {
                    TypeDefKind::Alias(target) => self.shape_name(target),
                    TypeDefKind::List(element) => {
                        Ok(format!("ListOf{}", self.shape_name(element)?))
                    }
                    TypeDefKind::Option(payload) => {
                        Ok(format!("OptionOf{}", self.shape_name(payload)?))
                    }
                    TypeDefKind::Result(result) => self.result_shape_name(result),
                    TypeDefKind::Record(_)
                    | TypeDefKind::Variant(_)
                    | TypeDefKind::Enum(_)
                    | TypeDefKind::Flags(_) => Ok(format!(
                        "{}{}",
                        pascal_case(&name.interface),
                        pascal_case(&name.name)
                    )),
                }
            }
        }
    }

    fn result_shape_name(&self, result: &ResultExpr) -> Result<String> {
        Ok(format!(
            "ResultOf{}And{}",
            self.shape_name_slot(result.ok.as_deref())?,
            self.shape_name_slot(result.err.as_deref())?
        ))
    }

    fn shape_name_slot(&self, slot: Option<&TypeExpr>) -> Result<String> {
        slot.map_or_else(|| Ok("Empty".to_string()), |ty| self.shape_name(ty))
    }

    fn named(&self, name: &QualifiedName) -> Result<&TypeDef> {
        self.model.type_def(name).with_context(|| {
            format!(
                "named type `{}/{}` is not in the model",
                name.interface, name.name
            )
        })
    }

    fn type_ident(interface: &str, ty: &str) -> Result<String> {
        proto_ident(
            &format!("{}{}", pascal_case(interface), pascal_case(ty)),
            "type",
        )
    }

    fn user_name(&mut self, interface: &str, ty: &str) -> Result<String> {
        let name = Self::type_ident(interface, ty)?;
        self.register_top(&name, format!("type {interface}/{ty}"))?;
        Ok(name)
    }

    fn register_top(&mut self, name: &str, source: String) -> Result<()> {
        if let Some(previous) = self.top_names.get(name) {
            if previous == &source {
                return Ok(());
            }
            bail!("proto name `{name}` is produced by both {previous} and {source}");
        }
        self.top_names.insert(name.to_string(), source);
        Ok(())
    }

    fn register_enum_value(&mut self, value: &str) -> Result<()> {
        if let Some(previous) = self
            .enum_values
            .insert(value.to_string(), value.to_string())
        {
            bail!("proto enum value `{value}` is produced more than once ({previous})");
        }
        Ok(())
    }

    fn number(&self, interface: &str, ty: &str, member: &str) -> Result<u32> {
        let key = format!(
            "{}:{}/{}/{}.{}",
            self.model.package.namespace, self.model.package.name, interface, ty, member
        );
        self.lock
            .get(&key)
            .map(|entry| entry.number)
            .with_context(|| format!("lockfile has no number for `{key}`"))
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Shape {
    Scalar,
    Bytes,
    Message,
    List,
    Option,
}

fn optional(ty: &str, required: bool) -> String {
    if required {
        format!("optional {ty}")
    } else {
        ty.to_string()
    }
}

fn is_u8(ty: &TypeExpr) -> bool {
    matches!(ty, TypeExpr::U8)
}

fn field_name(name: &str) -> Result<String> {
    let name = snake_case(name);
    if name.is_empty()
        || name == "."
        || name == ".."
        || name.chars().next().is_some_and(|ch| ch.is_ascii_digit())
        || !name
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || ch == '_')
    {
        bail!("invalid proto field `{name}`");
    }
    // Field names may be proto keywords (`message`, `optional`, ...); protoc accepts them in
    // field position. The real alint contract uses `message`.
    Ok(name)
}

fn proto_ident(name: &str, what: &str) -> Result<String> {
    if name.is_empty()
        || name == "."
        || name == ".."
        || name.chars().next().is_some_and(|ch| ch.is_ascii_digit())
        || !name
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || ch == '_')
    {
        bail!("invalid proto {what} `{name}`");
    }
    if PROTO_KEYWORDS.contains(&name) {
        bail!("proto {what} `{name}` is a reserved word");
    }
    Ok(name.to_string())
}

