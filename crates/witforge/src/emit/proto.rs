fn write_deprecated_option(
    out: &mut String,
    indent: usize,
    stability: &crate::model::Stability,
) -> Result<()> {
    if stability.deprecated().is_some() {
        writeln!(out, "{}option deprecated = true;", " ".repeat(indent))?;
    }
    Ok(())
}
