/// Legacy pre-0.6.0 shared line-comment header, adopted on write and reported as changed on
/// `--check`.
pub(crate) const LEGACY_COMMENT_HEADER: &str = "// @generated by witforge; do not edit.";
/// Legacy pre-0.6.0 shared JSON Schema header, adopted on write and reported as changed on
/// `--check`.
pub(crate) const LEGACY_JSON_HEADER: &str =
    "{\"$comment\":\"@generated by witforge; do not edit.\",";

const COMMENT_HEADER_PREFIX: &str = "// @generated by witforge (";
const COMMENT_HEADER_SUFFIX: &str = "); do not edit.";
const GO_HEADER_PREFIX: &str = "// Code generated by witforge (";
const GO_HEADER_SUFFIX: &str = "); DO NOT EDIT.";
const HASH_HEADER_PREFIX: &str = "# @generated by witforge (";
const HASH_HEADER_SUFFIX: &str = "); do not edit.";
const JSON_HEADER_PREFIX: &str = "{\"$comment\":\"@generated by witforge (";
const JSON_HEADER_SUFFIX: &str = "); do not edit.\",";
const HTML_HEADER_PREFIX: &str = "<!-- @generated by witforge (";
const HTML_HEADER_SUFFIX: &str = "); do not edit. -->";
const MAX_HEADER_LINE_BYTES: u64 = 1024;

/// Comment/metadata syntax used for generated-file ownership headers across target languages.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[non_exhaustive]
pub enum HeaderStyle {
    /// C-family / Rust / TypeScript / Java / C# / Protobuf line comment:
    /// `// @generated by witforge (<generator>, <namespace>:<name>); do not edit.`
    LineComment,
    /// Official Go generated-file header recognized by `go doc`, `pkg.go.dev`, and linters:
    /// `// Code generated by witforge (<generator>, <namespace>:<name>); DO NOT EDIT.`
    GoGenerated,
    /// Hash line comment (Python, shell, YAML, TOML):
    /// `# @generated by witforge (<generator>, <namespace>:<name>); do not edit.`
    HashComment,
    /// JSON Schema `$comment` prefix:
    /// `{"$comment":"@generated by witforge (<generator>, <namespace>:<name>); do not edit.",`
    JsonComment,
    /// HTML / Markdown comment:
    /// `<!-- @generated by witforge (<generator>, <namespace>:<name>); do not edit. -->`
    HtmlComment,
}

impl HeaderStyle {
    /// Format the canonical ownership header line for `generator` and contract
    /// `<namespace>:<name>`.
    ///
    /// Callers must pass single-line identifier strings without newlines or `", "`.
    #[must_use]
    pub fn format_header(self, generator: &str, namespace: &str, name: &str) -> String {
        match self {
            Self::LineComment => comment_header(generator, namespace, name),
            Self::GoGenerated => go_comment_header(generator, namespace, name),
            Self::HashComment => hash_comment_header(generator, namespace, name),
            Self::JsonComment => json_header(generator, namespace, name),
            Self::HtmlComment => html_comment_header(generator, namespace, name),
        }
    }
}

/// Build the per-generator, per-contract line-comment ownership header.
pub(crate) fn comment_header(generator: &str, namespace: &str, name: &str) -> String {
    format!("{COMMENT_HEADER_PREFIX}{generator}, {namespace}:{name}{COMMENT_HEADER_SUFFIX}")
}

/// Build the per-generator, per-contract Go generated-file ownership header.
pub(crate) fn go_comment_header(generator: &str, namespace: &str, name: &str) -> String {
    format!("{GO_HEADER_PREFIX}{generator}, {namespace}:{name}{GO_HEADER_SUFFIX}")
}

/// Build the per-generator, per-contract `#` hash-comment ownership header.
pub(crate) fn hash_comment_header(generator: &str, namespace: &str, name: &str) -> String {
    format!("{HASH_HEADER_PREFIX}{generator}, {namespace}:{name}{HASH_HEADER_SUFFIX}")
}

/// Build the per-generator, per-contract JSON Schema `$comment` ownership header.
pub(crate) fn json_header(generator: &str, namespace: &str, name: &str) -> String {
    format!("{JSON_HEADER_PREFIX}{generator}, {namespace}:{name}{JSON_HEADER_SUFFIX}")
}

/// Build the per-generator, per-contract HTML/Markdown comment ownership header.
pub(crate) fn html_comment_header(generator: &str, namespace: &str, name: &str) -> String {
    format!("{HTML_HEADER_PREFIX}{generator}, {namespace}:{name}{HTML_HEADER_SUFFIX}")
}

#[derive(Debug, PartialEq, Eq)]
enum HeaderKind {
    /// Matches this output set's exact ownership header.
    Owned,
    /// Matches the legacy pre-0.6.0 shared header for the same comment/JSON syntax.
    LegacyShared,
    /// Carries another generator's or another contract's witforge header.
    Foreign(String),
    /// Does not carry any witforge generated header.
    Unowned,
}

/// The reason committed generated output differs from the expected file set.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum GeneratedFileStatus {
    /// An expected generated file is absent.
    Missing,
    /// An expected generated file has different bytes.
    Changed {
        /// The first differing line or binary/line-ending explanation.
        detail: String,
    },
    /// An owned generated file is no longer expected.
    Extra,
    /// An expected output path is a symbolic link.
    Symlink,
    /// An expected output path exists but is not a regular file.
    NotRegular,
    /// An expected regular file does not carry witforge's ownership header.
    Unowned,
    /// An ancestor directory of an expected nested output path exists but is not a directory.
    NotDirectory,
}

impl GeneratedFileStatus {
    pub(crate) const fn sort_rank(&self) -> u8 {
        match self {
            // Preserve the previous lexicographic message order without rendering temporary
            // strings: backtick, changed, extra, generated, missing.
            Self::Unowned => 0,
            Self::Changed { .. } => 1,
            Self::Extra => 2,
            Self::Symlink | Self::NotRegular | Self::NotDirectory => 3,
            Self::Missing => 4,
        }
    }
}

/// One structured generated-output discrepancy.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub struct GeneratedFileFinding {
    /// The physical generated-file path.
    pub path: PathBuf,
    /// Why the file differs or cannot be replaced.
    pub status: GeneratedFileStatus,
    /// The exact command that regenerates the output, when supplied by the caller.
    pub regenerate_command: Option<String>,
}

impl GeneratedFileFinding {
    pub(crate) fn new(
        path: PathBuf,
        status: GeneratedFileStatus,
        regenerate_command: Option<&str>,
    ) -> Self {
        Self {
            path,
            status,
            regenerate_command: regenerate_command.map(str::to_string),
        }
    }

    fn fmt_hint(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.regenerate_command.as_deref() {
            Some(command) => write!(f, "; run `{command}`"),
            None => Ok(()),
        }
    }
    /// Render the byte-stable human message for this finding.
    #[must_use]
    pub fn message(&self) -> String {
        self.to_string()
    }

    /// Convert this finding into the stable generated-drift diagnostic.
    #[must_use]
    pub fn diagnostic(&self) -> crate::diagnostic::LocatedDiagnostic {
        let file = self.path.display().to_string();
        crate::diagnostic::LocatedDiagnostic::from_diagnostic(
            crate::diagnostic::Diagnostic::error(
                crate::diagnostic::codes::GENERATED_DRIFT,
                self.to_string(),
            )
            .with_path(file.clone()),
        )
        .with_file(file)
    }
}

impl fmt::Display for GeneratedFileFinding {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.status {
            GeneratedFileStatus::Missing => {
                write!(f, "missing generated file `{}`", self.path.display())?;
                self.fmt_hint(f)
            }
            GeneratedFileStatus::Changed { detail } => {
                write!(
                    f,
                    "changed generated file `{}`: {detail}",
                    self.path.display()
                )?;
                self.fmt_hint(f)
            }
            GeneratedFileStatus::Extra => {
                write!(f, "extra generated file `{}`", self.path.display())?;
                self.fmt_hint(f)
            }
            GeneratedFileStatus::Symlink => write!(
                f,
                "generated file `{}` is a symlink; generation refuses to write through it",
                self.path.display()
            ),
            GeneratedFileStatus::NotRegular => write!(
                f,
                "generated file `{}` is not a regular file; generation refuses to replace it",
                self.path.display()
            ),
            GeneratedFileStatus::NotDirectory => write!(
                f,
                "ancestor directory `{}` exists and is not a directory; generation refuses to \
                 replace it",
                self.path.display()
            ),
            GeneratedFileStatus::Unowned => write!(
                f,
                "`{}` does not start with witforge's header, so generation refuses to overwrite it",
                self.path.display()
            ),
        }
    }
}

/// A set of generated files that share one ownership-header line.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFiles {
    header: String,
    files: BTreeMap<String, String>,
    markers: BTreeSet<String>,
    /// Case-folded (`to_lowercase()`) relative file path -> exact registered file path.
    /// Populated whenever `nested == true` so collision and rename checks stay O(depth * log N).
    lower_files: BTreeMap<String, String>,
    /// Case-folded (`to_lowercase()`) ancestor directory prefix -> exact registered directory path.
    /// Populated whenever `nested == true` to reject file-vs-dir and directory-casing collisions.
    lower_dirs: BTreeMap<String, String>,
    nested: bool,
}

static TEMP_COUNTER: AtomicU64 = AtomicU64::new(0);

const WINDOWS_RESERVED_NAMES: &[&str] = &[
    "AUX", "COM0", "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8", "COM9", "CON",
    "CONIN$", "CONOUT$", "LPT0", "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8",
    "LPT9", "NUL", "PRN",
];

fn is_disallowed_path_char(ch: char) -> bool {
    ch.is_control()
        || matches!(
            ch,
            '\u{061C}'
                | '\u{200E}'
                | '\u{200F}'
                | '\u{202A}'..='\u{202E}'
                | '\u{2066}'..='\u{2069}'
        )
}

fn normalize_windows_device_stem(segment: &str) -> String {
    let stem = segment
        .split('.')
        .next()
        .unwrap_or(segment)
        .trim_end_matches(' ');
    stem.chars()
        .map(|ch| match ch {
            '\u{00B9}' => '1',
            '\u{00B2}' => '2',
            '\u{00B3}' => '3',
            other => other.to_ascii_uppercase(),
        })
        .collect()
}

/// Validate that `path` is a safe, canonical POSIX relative path suitable for nested generated
/// output trees across Linux, macOS, and Windows.
///
/// Refuses empty paths, leading/trailing `/`, empty segments (`//`), backslashes (`\`), `.` or
/// `..` segments, NUL / C0 / C1 control characters, Unicode bidirectional override/isolate
/// characters, witforge atomic-write temporary names (`.witforge.*.tmp`), segments ending with
/// spaces or `.`, Windows-illegal filename characters (`< > : " | ? *`), and Windows reserved
/// device names (`CON`, `PRN`, `AUX`, `NUL`, `CONIN$`, `CONOUT$`, `COM0`..`9`, `LPT0`..`9`,
/// including trailing spaces before `.` and superscript `¹`/`²`/`³` variants, with or without an
/// extension).
///
/// # Errors
///
/// Returns an operational error (`WF9004`) if `path` violates any cross-platform path-safety rule.
pub fn validate_relative_path(path: &str) -> Result<()> {
    if path.is_empty() {
        return Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            "generated relative path must not be empty",
            None,
        ));
    }
    if path.starts_with('/') || path.ends_with('/') {
        return Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            format!("generated relative path `{path}` must not start or end with `/`"),
            Some(path.to_string()),
        ));
    }
    if path.contains('\\') {
        return Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            format!("generated relative path `{path}` must use POSIX `/` separators, not `\\`"),
            Some(path.to_string()),
        ));
    }
    if path.chars().any(is_disallowed_path_char) {
        return Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            format!(
                "generated relative path `{path}` must not contain control or bidirectional \
                 formatting characters"
            ),
            Some(path.to_string()),
        ));
    }
    for segment in path.split('/') {
        if segment.is_empty() || segment == "." || segment == ".." {
            return Err(crate::operational_error(
                crate::diagnostic::codes::GUARD_REFUSED,
                format!("generated relative path `{path}` contains invalid segment `{segment}`"),
                Some(path.to_string()),
            ));
        }
        if is_temp_file(segment) {
            return Err(crate::operational_error(
                crate::diagnostic::codes::GUARD_REFUSED,
                format!(
                    "generated relative path `{path}` uses reserved temporary filename `{segment}`"
                ),
                Some(path.to_string()),
            ));
        }
        if segment.ends_with(' ') || segment.ends_with('.') {
            return Err(crate::operational_error(
                crate::diagnostic::codes::GUARD_REFUSED,
                format!(
                    "generated relative path `{path}` segment `{segment}` must not end with a \
                     space or `.`"
                ),
                Some(path.to_string()),
            ));
        }
        if segment
            .bytes()
            .any(|b| matches!(b, b'<' | b'>' | b':' | b'"' | b'|' | b'?' | b'*'))
        {
            return Err(crate::operational_error(
                crate::diagnostic::codes::GUARD_REFUSED,
                format!(
                    "generated relative path `{path}` segment `{segment}` contains characters \
                     disallowed on Windows"
                ),
                Some(path.to_string()),
            ));
        }
        let normalized_stem = normalize_windows_device_stem(segment);
        if WINDOWS_RESERVED_NAMES
            .binary_search(&normalized_stem.as_str())
            .is_ok()
        {
            return Err(crate::operational_error(
                crate::diagnostic::codes::GUARD_REFUSED,
                format!(
                    "generated relative path `{path}` segment `{segment}` uses Windows reserved \
                     device name `{normalized_stem}`"
                ),
                Some(path.to_string()),
            ));
        }
    }
    Ok(())
}

impl GeneratedFiles {
    /// Create a flat generated-file set using `header` as the generated-file ownership marker.
    #[must_use]
    pub fn new(header: impl Into<String>) -> Self {
        Self {
            header: header.into(),
            files: BTreeMap::new(),
            markers: BTreeSet::new(),
            lower_files: BTreeMap::new(),
            lower_dirs: BTreeMap::new(),
            nested: false,
        }
    }

    /// Create a nested-tree generated-file set using `header` as the generated-file ownership
    /// marker.
    ///
    /// Unlike [`Self::new`] (which manages only top-level files directly inside `out`), a nested
    /// set scans subdirectories recursively (without following symlinks), creates parent
    /// directories atomically on [`Self::write`], prunes stale owned files and resulting empty
    /// directories strictly inside `out`, and supports allowlisted marker files via
    /// [`Self::insert_marker`].
    #[must_use]
    pub fn new_nested(header: impl Into<String>) -> Self {
        Self {
            header: header.into(),
            files: BTreeMap::new(),
            markers: BTreeSet::new(),
            lower_files: BTreeMap::new(),
            lower_dirs: BTreeMap::new(),
            nested: true,
        }
    }

    /// Whether this generated-file set manages a nested directory tree.
    #[must_use]
    pub const fn is_nested(&self) -> bool {
        self.nested
    }

    /// Add one expected root-relative simple file name.
    ///
    /// If this file set is already in nested mode (created with [`Self::new_nested`] or promoted
    /// via [`Self::insert_relative`] / [`Self::insert_marker`]), `name` is also checked with
    /// [`validate_relative_path`] and cross-platform collision checks.
    ///
    /// # Errors
    ///
    /// Returns an error when `name` is not a simple file name, or when in nested mode and `name`
    /// fails path safety or collision checks (`WF9004`).
    pub fn insert(&mut self, name: impl Into<String>, contents: impl Into<String>) -> Result<()> {
        let name = name.into();
        let path = Path::new(&name);
        if name.is_empty()
            || name == "."
            || name == ".."
            || path.is_absolute()
            || path.components().count() != 1
        {
            bail!("generated file name `{name}` must be a simple name");
        }
        if self.nested {
            validate_relative_path(&name)?;
            Self::index_relative_path(&mut self.lower_files, &mut self.lower_dirs, &name)?;
        }
        self.files.insert(name, contents.into());
        Ok(())
    }

    /// Add one expected POSIX relative path (which may contain `/` subdirectories) and enable
    /// nested-tree mode.
    ///
    /// Enforces [`validate_relative_path`] plus duplicate, case-insensitive file, directory-casing,
    /// and file-vs-directory prefix collision checks against all previously inserted paths. If this
    /// file set was previously flat (with entries added via [`Self::insert`]), all existing entries
    /// are retroactively validated and indexed before enabling nested mode.
    ///
    /// # Errors
    ///
    /// Returns an operational error (`WF9004`) if `path` (or a previously inserted flat entry during
    /// promotion) fails cross-platform path validation or collides with another registered path.
    pub fn insert_relative(
        &mut self,
        path: impl Into<String>,
        contents: impl Into<String>,
    ) -> Result<()> {
        let path = path.into();
        self.insert_nested_entry(path, contents.into(), false)
    }

    /// Add one explicitly allowlisted marker file (such as an empty PEP 561 `py.typed` file)
    /// that cannot carry a witforge comment header, enabling nested-tree mode.
    ///
    /// On disk, an existing file at `path` is treated as owned if it carries this output set's own
    /// header, is empty, or matches `contents` (verbatim or with CRLF line endings), rejected as
    /// foreign (`WF9004`) if it carries another witforge header, and treated as unowned if it
    /// contains non-matching hand-written content.
    ///
    /// # Errors
    ///
    /// Returns an operational error (`WF9004`) if `path` (or a previously inserted flat entry during
    /// promotion) fails cross-platform path validation or collides with another registered path.
    pub fn insert_marker(
        &mut self,
        path: impl Into<String>,
        contents: impl Into<String>,
    ) -> Result<()> {
        let path = path.into();
        self.insert_nested_entry(path, contents.into(), true)
    }

    fn insert_nested_entry(
        &mut self,
        path: String,
        contents: String,
        is_marker: bool,
    ) -> Result<()> {
        validate_relative_path(&path)?;
        if self.nested {
            Self::index_relative_path(&mut self.lower_files, &mut self.lower_dirs, &path)?;
        } else {
            let mut lower_files = BTreeMap::new();
            let mut lower_dirs = BTreeMap::new();
            for existing in self.files.keys() {
                validate_relative_path(existing)?;
                Self::index_relative_path(&mut lower_files, &mut lower_dirs, existing)?;
            }
            Self::index_relative_path(&mut lower_files, &mut lower_dirs, &path)?;
            self.lower_files = lower_files;
            self.lower_dirs = lower_dirs;
            self.nested = true;
        }
        if is_marker {
            self.markers.insert(path.clone());
        }
        self.files.insert(path, contents);
        Ok(())
    }

    fn index_relative_path(
        lower_files: &mut BTreeMap<String, String>,
        lower_dirs: &mut BTreeMap<String, String>,
        candidate: &str,
    ) -> Result<()> {
        let candidate_lower = candidate.to_lowercase();
        if let Some(existing) = lower_files.get(&candidate_lower) {
            return Err(crate::operational_error(
                crate::diagnostic::codes::GUARD_REFUSED,
                format!(
                    "generated path `{candidate}` collides with `{existing}` (case-insensitive \
                     path collision)"
                ),
                Some(candidate.to_string()),
            ));
        }
        if let Some(existing_dir) = lower_dirs.get(&candidate_lower) {
            return Err(crate::operational_error(
                crate::diagnostic::codes::GUARD_REFUSED,
                format!(
                    "generated path `{candidate}` collides with file/directory prefix \
                     `{existing_dir}`"
                ),
                Some(candidate.to_string()),
            ));
        }

        let mut new_dirs = Vec::new();
        for (idx, byte) in candidate.bytes().enumerate() {
            if byte != b'/' {
                continue;
            }
            let dir_orig = &candidate[..idx];
            let dir_lower = dir_orig.to_lowercase();
            if let Some(existing_file) = lower_files.get(&dir_lower) {
                return Err(crate::operational_error(
                    crate::diagnostic::codes::GUARD_REFUSED,
                    format!(
                        "generated path `{candidate}` collides with file/directory prefix \
                         `{existing_file}`"
                    ),
                    Some(candidate.to_string()),
                ));
            }
            if let Some(existing_dir) = lower_dirs.get(&dir_lower)
                && existing_dir != dir_orig
            {
                return Err(crate::operational_error(
                    crate::diagnostic::codes::GUARD_REFUSED,
                    format!(
                        "generated path `{candidate}` directory `{dir_orig}` collides with \
                         `{existing_dir}` (case-insensitive directory collision)"
                    ),
                    Some(candidate.to_string()),
                ));
            }
            new_dirs.push((dir_lower, dir_orig.to_string()));
        }

        lower_files.insert(candidate_lower, candidate.to_string());
        for (dir_lower, dir_orig) in new_dirs {
            lower_dirs.entry(dir_lower).or_insert(dir_orig);
        }
        Ok(())
    }

    /// The ownership header.
    #[must_use]
    pub fn header(&self) -> &str {
        &self.header
    }

    /// The expected file names and contents.
    #[must_use]
    pub fn files(&self) -> &BTreeMap<String, String> {
        &self.files
    }

    /// The expected relative paths registered as allowlisted marker files via
    /// [`Self::insert_marker`].
    #[must_use]
    pub fn markers(&self) -> &BTreeSet<String> {
        &self.markers
    }

    /// Write all expected files and remove stale generated files in `out`.
    ///
    /// Each expected file whose content already matches on disk is left untouched (preserving its
    /// modification time, inode, and permissions). Expected files whose content changed are
    /// replaced atomically through a process-unique temporary sibling, preserving the replaced
    /// file's permission bits (including read-only files when the directory is writable). New
    /// files use the default mode under the process umask. Stale generated files are removed only
    /// after all expected writes succeed. Files without a witforge header (including unreadable
    /// unrelated files) and non-regular entries (directories, symlinks, FIFOs) at non-expected
    /// paths are never touched or opened past the bounded header probe. Active temporary siblings
    /// (`.witforge.<name>.<pid>.<seq>.tmp`) from concurrent runs are ignored.
    ///
    /// Before anything is created, written, or removed:
    /// - if `out` exists, no regular file in `out` (or in its subdirectories when
    ///   [`Self::is_nested`] is `true`, without descending into symlinks) may carry another
    ///   generator's or another contract's witforge header;
    /// - every expected path (and every ancestor directory in nested mode) that already exists
    ///   must not be a symlink, every ancestor must be a directory, and every existing leaf must
    ///   be a regular file owned by this generator (or a matching allowlisted marker file).
    ///
    /// In nested mode, removing stale owned files also prunes any resulting empty subdirectories
    /// strictly inside `out` without touching `out` itself or directories holding unowned files.
    ///
    /// # Errors
    ///
    /// Returns an error when `out` holds a file belonging to another generator or contract, when
    /// an expected path is a symlink, is not a regular file, is unreadable, or is unowned, and on
    /// I/O failure.
    #[allow(clippy::too_many_lines)]
    pub fn write(&self, out: &Path) -> Result<()> {
        if self.nested {
            return self.write_nested(out);
        }
        let mut stale = Vec::new();
        if out.exists() {
            let expected: std::collections::BTreeSet<&str> =
                self.files.keys().map(String::as_str).collect();
            for entry in sorted_output_entries(out)? {
                let file_type = match entry.file_type() {
                    Ok(ty) => ty,
                    Err(err) if err.kind() == std::io::ErrorKind::NotFound => continue,
                    Err(err) => return Err(err.into()),
                };
                if !file_type.is_file() {
                    continue;
                }
                let path = entry.path();
                let name = entry.file_name().to_string_lossy().into_owned();
                if is_temp_file(&name) {
                    continue;
                }
                let kind = if expected.contains(name.as_str()) {
                    self.classify(&path)?
                } else {
                    self.classify_unrelated(&path)?
                };
                match kind {
                    HeaderKind::Foreign(owner) => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "refusing to write into `{}`: `{}` belongs to {owner}; give each \
                                 generator and contract its own output root",
                                out.display(),
                                path.display()
                            ),
                            Some(path.display().to_string()),
                        ));
                    }
                    HeaderKind::Owned | HeaderKind::LegacyShared
                        if !expected.contains(name.as_str()) =>
                    {
                        stale.push(path);
                    }
                    HeaderKind::Owned | HeaderKind::LegacyShared | HeaderKind::Unowned => {}
                }
            }
            for name in self.files.keys() {
                let path = out.join(name);
                match fs::symlink_metadata(&path) {
                    Ok(metadata) if metadata.file_type().is_symlink() => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "refusing to write `{}`: it is a symlink, and generation never \
                                 writes through one",
                                path.display()
                            ),
                            Some(path.display().to_string()),
                        ));
                    }
                    Ok(metadata) if !metadata.is_file() => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "refusing to write `{}`: it exists and is not a regular file",
                                path.display()
                            ),
                            Some(path.display().to_string()),
                        ));
                    }
                    Ok(_) => match self.classify(&path)? {
                        HeaderKind::Owned | HeaderKind::LegacyShared => {}
                        HeaderKind::Foreign(owner) => {
                            return Err(crate::operational_error(
                                crate::diagnostic::codes::GUARD_REFUSED,
                                format!(
                                    "refusing to write into `{}`: `{}` belongs to {owner}; give \
                                     each generator and contract its own output root",
                                    out.display(),
                                    path.display()
                                ),
                                Some(path.display().to_string()),
                            ));
                        }
                        HeaderKind::Unowned => {
                            return Err(crate::operational_error(
                                crate::diagnostic::codes::GUARD_REFUSED,
                                format!(
                                    "refusing to overwrite `{}`: it does not start with \
                                     witforge's header, so it is not generated output; move it or \
                                     choose another output root",
                                    path.display()
                                ),
                                Some(path.display().to_string()),
                            ));
                        }
                    },
                    Err(err) if err.kind() == std::io::ErrorKind::NotFound => {}
                    Err(err) => {
                        return Err(err)
                            .with_context(|| format!("failed to inspect {}", path.display()));
                    }
                }
            }
        }
        fs::create_dir_all(out)
            .with_context(|| format!("failed to create output root {}", out.display()))?;
        for (name, contents) in &self.files {
            let path = out.join(name);
            let bytes = contents.as_bytes();
            if fs::read(&path).is_ok_and(|existing| existing == bytes) {
                continue;
            }
            write_atomic(&path, bytes)?;
        }
        for path in stale {
            remove_stale_file(&path)?;
        }
        Ok(())
    }

    /// Compare the expected files with `out`.
    ///
    /// Returns one structured finding per missing, changed, or extra generated file, and per
    /// expected path (or blocking ancestor directory in nested mode) that [`GeneratedFiles::write`]
    /// would refuse: a symlink, a non-regular leaf, a non-directory ancestor, or an unowned file.
    /// Only regular files are read, so a FIFO or a device at an expected path cannot block the
    /// check. Files without a witforge header (including unreadable unrelated files) and active
    /// `.witforge.*.tmp` temporaries at other paths are ignored. In nested mode, subdirectories
    /// are scanned recursively without following symlinks and allowlisted markers registered via
    /// [`Self::insert_marker`] are validated by marker content.
    ///
    /// # Errors
    ///
    /// Returns an error when the output root is missing or cannot be read, when any file in `out`
    /// carries another generator's or another contract's header, or when an expected file cannot
    /// be inspected or read.
    pub fn check(&self, out: &Path) -> Result<Vec<GeneratedFileFinding>> {
        self.check_inner(out, None)
    }

    /// Like [`GeneratedFiles::check`], carrying `regenerate_command` as structured fix metadata
    /// on each missing, changed, or extra generated-file finding.
    ///
    /// # Errors
    ///
    /// Returns the same errors as [`GeneratedFiles::check`].
    pub fn check_with_command(
        &self,
        out: &Path,
        regenerate_command: &str,
    ) -> Result<Vec<GeneratedFileFinding>> {
        self.check_inner(out, Some(regenerate_command))
    }

    #[allow(clippy::too_many_lines)]
    fn check_inner(
        &self,
        out: &Path,
        regenerate_command: Option<&str>,
    ) -> Result<Vec<GeneratedFileFinding>> {
        if self.nested {
            return self.check_nested(out, regenerate_command);
        }
        if !out.is_dir() {
            return Err(crate::operational_error(
                crate::diagnostic::codes::IO_ERROR,
                format!("output root {} does not exist", out.display()),
                Some(out.display().to_string()),
            ));
        }
        let mut extra = Vec::new();
        for entry in sorted_output_entries(out)? {
            let file_type = match entry.file_type() {
                Ok(ty) => ty,
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => continue,
                Err(err) => return Err(err.into()),
            };
            if !file_type.is_file() {
                continue;
            }
            let path = entry.path();
            let name = entry.file_name().to_string_lossy().into_owned();
            if is_temp_file(&name) {
                continue;
            }
            let kind = if self.files.contains_key(&name) {
                self.classify(&path)?
            } else {
                self.classify_unrelated(&path)?
            };
            match kind {
                HeaderKind::Foreign(owner) => {
                    return Err(crate::operational_error(
                        crate::diagnostic::codes::GUARD_REFUSED,
                        format!(
                            "output root `{}` contains `{}` which belongs to {owner}; give each \
                             generator and contract its own output root",
                            out.display(),
                            path.display()
                        ),
                        Some(path.display().to_string()),
                    ));
                }
                HeaderKind::Owned | HeaderKind::LegacyShared if !self.files.contains_key(&name) => {
                    extra.push(GeneratedFileFinding::new(
                        path,
                        GeneratedFileStatus::Extra,
                        regenerate_command,
                    ));
                }
                HeaderKind::Owned | HeaderKind::LegacyShared | HeaderKind::Unowned => {}
            }
        }

        let mut findings = extra;
        for (name, expected) in &self.files {
            let path = out.join(name);
            let metadata = match fs::symlink_metadata(&path) {
                Ok(metadata) => metadata,
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                    findings.push(GeneratedFileFinding::new(
                        path,
                        GeneratedFileStatus::Missing,
                        regenerate_command,
                    ));
                    continue;
                }
                Err(err) => {
                    return Err(err)
                        .with_context(|| format!("failed to inspect {}", path.display()));
                }
            };
            if metadata.file_type().is_symlink() {
                findings.push(GeneratedFileFinding::new(
                    path,
                    GeneratedFileStatus::Symlink,
                    regenerate_command,
                ));
            } else if !metadata.is_file() {
                findings.push(GeneratedFileFinding::new(
                    path,
                    GeneratedFileStatus::NotRegular,
                    regenerate_command,
                ));
            } else {
                match self.classify(&path)? {
                    HeaderKind::Owned | HeaderKind::LegacyShared => {
                        let actual = fs::read(&path)
                            .with_context(|| format!("failed to read {}", path.display()))?;
                        if actual != expected.as_bytes() {
                            let detail = describe_change(&actual, expected);
                            findings.push(GeneratedFileFinding::new(
                                path,
                                GeneratedFileStatus::Changed { detail },
                                regenerate_command,
                            ));
                        }
                    }
                    HeaderKind::Foreign(owner) => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "output root `{}` contains `{}` which belongs to {owner}; give \
                                 each generator and contract its own output root",
                                out.display(),
                                path.display()
                            ),
                            Some(path.display().to_string()),
                        ));
                    }
                    HeaderKind::Unowned => {
                        findings.push(GeneratedFileFinding::new(
                            path,
                            GeneratedFileStatus::Unowned,
                            regenerate_command,
                        ));
                    }
                }
            }
        }
        findings.sort_by(|left, right| {
            left.status
                .sort_rank()
                .cmp(&right.status.sort_rank())
                .then_with(|| left.path.cmp(&right.path))
        });
        Ok(findings)
    }

    /// Render a unified diff between the current files in `out` and this expected file set.
    ///
    /// Returns an empty string when `out` already matches every expected file with no extra
    /// generated files. If `out` does not exist yet, every expected file is shown as added from
    /// `/dev/null`. In nested mode, subdirectories are scanned recursively without following
    /// symlinks and allowlisted marker paths are diffed using marker ownership rules.
    ///
    /// # Errors
    ///
    /// Returns an error when `out` holds a foreign generator's or contract's file or when an
    /// owned file cannot be read.
    pub fn unified_diff(&self, out: &Path) -> Result<String> {
        if self.nested {
            return self.unified_diff_nested(out);
        }
        let mut rendered = String::new();
        if out.is_dir() {
            for entry in sorted_output_entries(out)? {
                let file_type = match entry.file_type() {
                    Ok(ty) => ty,
                    Err(err) if err.kind() == std::io::ErrorKind::NotFound => continue,
                    Err(err) => return Err(err.into()),
                };
                if !file_type.is_file() {
                    continue;
                }
                let path = entry.path();
                let name = entry.file_name().to_string_lossy().into_owned();
                if is_temp_file(&name) || self.files.contains_key(&name) {
                    continue;
                }
                match self.classify_unrelated(&path)? {
                    HeaderKind::Foreign(owner) => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "output root `{}` contains `{}` which belongs to {owner}; give \
                                 each generator and contract its own output root",
                                out.display(),
                                path.display()
                            ),
                            Some(path.display().to_string()),
                        ));
                    }
                    HeaderKind::Owned | HeaderKind::LegacyShared => {
                        let actual_bytes = fs::read(&path)
                            .with_context(|| format!("failed to read {}", path.display()))?;
                        let actual = String::from_utf8_lossy(&actual_bytes);
                        rendered.push_str(&render_unified_diff(
                            &path.display().to_string(),
                            Some(&actual),
                            None,
                        ));
                    }
                    HeaderKind::Unowned => {}
                }
            }
        }
        for (name, expected) in &self.files {
            let path = out.join(name);
            let label = path.display().to_string();
            match fs::symlink_metadata(&path) {
                Ok(metadata) if metadata.is_file() && !metadata.file_type().is_symlink() => {
                    match self.classify(&path)? {
                        HeaderKind::Owned | HeaderKind::LegacyShared => {
                            let actual_bytes = fs::read(&path)
                                .with_context(|| format!("failed to read {}", path.display()))?;
                            if actual_bytes != expected.as_bytes() {
                                let actual = String::from_utf8_lossy(&actual_bytes);
                                rendered.push_str(&render_unified_diff(
                                    &label,
                                    Some(&actual),
                                    Some(expected),
                                ));
                            }
                        }
                        HeaderKind::Foreign(owner) => {
                            return Err(crate::operational_error(
                                crate::diagnostic::codes::GUARD_REFUSED,
                                format!(
                                    "output root `{}` contains `{}` which belongs to {owner}; \
                                     give each generator and contract its own output root",
                                    out.display(),
                                    path.display()
                                ),
                                Some(path.display().to_string()),
                            ));
                        }
                        HeaderKind::Unowned => {}
                    }
                }
                Ok(_) => {}
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                    rendered.push_str(&render_unified_diff(&label, None, Some(expected)));
                }
                Err(err) => {
                    return Err(err)
                        .with_context(|| format!("failed to inspect {}", path.display()));
                }
            }
        }
        Ok(rendered)
    }

    /// Classify the first line of an unrelated file in `out`, skipping unreadable or vanished
    /// files as unowned so unrelated files never abort a run.
    fn classify_unrelated(&self, path: &Path) -> Result<HeaderKind> {
        match self.classify_raw(path) {
            Ok(kind) => Ok(kind),
            Err(err)
                if matches!(
                    err.kind(),
                    std::io::ErrorKind::PermissionDenied | std::io::ErrorKind::NotFound
                ) =>
            {
                Ok(HeaderKind::Unowned)
            }
            Err(err) => Err(err).with_context(|| format!("failed to read {}", path.display())),
        }
    }

    /// Classify the first line of `path` against this output set's ownership header.
    ///
    /// Only the first line (up to a small byte bound) is read as raw bytes, so non-UTF-8 files
    /// (such as `.DS_Store` or images) are recognised as unowned without failing.
    fn classify(&self, path: &Path) -> Result<HeaderKind> {
        self.classify_raw(path)
            .with_context(|| format!("failed to read {}", path.display()))
    }

    fn classify_raw(&self, path: &Path) -> std::io::Result<HeaderKind> {
        let limit = u64::try_from(self.header.len() + 2)
            .unwrap_or(MAX_HEADER_LINE_BYTES)
            .max(MAX_HEADER_LINE_BYTES);
        let mut buf = Vec::new();
        File::open(path)?.take(limit).read_to_end(&mut buf)?;
        let mut line = match buf.iter().position(|&byte| byte == b'\n') {
            Some(newline) => &buf[..newline],
            None => &buf[..],
        };
        if let Some(stripped) = line.strip_suffix(b"\r") {
            line = stripped;
        }
        Ok(classify_header_line(&self.header, line))
    }

    fn classify_expected(&self, rel_path: &str, abs_path: &Path) -> Result<HeaderKind> {
        if self.markers.contains(rel_path) {
            let header_kind = self.classify(abs_path)?;
            match header_kind {
                HeaderKind::Owned | HeaderKind::LegacyShared | HeaderKind::Foreign(_) => {
                    return Ok(header_kind);
                }
                HeaderKind::Unowned => {}
            }
            let expected = self.files.get(rel_path).map_or("", String::as_str);
            // Bound the read so a large hand-written file at a marker path is never loaded into
            // memory just to determine it is unowned. Account for CRLF expansion (at most 2x).
            let max_expected_len = expected.len().saturating_mul(2).saturating_add(1);
            let limit = u64::try_from(max_expected_len).unwrap_or(u64::MAX);
            let mut actual = Vec::new();
            File::open(abs_path)
                .with_context(|| format!("failed to open {}", abs_path.display()))?
                .take(limit)
                .read_to_end(&mut actual)
                .with_context(|| format!("failed to read {}", abs_path.display()))?;
            if actual.len() == max_expected_len {
                return Ok(HeaderKind::Unowned);
            }
            if actual.is_empty()
                || actual == expected.as_bytes()
                || std::str::from_utf8(&actual)
                    .is_ok_and(|text| text.replace("\r\n", "\n") == expected)
            {
                return Ok(HeaderKind::Owned);
            }
            return Ok(HeaderKind::Unowned);
        }
        self.classify(abs_path)
    }

    #[allow(clippy::too_many_lines)]
    fn write_nested(&self, out: &Path) -> Result<()> {
        let mut stale = Vec::new();
        let mut case_renames = Vec::new();
        let mut force_rewrite_lower = BTreeSet::new();
        if out.exists() {
            let discovered = collect_nested_regular_files(out, &self.lower_dirs)?;
            for (rel_path, abs_path) in discovered {
                let kind = if self.files.contains_key(&rel_path) {
                    self.classify_expected(&rel_path, &abs_path)?
                } else {
                    self.classify_unrelated(&abs_path)?
                };
                match kind {
                    HeaderKind::Foreign(owner) => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "refusing to write into `{}`: `{}` belongs to {owner}; give each \
                                 generator and contract its own output root",
                                out.display(),
                                abs_path.display()
                            ),
                            Some(abs_path.display().to_string()),
                        ));
                    }
                    HeaderKind::Owned | HeaderKind::LegacyShared
                        if !self.files.contains_key(&rel_path) =>
                    {
                        if is_case_only_rename(&rel_path, &self.lower_files) {
                            case_renames.push((rel_path, abs_path));
                        } else {
                            stale.push(abs_path);
                        }
                    }
                    HeaderKind::Owned | HeaderKind::LegacyShared | HeaderKind::Unowned => {}
                }
            }
            for rel_path in self.files.keys() {
                if let Some((ancestor, status)) = inspect_ancestor_dirs(out, rel_path)? {
                    let msg = match status {
                        GeneratedFileStatus::Symlink => format!(
                            "refusing to write `{}`: ancestor `{}` is a symlink, and generation \
                             never writes through one",
                            join_relative(out, rel_path).display(),
                            ancestor.display()
                        ),
                        _ => format!(
                            "refusing to write `{}`: ancestor `{}` exists and is not a directory",
                            join_relative(out, rel_path).display(),
                            ancestor.display()
                        ),
                    };
                    return Err(crate::operational_error(
                        crate::diagnostic::codes::GUARD_REFUSED,
                        msg,
                        Some(ancestor.display().to_string()),
                    ));
                }
                let path = join_relative(out, rel_path);
                match fs::symlink_metadata(&path) {
                    Ok(metadata) if metadata.file_type().is_symlink() => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "refusing to write `{}`: it is a symlink, and generation never \
                                 writes through one",
                                path.display()
                            ),
                            Some(path.display().to_string()),
                        ));
                    }
                    Ok(metadata) if !metadata.is_file() => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "refusing to write `{}`: it exists and is not a regular file",
                                path.display()
                            ),
                            Some(path.display().to_string()),
                        ));
                    }
                    Ok(_) => match self.classify_expected(rel_path, &path)? {
                        HeaderKind::Owned | HeaderKind::LegacyShared => {}
                        HeaderKind::Foreign(owner) => {
                            return Err(crate::operational_error(
                                crate::diagnostic::codes::GUARD_REFUSED,
                                format!(
                                    "refusing to write into `{}`: `{}` belongs to {owner}; give \
                                     each generator and contract its own output root",
                                    out.display(),
                                    path.display()
                                ),
                                Some(path.display().to_string()),
                            ));
                        }
                        HeaderKind::Unowned => {
                            let message = if self.markers.contains(rel_path) {
                                format!(
                                    "refusing to overwrite marker `{}`: it contains non-matching \
                                     hand-written content; move it or choose another output root",
                                    path.display()
                                )
                            } else {
                                format!(
                                    "refusing to overwrite `{}`: it does not start with \
                                     witforge's header, so it is not generated output; move it or \
                                     choose another output root",
                                    path.display()
                                )
                            };
                            return Err(crate::operational_error(
                                crate::diagnostic::codes::GUARD_REFUSED,
                                message,
                                Some(path.display().to_string()),
                            ));
                        }
                    },
                    Err(err) if err.kind() == std::io::ErrorKind::NotFound => {}
                    Err(err) => {
                        return Err(err)
                            .with_context(|| format!("failed to inspect {}", path.display()));
                    }
                }
            }
        }
        fs::create_dir_all(out)
            .with_context(|| format!("failed to create output root {}", out.display()))?;

        // On case-insensitive platforms (macOS APFS, Windows NTFS), removing an old-cased file
        // AFTER writing its new-cased replacement would delete the newly written file! Remove
        // old-cased paths first (and prune now-empty old-cased directories) and force-rewrite the
        // target path so the on-disk casing matches `self.files` exactly.
        if cfg!(any(target_os = "macos", target_os = "windows")) {
            for (rel_path, abs_path) in case_renames {
                force_rewrite_lower.insert(rel_path.to_lowercase());
                remove_stale_file(&abs_path)?;
                prune_empty_ancestors(abs_path.parent(), out);
            }
        } else {
            for (_rel_path, abs_path) in case_renames {
                stale.push(abs_path);
            }
        }

        for (rel_path, contents) in &self.files {
            let path = join_relative(out, rel_path);
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)
                    .with_context(|| format!("failed to create directory {}", parent.display()))?;
            }
            let bytes = contents.as_bytes();
            if !force_rewrite_lower.contains(&rel_path.to_lowercase())
                && fs::read(&path).is_ok_and(|existing| existing == bytes)
            {
                continue;
            }
            write_atomic(&path, bytes)?;
        }
        for path in stale {
            remove_stale_file(&path)?;
            prune_empty_ancestors(path.parent(), out);
        }
        Ok(())
    }

    #[allow(clippy::too_many_lines)]
    fn check_nested(
        &self,
        out: &Path,
        regenerate_command: Option<&str>,
    ) -> Result<Vec<GeneratedFileFinding>> {
        if !out.is_dir() {
            return Err(crate::operational_error(
                crate::diagnostic::codes::IO_ERROR,
                format!("output root {} does not exist", out.display()),
                Some(out.display().to_string()),
            ));
        }
        let mut blocking_ancestors: BTreeMap<PathBuf, GeneratedFileStatus> = BTreeMap::new();
        for rel_path in self.files.keys() {
            if let Some((ancestor, status)) = inspect_ancestor_dirs(out, rel_path)? {
                blocking_ancestors.entry(ancestor).or_insert(status);
            }
        }

        let discovered = collect_nested_regular_files(out, &self.lower_dirs)?;
        let discovered_exact: BTreeSet<&str> = discovered
            .iter()
            .map(|(rel_path, _)| rel_path.as_str())
            .collect();
        let mut case_renamed_expected: BTreeSet<String> = BTreeSet::new();

        let mut findings = Vec::new();
        for (rel_path, abs_path) in &discovered {
            let kind = if self.files.contains_key(rel_path) {
                self.classify_expected(rel_path, abs_path)?
            } else {
                self.classify_unrelated(abs_path)?
            };
            match kind {
                HeaderKind::Foreign(owner) => {
                    return Err(crate::operational_error(
                        crate::diagnostic::codes::GUARD_REFUSED,
                        format!(
                            "output root `{}` contains `{}` which belongs to {owner}; give each \
                             generator and contract its own output root",
                            out.display(),
                            abs_path.display()
                        ),
                        Some(abs_path.display().to_string()),
                    ));
                }
                HeaderKind::Owned | HeaderKind::LegacyShared
                    if !self.files.contains_key(rel_path) =>
                {
                    if let Some(expected_rel) = self.lower_files.get(&rel_path.to_lowercase())
                        && expected_rel != rel_path
                        && !discovered_exact.contains(expected_rel.as_str())
                    {
                        case_renamed_expected.insert(expected_rel.clone());
                    }
                    if !blocking_ancestors.contains_key(abs_path) {
                        findings.push(GeneratedFileFinding::new(
                            abs_path.clone(),
                            GeneratedFileStatus::Extra,
                            regenerate_command,
                        ));
                    }
                }
                HeaderKind::Owned | HeaderKind::LegacyShared | HeaderKind::Unowned => {}
            }
        }

        for (ancestor, status) in &blocking_ancestors {
            findings.push(GeneratedFileFinding::new(
                ancestor.clone(),
                status.clone(),
                regenerate_command,
            ));
        }

        for (rel_path, expected) in &self.files {
            if inspect_ancestor_dirs(out, rel_path)?.is_some() {
                continue;
            }
            let path = join_relative(out, rel_path);
            if case_renamed_expected.contains(rel_path) {
                findings.push(GeneratedFileFinding::new(
                    path,
                    GeneratedFileStatus::Missing,
                    regenerate_command,
                ));
                continue;
            }
            let metadata = match fs::symlink_metadata(&path) {
                Ok(metadata) => metadata,
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                    findings.push(GeneratedFileFinding::new(
                        path,
                        GeneratedFileStatus::Missing,
                        regenerate_command,
                    ));
                    continue;
                }
                Err(err) => {
                    return Err(err)
                        .with_context(|| format!("failed to inspect {}", path.display()));
                }
            };
            if metadata.file_type().is_symlink() {
                findings.push(GeneratedFileFinding::new(
                    path,
                    GeneratedFileStatus::Symlink,
                    regenerate_command,
                ));
            } else if !metadata.is_file() {
                findings.push(GeneratedFileFinding::new(
                    path,
                    GeneratedFileStatus::NotRegular,
                    regenerate_command,
                ));
            } else {
                match self.classify_expected(rel_path, &path)? {
                    HeaderKind::Owned | HeaderKind::LegacyShared => {
                        let actual = fs::read(&path)
                            .with_context(|| format!("failed to read {}", path.display()))?;
                        if actual != expected.as_bytes() {
                            let detail = describe_change(&actual, expected);
                            findings.push(GeneratedFileFinding::new(
                                path,
                                GeneratedFileStatus::Changed { detail },
                                regenerate_command,
                            ));
                        }
                    }
                    HeaderKind::Foreign(owner) => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "output root `{}` contains `{}` which belongs to {owner}; give \
                                 each generator and contract its own output root",
                                out.display(),
                                path.display()
                            ),
                            Some(path.display().to_string()),
                        ));
                    }
                    HeaderKind::Unowned => {
                        findings.push(GeneratedFileFinding::new(
                            path,
                            GeneratedFileStatus::Unowned,
                            regenerate_command,
                        ));
                    }
                }
            }
        }
        findings.sort_by(|left, right| {
            left.status
                .sort_rank()
                .cmp(&right.status.sort_rank())
                .then_with(|| left.path.cmp(&right.path))
        });
        Ok(findings)
    }

    fn unified_diff_nested(&self, out: &Path) -> Result<String> {
        let mut rendered = String::new();
        let mut case_renamed_expected: BTreeSet<String> = BTreeSet::new();
        if out.is_dir() {
            let discovered = collect_nested_regular_files(out, &self.lower_dirs)?;
            let discovered_exact: BTreeSet<&str> = discovered
                .iter()
                .map(|(rel_path, _)| rel_path.as_str())
                .collect();
            for (rel_path, abs_path) in &discovered {
                if self.files.contains_key(rel_path) {
                    continue;
                }
                match self.classify_unrelated(abs_path)? {
                    HeaderKind::Foreign(owner) => {
                        return Err(crate::operational_error(
                            crate::diagnostic::codes::GUARD_REFUSED,
                            format!(
                                "output root `{}` contains `{}` which belongs to {owner}; give \
                                 each generator and contract its own output root",
                                out.display(),
                                abs_path.display()
                            ),
                            Some(abs_path.display().to_string()),
                        ));
                    }
                    HeaderKind::Owned | HeaderKind::LegacyShared => {
                        if let Some(expected_rel) = self.lower_files.get(&rel_path.to_lowercase())
                            && expected_rel != rel_path
                            && !discovered_exact.contains(expected_rel.as_str())
                        {
                            case_renamed_expected.insert(expected_rel.clone());
                        }
                        let actual_bytes = fs::read(abs_path)
                            .with_context(|| format!("failed to read {}", abs_path.display()))?;
                        let actual = String::from_utf8_lossy(&actual_bytes);
                        rendered.push_str(&render_unified_diff(
                            &abs_path.display().to_string(),
                            Some(&actual),
                            None,
                        ));
                    }
                    HeaderKind::Unowned => {}
                }
            }
        }
        for (rel_path, expected) in &self.files {
            if inspect_ancestor_dirs(out, rel_path)?.is_some() {
                continue;
            }
            let path = join_relative(out, rel_path);
            let label = path.display().to_string();
            if case_renamed_expected.contains(rel_path) {
                rendered.push_str(&render_unified_diff(&label, None, Some(expected)));
                continue;
            }
            match fs::symlink_metadata(&path) {
                Ok(metadata) if metadata.is_file() && !metadata.file_type().is_symlink() => {
                    match self.classify_expected(rel_path, &path)? {
                        HeaderKind::Owned | HeaderKind::LegacyShared => {
                            let actual_bytes = fs::read(&path)
                                .with_context(|| format!("failed to read {}", path.display()))?;
                            if actual_bytes != expected.as_bytes() {
                                let actual = String::from_utf8_lossy(&actual_bytes);
                                rendered.push_str(&render_unified_diff(
                                    &label,
                                    Some(&actual),
                                    Some(expected),
                                ));
                            }
                        }
                        HeaderKind::Foreign(owner) => {
                            return Err(crate::operational_error(
                                crate::diagnostic::codes::GUARD_REFUSED,
                                format!(
                                    "output root `{}` contains `{}` which belongs to {owner}; \
                                     give each generator and contract its own output root",
                                    out.display(),
                                    path.display()
                                ),
                                Some(path.display().to_string()),
                            ));
                        }
                        HeaderKind::Unowned => {}
                    }
                }
                Ok(_) => {}
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                    rendered.push_str(&render_unified_diff(&label, None, Some(expected)));
                }
                Err(err) => {
                    return Err(err)
                        .with_context(|| format!("failed to inspect {}", path.display()));
                }
            }
        }
        Ok(rendered)
    }
}

fn is_case_only_rename(
    discovered_rel: &str,
    expected_lower_files: &BTreeMap<String, String>,
) -> bool {
    expected_lower_files
        .get(&discovered_rel.to_lowercase())
        .is_some_and(|expected_rel| expected_rel != discovered_rel)
}

fn join_relative(out: &Path, rel_posix: &str) -> PathBuf {
    let mut path = out.to_path_buf();
    for segment in rel_posix.split('/') {
        path.push(segment);
    }
    path
}

fn inspect_ancestor_dirs(
    out: &Path,
    rel_posix: &str,
) -> Result<Option<(PathBuf, GeneratedFileStatus)>> {
    let mut segments = rel_posix.split('/').peekable();
    let mut current = out.to_path_buf();
    while let Some(seg) = segments.next() {
        if segments.peek().is_none() {
            break;
        }
        current.push(seg);
        match fs::symlink_metadata(&current) {
            Ok(meta) if meta.file_type().is_symlink() => {
                return Ok(Some((current, GeneratedFileStatus::Symlink)));
            }
            Ok(meta) if !meta.is_dir() => {
                return Ok(Some((current, GeneratedFileStatus::NotDirectory)));
            }
            Ok(_) => {}
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(err) => {
                return Err(err)
                    .with_context(|| format!("failed to inspect {}", current.display()));
            }
        }
    }
    Ok(None)
}

fn collect_nested_regular_files(
    out: &Path,
    expected_lower_dirs: &BTreeMap<String, String>,
) -> Result<Vec<(String, PathBuf)>> {
    let mut found = Vec::new();
    collect_nested_dir(out, "", expected_lower_dirs, &mut found)?;
    Ok(found)
}

fn collect_nested_dir(
    dir: &Path,
    rel_prefix: &str,
    expected_lower_dirs: &BTreeMap<String, String>,
    found: &mut Vec<(String, PathBuf)>,
) -> Result<()> {
    let is_expected_dir =
        !rel_prefix.is_empty() && expected_lower_dirs.contains_key(&rel_prefix.to_lowercase());
    let entries = match sorted_dir_entries(dir, rel_prefix.is_empty()) {
        Ok(entries) => entries,
        Err(err)
            if !rel_prefix.is_empty()
                && !is_expected_dir
                && err.chain().any(|cause| {
                    cause.downcast_ref::<std::io::Error>().is_some_and(|io| {
                        matches!(
                            io.kind(),
                            std::io::ErrorKind::PermissionDenied | std::io::ErrorKind::NotFound
                        )
                    })
                }) =>
        {
            return Ok(());
        }
        Err(err) => return Err(err),
    };
    for entry in entries {
        let file_type = match entry.file_type() {
            Ok(ty) => ty,
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => continue,
            Err(err) => return Err(err.into()),
        };
        if file_type.is_symlink() {
            continue;
        }
        let name = entry.file_name().to_string_lossy().into_owned();
        let rel = if rel_prefix.is_empty() {
            name.clone()
        } else {
            format!("{rel_prefix}/{name}")
        };
        let path = entry.path();
        if file_type.is_dir() {
            collect_nested_dir(&path, &rel, expected_lower_dirs, found)?;
        } else if file_type.is_file() {
            if is_temp_file(&name) {
                continue;
            }
            found.push((rel, path));
        }
    }
    Ok(())
}

fn prune_empty_ancestors(start: Option<&Path>, stop_at: &Path) {
    let mut current = start;
    while let Some(dir) = current {
        if dir == stop_at || !dir.starts_with(stop_at) {
            break;
        }
        if fs::remove_dir(dir).is_err() {
            break;
        }
        current = dir.parent();
    }
}

/// Whether `name` is a witforge atomic-write temporary file (`.witforge.<name>.<pid>.<seq>.tmp`).
fn is_temp_file(name: &str) -> bool {
    let Some(inner) = name
        .strip_prefix(".witforge.")
        .and_then(|rest| rest.strip_suffix(".tmp"))
    else {
        return false;
    };
    let Some((prefix, seq)) = inner.rsplit_once('.') else {
        return false;
    };
    let Some((base, pid)) = prefix.rsplit_once('.') else {
        return false;
    };
    !base.is_empty()
        && !pid.is_empty()
        && !seq.is_empty()
        && pid.bytes().all(|byte| byte.is_ascii_digit())
        && seq.bytes().all(|byte| byte.is_ascii_digit())
}

fn describe_change(actual_bytes: &[u8], expected: &str) -> String {
    let Ok(actual) = std::str::from_utf8(actual_bytes) else {
        return "content differs (non-UTF-8 bytes)".to_string();
    };
    if actual.replace("\r\n", "\n") == expected {
        return "line endings differ (CRLF vs LF; check git core.autocrlf)".to_string();
    }
    let actual_lines: Vec<&str> = split_lines_keep_cr(actual);
    let expected_lines: Vec<&str> = split_lines_keep_cr(expected);
    let shared = actual_lines.len().min(expected_lines.len());
    for index in 0..shared {
        if actual_lines[index] != expected_lines[index] {
            let line_no = index + 1;
            return format!(
                "first difference at line {line_no}: expected {}, found {}",
                format_line_snippet(expected_lines[index]),
                format_line_snippet(actual_lines[index]),
            );
        }
    }
    let line_no = shared + 1;
    match actual_lines.len().cmp(&expected_lines.len()) {
        std::cmp::Ordering::Less => format!(
            "first difference at line {line_no}: expected {}, found end of file",
            format_line_snippet(expected_lines[shared]),
        ),
        std::cmp::Ordering::Greater => format!(
            "first difference at line {line_no}: expected end of file, found {}",
            format_line_snippet(actual_lines[shared]),
        ),
        std::cmp::Ordering::Equal => "trailing newline differs".to_string(),
    }
}

fn split_lines_keep_cr(text: &str) -> Vec<&str> {
    if text.is_empty() {
        return Vec::new();
    }
    let trimmed = text.strip_suffix('\n').unwrap_or(text);
    trimmed.split('\n').collect()
}

fn format_line_snippet(line: &str) -> String {
    let display = if let Some(stripped) = line.strip_suffix('\r') {
        format!("{stripped}\\r")
    } else {
        line.to_string()
    };
    let mut chars = display.chars();
    let truncated: String = chars.by_ref().take(100).collect();
    if chars.next().is_some() {
        format!("{truncated:?}...")
    } else {
        format!("{truncated:?}")
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum DiffOp {
    Context(usize, usize),
    Delete(usize),
    Insert(usize),
}

fn render_unified_diff(path: &str, actual: Option<&str>, expected: Option<&str>) -> String {
    use std::fmt::Write as _;

    let old_lines: Vec<&str> = actual.map_or_else(Vec::new, split_lines_keep_cr);
    let new_lines: Vec<&str> = expected.map_or_else(Vec::new, split_lines_keep_cr);
    let mut out = String::new();
    let old_header = if actual.is_some() {
        format!("a/{path}")
    } else {
        "/dev/null".to_string()
    };
    let new_header = if expected.is_some() {
        format!("b/{path}")
    } else {
        "/dev/null".to_string()
    };
    let _ = writeln!(out, "--- {old_header}");
    let _ = writeln!(out, "+++ {new_header}");

    let ops = compute_diff_ops(&old_lines, &new_lines);
    let context = 3usize;
    let changed_indices: Vec<usize> = ops
        .iter()
        .enumerate()
        .filter_map(|(idx, op)| (!matches!(op, DiffOp::Context(_, _))).then_some(idx))
        .collect();
    if changed_indices.is_empty() {
        return out;
    }

    let mut hunk_ranges: Vec<(usize, usize)> = Vec::new();
    for idx in changed_indices {
        let start = idx.saturating_sub(context);
        let end = (idx + context + 1).min(ops.len());
        if let Some(last) = hunk_ranges.last_mut()
            && start <= last.1
        {
            last.1 = end;
        } else {
            hunk_ranges.push((start, end));
        }
    }

    for (start, end) in hunk_ranges {
        let slice = &ops[start..end];
        let old_count = slice
            .iter()
            .filter(|op| matches!(op, DiffOp::Context(_, _) | DiffOp::Delete(_)))
            .count();
        let new_count = slice
            .iter()
            .filter(|op| matches!(op, DiffOp::Context(_, _) | DiffOp::Insert(_)))
            .count();
        let old_start = slice
            .iter()
            .find_map(|op| match *op {
                DiffOp::Context(i, _) | DiffOp::Delete(i) => Some(i + 1),
                DiffOp::Insert(_) => None,
            })
            .unwrap_or(0);
        let new_start = slice
            .iter()
            .find_map(|op| match *op {
                DiffOp::Context(_, j) | DiffOp::Insert(j) => Some(j + 1),
                DiffOp::Delete(_) => None,
            })
            .unwrap_or(0);
        let _ = writeln!(
            out,
            "@@ -{old_start},{old_count} +{new_start},{new_count} @@"
        );
        for &op in slice {
            match op {
                DiffOp::Context(i, _) => {
                    let _ = writeln!(out, " {}", format_diff_line(old_lines[i]));
                }
                DiffOp::Delete(i) => {
                    let _ = writeln!(out, "-{}", format_diff_line(old_lines[i]));
                }
                DiffOp::Insert(j) => {
                    let _ = writeln!(out, "+{}", format_diff_line(new_lines[j]));
                }
            }
        }
    }
    out
}

fn format_diff_line(line: &str) -> String {
    if let Some(stripped) = line.strip_suffix('\r') {
        format!("{stripped}\\r")
    } else {
        line.to_string()
    }
}

fn compute_diff_ops(old: &[&str], new: &[&str]) -> Vec<DiffOp> {
    let mut prefix = 0usize;
    while prefix < old.len() && prefix < new.len() && old[prefix] == new[prefix] {
        prefix += 1;
    }
    let mut suffix = 0usize;
    while prefix + suffix < old.len()
        && prefix + suffix < new.len()
        && old[old.len() - 1 - suffix] == new[new.len() - 1 - suffix]
    {
        suffix += 1;
    }

    let mut ops = Vec::with_capacity(old.len().max(new.len()));
    for idx in 0..prefix {
        ops.push(DiffOp::Context(idx, idx));
    }

    let old_mid = &old[prefix..old.len() - suffix];
    let new_mid = &new[prefix..new.len() - suffix];
    let m = old_mid.len();
    let n = new_mid.len();

    // Exact LCS for ordinary files; bounded fallback avoids quadratic memory on giant files.
    if m.saturating_mul(n) <= 400_000 {
        let mut dp = vec![0u32; (m + 1) * (n + 1)];
        let stride = n + 1;
        for i in (0..m).rev() {
            for j in (0..n).rev() {
                dp[i * stride + j] = if old_mid[i] == new_mid[j] {
                    dp[(i + 1) * stride + (j + 1)] + 1
                } else {
                    dp[(i + 1) * stride + j].max(dp[i * stride + (j + 1)])
                };
            }
        }
        let (mut i, mut j) = (0usize, 0usize);
        while i < m && j < n {
            if old_mid[i] == new_mid[j] {
                ops.push(DiffOp::Context(prefix + i, prefix + j));
                i += 1;
                j += 1;
            } else if dp[(i + 1) * stride + j] >= dp[i * stride + (j + 1)] {
                ops.push(DiffOp::Delete(prefix + i));
                i += 1;
            } else {
                ops.push(DiffOp::Insert(prefix + j));
                j += 1;
            }
        }
        while i < m {
            ops.push(DiffOp::Delete(prefix + i));
            i += 1;
        }
        while j < n {
            ops.push(DiffOp::Insert(prefix + j));
            j += 1;
        }
    } else {
        for i in 0..m {
            ops.push(DiffOp::Delete(prefix + i));
        }
        for j in 0..n {
            ops.push(DiffOp::Insert(prefix + j));
        }
    }

    for k in 0..suffix {
        ops.push(DiffOp::Context(
            old.len() - suffix + k,
            new.len() - suffix + k,
        ));
    }
    ops
}

fn sorted_output_entries(out: &Path) -> Result<Vec<fs::DirEntry>> {
    sorted_dir_entries(out, true)
}

fn sorted_dir_entries(dir: &Path, is_root: bool) -> Result<Vec<fs::DirEntry>> {
    let mut entries = Vec::new();
    let label = if is_root { "output root" } else { "directory" };
    for entry in
        fs::read_dir(dir).with_context(|| format!("failed to read {label} {}", dir.display()))?
    {
        entries.push(entry?);
    }
    entries.sort_by(|left, right| {
        left.file_name()
            .as_encoded_bytes()
            .cmp(right.file_name().as_encoded_bytes())
    });
    Ok(entries)
}

fn classify_header_line(expected_header: &str, line: &[u8]) -> HeaderKind {
    if line == expected_header.as_bytes() {
        return HeaderKind::Owned;
    }
    let Ok(text) = std::str::from_utf8(line) else {
        return HeaderKind::Unowned;
    };
    let expected_scoped = parse_scoped_header(expected_header);
    let expected_is_legacy_comment_gen = expected_header.starts_with(COMMENT_HEADER_PREFIX)
        && expected_header.ends_with(COMMENT_HEADER_SUFFIX)
        && expected_scoped
            .is_some_and(|(gen_name, _)| matches!(gen_name, "rust" | "proto" | "glue"));
    let expected_is_legacy_json_gen = expected_header.starts_with(JSON_HEADER_PREFIX)
        && expected_header.ends_with(JSON_HEADER_SUFFIX)
        && expected_scoped.is_some_and(|(gen_name, _)| gen_name == "schema");

    if text == LEGACY_COMMENT_HEADER {
        if expected_is_legacy_comment_gen {
            return HeaderKind::LegacyShared;
        }
        if expected_scoped.is_some() {
            return HeaderKind::Foreign("another witforge generator (legacy header)".to_string());
        }
    }
    if text == LEGACY_JSON_HEADER {
        if expected_is_legacy_json_gen {
            return HeaderKind::LegacyShared;
        }
        if expected_scoped.is_some() {
            return HeaderKind::Foreign("generator `schema` (legacy header)".to_string());
        }
    }
    if let Some((generator, contract)) = parse_scoped_header(text) {
        return HeaderKind::Foreign(format!("generator `{generator}` for contract `{contract}`"));
    }
    HeaderKind::Unowned
}

fn parse_scoped_header(line: &str) -> Option<(&str, &str)> {
    let inner = line
        .strip_prefix(COMMENT_HEADER_PREFIX)
        .and_then(|rest| rest.strip_suffix(COMMENT_HEADER_SUFFIX))
        .or_else(|| {
            line.strip_prefix(GO_HEADER_PREFIX)
                .and_then(|rest| rest.strip_suffix(GO_HEADER_SUFFIX))
        })
        .or_else(|| {
            line.strip_prefix(HASH_HEADER_PREFIX)
                .and_then(|rest| rest.strip_suffix(HASH_HEADER_SUFFIX))
        })
        .or_else(|| {
            line.strip_prefix(JSON_HEADER_PREFIX)
                .and_then(|rest| rest.strip_suffix(JSON_HEADER_SUFFIX))
        })
        .or_else(|| {
            line.strip_prefix(HTML_HEADER_PREFIX)
                .and_then(|rest| rest.strip_suffix(HTML_HEADER_SUFFIX))
        })?;
    let (generator, contract) = inner.split_once(", ")?;
    if generator.is_empty() || contract.is_empty() {
        return None;
    }
    Some((generator, contract))
}

#[cfg(not(windows))]
fn remove_stale_file(path: &Path) -> Result<()> {
    match fs::remove_file(path) {
        Ok(()) => Ok(()),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(err) => Err(err).with_context(|| format!("failed to remove stale {}", path.display())),
    }
}

#[cfg(windows)]
fn remove_stale_file(path: &Path) -> Result<()> {
    const RETRIES: usize = 32;
    for attempt in 0..=RETRIES {
        match fs::remove_file(path) {
            Ok(()) => return Ok(()),
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(()),
            Err(err) if err.kind() == std::io::ErrorKind::PermissionDenied && attempt < RETRIES => {
                // Windows refuses deletion while another process has the file open without
                // delete sharing. A concurrent witforge writer only holds that handle briefly.
                std::thread::sleep(std::time::Duration::from_millis(1));
            }
            Err(err) => {
                return Err(err)
                    .with_context(|| format!("failed to remove stale {}", path.display()));
            }
        }
    }
    unreachable!("the final removal attempt returns")
}

/// Replace `path` with `contents` through a temporary file in the same directory.
///
/// A failed write leaves the previous file untouched and removes the temporary file. The
/// temporary name is hidden, prefixed with `.witforge.`, and unique per process/call. If `path`
/// already exists, its permission bits are copied onto the temporary file before rename so a
/// replaced file keeps its mode (including read-only files in a writable directory).
fn write_atomic(path: &Path, contents: &[u8]) -> Result<()> {
    let parent = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    let name = path
        .file_name()
        .with_context(|| format!("output path `{}` has no file name", path.display()))?;
    let existing_perms = fs::symlink_metadata(path)
        .ok()
        .filter(fs::Metadata::is_file)
        .map(|metadata| metadata.permissions());
    let sequence = TEMP_COUNTER.fetch_add(1, Ordering::Relaxed);
    let temporary = parent.join(format!(
        ".witforge.{}.{}.{}.tmp",
        name.to_string_lossy(),
        std::process::id(),
        sequence
    ));
    let result = (|| -> Result<()> {
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temporary)
            .with_context(|| format!("failed to create {}", temporary.display()))?;
        file.write_all(contents)
            .with_context(|| format!("failed to write {}", temporary.display()))?;
        file.sync_all()
            .with_context(|| format!("failed to sync {}", temporary.display()))?;
        drop(file);
        if let Some(perms) = existing_perms {
            #[cfg(windows)]
            let was_readonly = perms.readonly();
            fs::set_permissions(&temporary, perms)
                .with_context(|| format!("failed to set permissions on {}", temporary.display()))?;
            #[cfg(windows)]
            if was_readonly
                && let Ok(mut target_perms) = fs::metadata(path).map(|m| m.permissions())
            {
                #[allow(clippy::permissions_set_readonly_false)]
                target_perms.set_readonly(false);
                let _ = fs::set_permissions(path, target_perms);
            }
        }
        fs::rename(&temporary, path)
            .with_context(|| format!("failed to replace {}", path.display()))?;
        Ok(())
    })();
    if result.is_err() {
        #[cfg(windows)]
        if let Ok(mut perms) = fs::metadata(&temporary).map(|m| m.permissions())
            && perms.readonly()
        {
            #[allow(clippy::permissions_set_readonly_false)]
            perms.set_readonly(false);
            let _ = fs::set_permissions(&temporary, perms);
        }
        let _ = fs::remove_file(&temporary);
    }
    result
}

/// Maximum symbolic-link hops followed when resolving a dangling output path.
const MAX_SYMLINK_DEPTH: usize = 40;

/// Refuse an output root that is, lies inside, or contains the WIT root.
///
/// Both paths are resolved to canonical form before they are compared: the WIT root is
/// canonicalised, and each existing prefix component of the output root is canonicalised (which
/// follows symlinks, Windows junctions, and case-insensitive spellings). A `..` component after a
/// component that does not exist yet is refused rather than collapsed lexically, so a path such as
/// `missing/../witlink/v0.1` cannot bypass the guard.
///
/// This guard prevents accidental writes into the WIT tree; it does not defend against a local
/// attacker swapping a symlink between the check and the write.
///
/// # Errors
///
/// Returns an error when the WIT root cannot be resolved, the output path uses `..` after a
/// missing component, or the output path is equal to, inside, or an ancestor of the WIT root.
pub fn ensure_outside_wit_root(wit_root: &Path, out: &Path) -> Result<()> {
    let root = fs::canonicalize(wit_root)
        .with_context(|| format!("failed to resolve WIT root {}", wit_root.display()))?;
    let resolved = resolve_output_root(out)?;
    if paths_overlap(&resolved, &root) {
        return Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            format!(
                "output root {} must not be the WIT root, inside it, or contain it ({})",
                out.display(),
                root.display()
            ),
            Some(out.display().to_string()),
        ));
    }
    Ok(())
}

/// Refuse an output root that is, lies inside, or contains any directory listed in `manifest`.
///
/// `manifest_dir` is the directory that owns the `released` manifest (usually the WIT root, or
/// the parent of an explicit `--released` file). Uses the same canonical path resolution as
/// [`ensure_outside_wit_root`].
///
/// # Errors
///
/// Returns an error when the output path or a released directory cannot be resolved, or when the
/// output path overlaps any listed released directory.
pub fn ensure_outside_released(
    manifest_dir: &Path,
    manifest: &crate::ReleasedManifest,
    out: &Path,
) -> Result<()> {
    if manifest.directories().is_empty() {
        return Ok(());
    }
    let resolved = resolve_output_root(out)?;
    for entry in manifest.directories() {
        let released = manifest_dir.join(entry);
        let canonical = fs::canonicalize(&released).with_context(|| {
            format!(
                "failed to resolve released directory `{entry}` ({})",
                released.display()
            )
        })?;
        if paths_overlap(&resolved, &canonical) {
            return Err(crate::operational_error(
                crate::diagnostic::codes::GUARD_REFUSED,
                format!(
                    "output root {} must not be, contain, or lie inside released directory \
                     `{entry}` ({})",
                    out.display(),
                    canonical.display()
                ),
                Some(out.display().to_string()),
            ));
        }
    }
    Ok(())
}

/// Resolve an output root to a canonical absolute path without lexically collapsing `..` across
/// missing components.
///
/// Every existing component (including symlinks and Windows junctions) is canonicalised step by
/// step; a dangling symlink target is resolved recursively up to a hop limit. Any `..` component
/// that appears after a missing component is refused.
///
/// # Errors
///
/// Returns an error when the current directory or an existing prefix cannot be resolved, a
/// symbolic-link loop is encountered, or `..` appears after a missing path component.
pub fn resolve_output_root(path: &Path) -> Result<PathBuf> {
    resolve_components(path, path, 0)
}

/// Refuse any pair of configured output roots that coincide or nest after resolving existing
/// prefixes and symlinks.
///
/// # Errors
///
/// Returns an error when an output root cannot be resolved or when any two roots coincide or one
/// lies inside the other.
pub fn ensure_distinct_output_roots(roots: &[(&str, &Path)]) -> Result<()> {
    let mut resolved: Vec<(&str, &Path, PathBuf)> = Vec::with_capacity(roots.len());
    for &(label, path) in roots {
        let canon = resolve_output_root(path)
            .with_context(|| format!("invalid output root for `{label}`"))?;
        resolved.push((label, path, canon));
    }
    for (index, (left_label, left_raw, left_canon)) in resolved.iter().enumerate() {
        for (right_label, right_raw, right_canon) in &resolved[index + 1..] {
            if paths_overlap_for_platform(left_canon, right_canon) {
                return Err(crate::operational_error(
                    crate::diagnostic::codes::GUARD_REFUSED,
                    format!(
                        "configured output roots `{left_label}` ({}) and `{right_label}` ({}) \
                         overlap; each generator and project must have its own non-overlapping \
                         output root",
                        left_raw.display(),
                        right_raw.display()
                    ),
                    Some(right_raw.display().to_string()),
                ));
            }
        }
    }
    Ok(())
}

fn paths_overlap(left: &Path, right: &Path) -> bool {
    left.starts_with(right) || right.starts_with(left)
}

fn paths_overlap_for_platform(left: &Path, right: &Path) -> bool {
    paths_overlap(left, right) || paths_overlap_case_insensitive_on_platform(left, right)
}

#[cfg(any(target_os = "windows", target_os = "macos"))]
fn paths_overlap_case_insensitive_on_platform(left: &Path, right: &Path) -> bool {
    paths_overlap_ascii_case_insensitive(left, right)
}

#[cfg(not(any(target_os = "windows", target_os = "macos")))]
fn paths_overlap_case_insensitive_on_platform(_left: &Path, _right: &Path) -> bool {
    false
}

#[cfg(any(test, target_os = "windows", target_os = "macos"))]
fn paths_overlap_ascii_case_insensitive(left: &Path, right: &Path) -> bool {
    let left_parts: Vec<String> = left
        .components()
        .map(|c| c.as_os_str().to_string_lossy().to_ascii_lowercase())
        .collect();
    let right_parts: Vec<String> = right
        .components()
        .map(|c| c.as_os_str().to_string_lossy().to_ascii_lowercase())
        .collect();
    let shared = left_parts.len().min(right_parts.len());
    left_parts[..shared] == right_parts[..shared]
}

#[allow(clippy::too_many_lines)]
fn resolve_components(original: &Path, path: &Path, depth: usize) -> Result<PathBuf> {
    if path.as_os_str().is_empty() {
        return Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            "output root must not be empty",
            None,
        ));
    }
    if depth > MAX_SYMLINK_DEPTH {
        return Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            format!(
                "failed to resolve {}: too many levels of symbolic links",
                original.display()
            ),
            Some(original.display().to_string()),
        ));
    }
    let mut current = if path.is_relative() {
        let cwd = std::env::current_dir().context("failed to read the current directory")?;
        fs::canonicalize(&cwd)
            .with_context(|| format!("failed to resolve current directory {}", cwd.display()))?
    } else {
        PathBuf::new()
    };
    let mut missing_tail = false;

    for component in path.components() {
        match component {
            Component::Prefix(prefix) => {
                current.push(prefix.as_os_str());
            }
            Component::RootDir => {
                current.push(Component::RootDir.as_os_str());
                if let Ok(canon) = fs::canonicalize(&current) {
                    current = canon;
                }
            }
            Component::CurDir => {}
            Component::ParentDir => {
                if missing_tail {
                    return Err(crate::operational_error(
                        crate::diagnostic::codes::GUARD_REFUSED,
                        format!(
                            "output root {} must not contain `..` after a missing directory \
                             component (it must not be the WIT root, inside it, or contain it)",
                            original.display()
                        ),
                        Some(original.display().to_string()),
                    ));
                }
                current.push(Component::ParentDir);
                current = fs::canonicalize(&current)
                    .with_context(|| format!("failed to resolve {}", original.display()))?;
            }
            Component::Normal(name) => {
                current.push(name);
                if missing_tail {
                    continue;
                }
                match fs::symlink_metadata(&current) {
                    Ok(metadata) if metadata.file_type().is_symlink() => {
                        match fs::canonicalize(&current) {
                            Ok(canon) => current = canon,
                            Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                                let target = fs::read_link(&current).with_context(|| {
                                    format!("failed to read symlink {}", current.display())
                                })?;
                                let next = if target.is_absolute() {
                                    target
                                } else {
                                    current
                                        .parent()
                                        .unwrap_or_else(|| Path::new("."))
                                        .join(target)
                                };
                                current = resolve_components(original, &next, depth + 1)?;
                                missing_tail = true;
                            }
                            Err(err) => {
                                return Err(err).with_context(|| {
                                    format!("failed to resolve {}", original.display())
                                });
                            }
                        }
                    }
                    Ok(_) => {
                        current = fs::canonicalize(&current)
                            .with_context(|| format!("failed to resolve {}", original.display()))?;
                    }
                    Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                        missing_tail = true;
                    }
                    Err(err) => {
                        return Err(err)
                            .with_context(|| format!("failed to resolve {}", original.display()));
                    }
                }
            }
        }
    }
    if current.as_os_str().is_empty() {
        bail!("failed to resolve {}", original.display());
    }
    Ok(current)
}

