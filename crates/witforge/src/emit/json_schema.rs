//! Deterministic Draft 7 JSON Schema generation from the owned model.
//!
//! The schema is a value projection, not a wire format: every contract version gets one
//! `v<major>_<minor>.schema.json` file whose `definitions` contain every named type. There is
//! no root instance type, so consumers select a definition with `$ref`.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result};

use crate::emit::output::{GeneratedFiles, ensure_outside_wit_root};
use crate::emit::rust::version_module_name;
use crate::emit::versions::{Version, load_versions};
use crate::model::{Interface, Model, ResultExpr, TypeDef, TypeDefKind, TypeExpr};

/// The first line of every generated schema.
///
/// The comma is part of the JSON object, so the complete file remains valid Draft 7 JSON while
/// [`GeneratedFiles`] can still recognise the ownership prefix as a first-line header.
pub const HEADER: &str = "{\"$comment\":\"@generated by witforge; do not edit.\",";

/// Plan JSON Schema output for every version under `wit_root`.
///
/// # Errors
///
/// Returns an error for invalid input or an output-root or I/O failure.
pub fn plan(wit_root: &Path) -> Result<GeneratedFiles> {
    plan_versions(&load_versions(wit_root)?)
}

/// Plan JSON Schema output for validated `versions`.
pub(crate) fn plan_versions(versions: &[Version]) -> Result<GeneratedFiles> {
    let mut files = GeneratedFiles::new(HEADER);
    for version in versions {
        let module = version_module_name(&version.model);
        let generated = emit_version(&version.model)
            .with_context(|| version.directory.display().to_string())?;
        files.insert(format!("{module}.schema.json"), generated)?;
    }
    Ok(files)
}

/// Generate JSON Schema output under `out`.
///
/// # Errors
///
/// Returns an error for invalid input, an output root inside the WIT tree, or an I/O failure.
pub fn generate(wit_root: &Path, out: &Path) -> Result<()> {
    ensure_outside_wit_root(wit_root, out)?;
    plan(wit_root)?.write(out)
}

/// Check generated JSON Schema output under `out` without writing.
///
/// # Errors
///
/// Returns an error for invalid input, an output root inside the WIT tree, or an I/O failure.
pub fn check(wit_root: &Path, out: &Path) -> Result<Vec<String>> {
    ensure_outside_wit_root(wit_root, out)?;
    plan(wit_root)?.check(out)
}

/// Emit one version's complete JSON Schema document.
///
/// # Errors
///
/// Returns a [`crate::ContractError`] when a WIT name or schema shape cannot be represented and a
/// plain error when the model contains a dangling named type.
pub fn emit_version(model: &Model) -> Result<String> {
    let mut out = String::new();
    writeln!(out, "{HEADER}")?;
    writeln!(
        out,
        "  \"$schema\": \"http://json-schema.org/draft-07/schema#\","
    )?;
    writeln!(
        out,
        "  \"title\": {},",
        json_string(&format!(
            "{}:{}@{}",
            model.package.namespace, model.package.name, model.package.version
        ))
    )?;
    writeln!(out, "  \"definitions\": {{")?;
    let mut definitions = Vec::new();
    for interface in &model.interfaces {
        for def in &interface.types {
            let key = format!("{}/{}", interface.name, def.name);
            let schema = definition_schema(model, interface, def)?;
            definitions.push(format!("    {}: {}", json_string(&key), schema));
        }
    }
    write!(out, "{}", definitions.join(",\n"))?;
    writeln!(out)?;
    writeln!(out, "  }}")?;
    writeln!(out, "}}")?;
    Ok(out)
}

fn definition_schema(model: &Model, interface: &Interface, def: &TypeDef) -> Result<String> {
    let schema = match &def.kind {
        TypeDefKind::Record(fields) => {
            let mut properties = Vec::new();
            let mut required = Vec::new();
            for field in fields {
                properties.push(format!(
                    "{}:{}",
                    json_string(&field.name),
                    type_schema(model, interface, &field.ty)?
                ));
                required.push(json_string(&field.name));
            }
            format!(
                "{{\"type\":\"object\",\"properties\":{{{}}},\"required\":[{}],\"additionalProperties\":false}}",
                properties.join(","),
                required.join(",")
            )
        }
        TypeDefKind::Variant(cases) => {
            let mut variants = Vec::new();
            for case in cases {
                let value = match &case.payload {
                    Some(payload) => type_schema(model, interface, payload)?,
                    None => "{\"type\":\"null\"}".to_string(),
                };
                let property = format!("{}:{}", json_string(&case.name), value);
                variants.push(format!(
                    "{{\"type\":\"object\",\"properties\":{{{property}}},\"required\":[{}],\"additionalProperties\":false}}",
                    json_string(&case.name)
                ));
            }
            format!("{{\"oneOf\":[{}]}}", variants.join(","))
        }
        TypeDefKind::Enum(cases) => format!(
            "{{\"type\":\"string\",\"enum\":[{}]}}",
            cases
                .iter()
                .map(|case| json_string(&case.name))
                .collect::<Vec<_>>()
                .join(",")
        ),
        TypeDefKind::Flags(flags) => {
            let mut properties = Vec::new();
            let mut required = Vec::new();
            for flag in flags {
                properties.push(format!(
                    "{}:{{\"type\":\"boolean\"}}",
                    json_string(&flag.name)
                ));
                required.push(json_string(&flag.name));
            }
            format!(
                "{{\"type\":\"object\",\"properties\":{{{}}},\"required\":[{}],\"additionalProperties\":false}}",
                properties.join(","),
                required.join(",")
            )
        }
        TypeDefKind::Alias(target) => type_schema(model, interface, target)?,
        TypeDefKind::List(element) => {
            format!(
                "{{\"type\":\"array\",\"items\":{}}}",
                type_schema(model, interface, element)?
            )
        }
        TypeDefKind::Option(payload) => option_schema(model, interface, payload)?,
        TypeDefKind::Result(result) => result_schema(model, interface, result)?,
    };
    Ok(with_description(&def.docs, schema))
}

fn type_schema(model: &Model, interface: &Interface, ty: &TypeExpr) -> Result<String> {
    match ty {
        TypeExpr::Bool => Ok("{\"type\":\"boolean\"}".to_string()),
        TypeExpr::U8 => Ok(integer_schema(0, u64::from(u8::MAX))),
        TypeExpr::U16 => Ok(integer_schema(0, u64::from(u16::MAX))),
        TypeExpr::U32 => Ok(integer_schema(0, u64::from(u32::MAX))),
        TypeExpr::U64 => Ok(integer_schema(0, u64::MAX)),
        TypeExpr::S8 => Ok(integer_schema(
            i64::from(i8::MIN),
            u64::from(i8::MAX.unsigned_abs()),
        )),
        TypeExpr::S16 => Ok(integer_schema(
            i64::from(i16::MIN),
            u64::from(i16::MAX.unsigned_abs()),
        )),
        TypeExpr::S32 => Ok(integer_schema(
            i64::from(i32::MIN),
            u64::from(i32::MAX.unsigned_abs()),
        )),
        TypeExpr::S64 => Ok(integer_schema(i64::MIN, i64::MAX.unsigned_abs())),
        TypeExpr::F32 | TypeExpr::F64 => Ok("{\"type\":\"number\"}".to_string()),
        TypeExpr::String => Ok("{\"type\":\"string\"}".to_string()),
        TypeExpr::Named(name) => {
            model
                .type_def(name)
                .with_context(|| format!("named type `{name}` is not in the model"))?;
            Ok(format!(
                "{{\"$ref\":{}}}",
                json_string(&format!(
                    "#/definitions/{}",
                    pointer(&format!("{}/{}", name.interface, name.name))
                ))
            ))
        }
        TypeExpr::List(element) => Ok(format!(
            "{{\"type\":\"array\",\"items\":{}}}",
            type_schema(model, interface, element)?
        )),
        TypeExpr::Option(payload) => option_schema(model, interface, payload),
        TypeExpr::Result(result) => result_schema(model, interface, result),
    }
}

fn option_schema(model: &Model, interface: &Interface, payload: &TypeExpr) -> Result<String> {
    Ok(format!(
        "{{\"anyOf\":[{},{{\"type\":\"null\"}}]}}",
        type_schema(model, interface, payload)?
    ))
}

fn result_schema(model: &Model, interface: &Interface, result: &ResultExpr) -> Result<String> {
    let mut variants = Vec::new();
    if let Some(ok) = &result.ok {
        variants.push(result_variant(model, interface, "ok", ok)?);
    }
    if let Some(err) = &result.err {
        variants.push(result_variant(model, interface, "err", err)?);
    }
    match variants.len() {
        0 => Ok(
            "{\"type\":\"object\",\"maxProperties\":0,\"additionalProperties\":false}".to_string(),
        ),
        1 => Ok(variants.remove(0)),
        _ => Ok(format!("{{\"oneOf\":[{}]}}", variants.join(","))),
    }
}

fn result_variant(
    model: &Model,
    interface: &Interface,
    name: &str,
    payload: &TypeExpr,
) -> Result<String> {
    let property = format!(
        "{}:{}",
        json_string(name),
        type_schema(model, interface, payload)?
    );
    Ok(format!(
        "{{\"type\":\"object\",\"properties\":{{{property}}},\"required\":[{}],\"additionalProperties\":false}}",
        json_string(name)
    ))
}

fn integer_schema(minimum: i64, maximum: u64) -> String {
    format!("{{\"type\":\"integer\",\"minimum\":{minimum},\"maximum\":{maximum}}}")
}

fn with_description(description: &str, schema: String) -> String {
    if description.is_empty() {
        schema
    } else {
        format!(
            "{{\"description\":{},{}",
            json_string(description),
            &schema[1..]
        )
    }
}

fn pointer(value: &str) -> String {
    value.replace('~', "~0").replace('/', "~1")
}

fn json_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{08}' => out.push_str("\\b"),
            '\u{0c}' => out.push_str("\\f"),
            ch if ch < '\u{20}' => {
                let _ = write!(out, "\\u{:04x}", u32::from(ch));
            }
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}
