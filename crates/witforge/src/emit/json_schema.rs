//! Deterministic Draft 7 JSON Schema generation from the owned model.
//!
//! The schema is a value projection, not a wire format: every contract version gets one
//! `v<major>_<minor>.schema.json` file whose `definitions` contain every named type. There is
//! no root instance type, so consumers select a definition with `$ref`.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result};

use crate::emit::output::{
    GeneratedFileFinding, GeneratedFiles, ensure_outside_wit_root, json_header,
};
use crate::emit::rust::version_module_name;
use crate::emit::stability_doc;
use crate::emit::versions::{
    DepLayout, Version, load_versions, load_versions_with_released, same_dependency,
};
use crate::model::{Dependency, Interface, Model, ResultExpr, TypeDef, TypeDefKind, TypeExpr};

/// Legacy pre-0.6.0 shared ownership header for JSON Schema files.
///
/// Current output writes a per-generator, per-contract `$comment` prefix
/// (`{"$comment":"@generated by witforge (schema, <namespace>:<name>); do not edit.",`); files
/// starting with this legacy header are adopted and rewritten on generation.
pub const HEADER: &str = "{\"$comment\":\"@generated by witforge; do not edit.\",";

fn header_for(namespace: &str, name: &str) -> String {
    json_header("schema", namespace, name)
}

/// Plan JSON Schema output for every version under `wit_root`.
///
/// # Errors
///
/// Returns an error for invalid input or an output-root or I/O failure.
pub fn plan(wit_root: &Path) -> Result<GeneratedFiles> {
    plan_versions(&load_versions(wit_root)?)
}

/// Plan JSON Schema output for `wit_root`, using an optional explicit released-version manifest
/// path (`--released`) when determining retired versions.
///
/// # Errors
///
/// Returns the same errors as [`plan`].
pub fn plan_with_released(wit_root: &Path, released: Option<&Path>) -> Result<GeneratedFiles> {
    plan_versions(&load_versions_with_released(wit_root, released)?)
}

/// Plan JSON Schema output for validated `versions`.
pub(crate) fn plan_versions(versions: &[Version]) -> Result<GeneratedFiles> {
    let dep_layout = DepLayout::from_versions(versions)?;
    let root_package = &versions
        .first()
        .context("no version directories found under WIT root")?
        .model
        .package;
    let header = header_for(&root_package.namespace, &root_package.name);
    let mut files = GeneratedFiles::new(&header);
    for version in versions {
        let module = version_module_name(&version.model);
        let generated =
            emit_version_with_layout(&version.model, &header, version.major, Some(&dep_layout))
                .with_context(|| version.directory.display().to_string())?;
        files.insert(format!("{module}.schema.json"), generated)?;
    }
    let mut emitted_dep_files: std::collections::BTreeMap<String, Dependency> =
        std::collections::BTreeMap::new();
    for (&major, deps) in &dep_layout.by_major {
        for dependency in deps {
            let filename = dep_layout.schema_file_name(major, dependency);
            if let Some(previous) = emitted_dep_files.get(&filename) {
                if previous.package.namespace == dependency.package.namespace
                    && previous.package.name == dependency.package.name
                    && same_dependency(previous, dependency)
                {
                    continue;
                }
                contract_bail!("dependency packages both generate `{filename}`");
            }
            let model = Model {
                package: dependency.package.clone(),
                interfaces: dependency.interfaces.clone(),
                worlds: Vec::new(),
                dependencies: deps
                    .iter()
                    .filter(|other| {
                        other.package.namespace != dependency.package.namespace
                            || other.package.name != dependency.package.name
                    })
                    .cloned()
                    .collect(),
            };
            let generated = emit_version_with_layout(&model, &header, major, Some(&dep_layout))
                .with_context(|| format!("dependency {}", dependency.package.name))?;
            emitted_dep_files.insert(filename.clone(), dependency.clone());
            files.insert(filename, generated)?;
        }
    }
    Ok(files)
}

/// Generate JSON Schema output under `out`.
///
/// # Errors
///
/// Returns an error for invalid input, an output root inside the WIT tree, or an I/O failure.
pub fn generate(wit_root: &Path, out: &Path) -> Result<()> {
    ensure_outside_wit_root(wit_root, out)?;
    plan(wit_root)?.write(out)
}

/// Check generated JSON Schema output under `out` without writing.
///
/// Returns one structured finding per missing, changed, or extra generated file.
///
/// # Errors
///
/// Returns an error for invalid input, an output root inside the WIT tree, or an I/O failure.
pub fn check(wit_root: &Path, out: &Path) -> Result<Vec<GeneratedFileFinding>> {
    ensure_outside_wit_root(wit_root, out)?;
    plan(wit_root)?.check(out)
}

/// Validate that `model` (root package and pinned dependencies) can be emitted to JSON Schema
/// without contract refusals.
pub(crate) fn validate_model(model: &Model) -> Result<()> {
    let header = header_for(&model.package.namespace, &model.package.name);
    let _ = emit_version_with_header(model, &header)?;
    let mut dependency_files = std::collections::BTreeSet::new();
    for dependency in &model.dependencies {
        let dep_model = Model {
            package: dependency.package.clone(),
            interfaces: dependency.interfaces.clone(),
            worlds: Vec::new(),
            dependencies: model
                .dependencies
                .iter()
                .filter(|other| {
                    other.package.namespace != dependency.package.namespace
                        || other.package.name != dependency.package.name
                })
                .cloned()
                .collect(),
        };
        let _ = emit_version_with_header(&dep_model, &header).with_context(|| {
            format!(
                "dependency {}:{}",
                dependency.package.namespace, dependency.package.name
            )
        })?;
        let filename = dependency_schema_filename(dependency);
        if !dependency_files.insert(filename.clone()) {
            contract_bail!("dependency packages both generate `{filename}`");
        }
    }
    Ok(())
}

/// Emit one version's complete JSON Schema document.
///
/// # Errors
///
/// Returns a [`crate::ContractError`] when a WIT name or schema shape cannot be represented and a
/// plain error when the model contains a dangling named type.
pub fn emit_version(model: &Model) -> Result<String> {
    let header = header_for(&model.package.namespace, &model.package.name);
    emit_version_with_header(model, &header)
}

fn emit_version_with_header(model: &Model, header: &str) -> Result<String> {
    emit_version_with_layout(model, header, model.package.version.major, None)
}

fn emit_version_with_layout(
    model: &Model,
    header: &str,
    root_major: u64,
    dep_layout: Option<&DepLayout>,
) -> Result<String> {
    let mut out = String::new();
    writeln!(out, "{header}")?;
    writeln!(
        out,
        "  \"$schema\": \"http://json-schema.org/draft-07/schema#\","
    )?;
    writeln!(
        out,
        "  \"title\": {},",
        json_string(&format!(
            "{}:{}@{}",
            model.package.namespace, model.package.name, model.package.version
        ))
    )?;
    if !model.package.docs.is_empty() {
        writeln!(
            out,
            "  \"description\": {},",
            json_string(&model.package.docs)
        )?;
    }
    writeln!(out, "  \"definitions\": {{")?;
    let mut definitions = Vec::new();
    for interface in &model.interfaces {
        for def in &interface.types {
            let key = format!("{}/{}", interface.name, def.name);
            let schema = definition_schema(model, interface, def, root_major, dep_layout)?;
            definitions.push(format!("    {}: {}", json_string(&key), schema));
        }
    }
    write!(out, "{}", definitions.join(",\n"))?;
    writeln!(out)?;
    writeln!(out, "  }}")?;
    writeln!(out, "}}")?;
    Ok(out)
}

fn definition_schema(
    model: &Model,
    interface: &Interface,
    def: &TypeDef,
    root_major: u64,
    dep_layout: Option<&DepLayout>,
) -> Result<String> {
    let schema = match &def.kind {
        TypeDefKind::Record(fields) => {
            let mut properties = Vec::new();
            let mut required = Vec::new();
            for field in fields {
                properties.push(format!(
                    "{}:{}",
                    json_string(&field.name),
                    type_schema(model, interface, &field.ty, root_major, dep_layout)?
                ));
                required.push(json_string(&field.name));
            }
            format!(
                "{{\"type\":\"object\",\"properties\":{{{}}},\"required\":[{}],\"additionalProperties\":false}}",
                properties.join(","),
                required.join(",")
            )
        }
        TypeDefKind::Variant(cases) => {
            let mut variants = Vec::new();
            for case in cases {
                let value = match &case.payload {
                    Some(payload) => {
                        type_schema(model, interface, payload, root_major, dep_layout)?
                    }
                    None => "{\"type\":\"null\"}".to_string(),
                };
                let property = format!("{}:{}", json_string(&case.name), value);
                variants.push(format!(
                    "{{\"type\":\"object\",\"properties\":{{{property}}},\"required\":[{}],\"additionalProperties\":false}}",
                    json_string(&case.name)
                ));
            }
            format!("{{\"oneOf\":[{}]}}", variants.join(","))
        }
        TypeDefKind::Enum(cases) => format!(
            "{{\"type\":\"string\",\"enum\":[{}]}}",
            cases
                .iter()
                .map(|case| json_string(&case.name))
                .collect::<Vec<_>>()
                .join(",")
        ),
        TypeDefKind::Flags(flags) => {
            let mut properties = Vec::new();
            let mut required = Vec::new();
            for flag in flags {
                properties.push(format!(
                    "{}:{{\"type\":\"boolean\"}}",
                    json_string(&flag.name)
                ));
                required.push(json_string(&flag.name));
            }
            format!(
                "{{\"type\":\"object\",\"properties\":{{{}}},\"required\":[{}],\"additionalProperties\":false}}",
                properties.join(","),
                required.join(",")
            )
        }
        TypeDefKind::Alias(target) => {
            type_schema(model, interface, target, root_major, dep_layout)?
        }
        TypeDefKind::List(element) => {
            let item = if model.resolves_to_u8(element) {
                TypeExpr::U8
            } else {
                element.clone()
            };
            format!(
                "{{\"type\":\"array\",\"items\":{}}}",
                type_schema(model, interface, &item, root_major, dep_layout)?
            )
        }
        TypeDefKind::Option(payload) => {
            option_schema(model, interface, payload, root_major, dep_layout)?
        }
        TypeDefKind::Result(result) => {
            result_schema(model, interface, result, root_major, dep_layout)?
        }
    };
    Ok(with_metadata(&def.docs, &def.stability, schema))
}

fn type_schema(
    model: &Model,
    interface: &Interface,
    ty: &TypeExpr,
    root_major: u64,
    dep_layout: Option<&DepLayout>,
) -> Result<String> {
    match ty {
        TypeExpr::Bool => Ok("{\"type\":\"boolean\"}".to_string()),
        TypeExpr::U8 => Ok(integer_schema(0, u64::from(u8::MAX))),
        TypeExpr::U16 => Ok(integer_schema(0, u64::from(u16::MAX))),
        TypeExpr::U32 => Ok(integer_schema(0, u64::from(u32::MAX))),
        TypeExpr::U64 => Ok(integer_schema(0, u64::MAX)),
        TypeExpr::S8 => Ok(integer_schema(
            i64::from(i8::MIN),
            u64::from(i8::MAX.unsigned_abs()),
        )),
        TypeExpr::S16 => Ok(integer_schema(
            i64::from(i16::MIN),
            u64::from(i16::MAX.unsigned_abs()),
        )),
        TypeExpr::S32 => Ok(integer_schema(
            i64::from(i32::MIN),
            u64::from(i32::MAX.unsigned_abs()),
        )),
        TypeExpr::S64 => Ok(integer_schema(i64::MIN, i64::MAX.unsigned_abs())),
        TypeExpr::F32 => Ok(
            "{\"type\":\"number\",\"minimum\":-3.4028235e38,\"maximum\":3.4028235e38}".to_string(),
        ),
        TypeExpr::F64 => Ok("{\"type\":\"number\"}".to_string()),
        TypeExpr::String => Ok("{\"type\":\"string\"}".to_string()),
        TypeExpr::Named(name) => {
            if let Some((namespace, package)) = name.package() {
                let dependency =
                    model
                        .dependency_package(namespace, package)
                        .with_context(|| {
                            format!("dependency `{namespace}:{package}` is not in the model")
                        })?;
                let key = format!("{}/{}", name.interface_name(), name.name);
                let filename = dep_layout.map_or_else(
                    || dependency_schema_filename(dependency),
                    |layout| layout.schema_file_name(root_major, dependency),
                );
                return Ok(format!(
                    "{{\"$ref\":{}}}",
                    json_string(&format!("{filename}#/definitions/{}", pointer(&key)))
                ));
            }
            model
                .type_def(name)
                .with_context(|| format!("named type `{name}` is not in the model"))?;
            Ok(format!(
                "{{\"$ref\":{}}}",
                json_string(&format!(
                    "#/definitions/{}",
                    pointer(&format!("{}/{}", name.interface, name.name))
                ))
            ))
        }
        TypeExpr::List(element) => {
            let item = if model.resolves_to_u8(element) {
                TypeExpr::U8
            } else {
                element.as_ref().clone()
            };
            Ok(format!(
                "{{\"type\":\"array\",\"items\":{}}}",
                type_schema(model, interface, &item, root_major, dep_layout)?
            ))
        }
        TypeExpr::Option(payload) => {
            option_schema(model, interface, payload, root_major, dep_layout)
        }
        TypeExpr::Result(result) => result_schema(model, interface, result, root_major, dep_layout),
    }
}

fn option_schema(
    model: &Model,
    interface: &Interface,
    payload: &TypeExpr,
    root_major: u64,
    dep_layout: Option<&DepLayout>,
) -> Result<String> {
    Ok(format!(
        "{{\"anyOf\":[{},{{\"type\":\"null\"}}]}}",
        type_schema(model, interface, payload, root_major, dep_layout)?
    ))
}

fn result_schema(
    model: &Model,
    interface: &Interface,
    result: &ResultExpr,
    root_major: u64,
    dep_layout: Option<&DepLayout>,
) -> Result<String> {
    let ok = result_variant(
        model,
        interface,
        "ok",
        result.ok.as_deref(),
        root_major,
        dep_layout,
    )?;
    let err = result_variant(
        model,
        interface,
        "err",
        result.err.as_deref(),
        root_major,
        dep_layout,
    )?;
    Ok(format!("{{\"oneOf\":[{ok},{err}]}}"))
}

fn result_variant(
    model: &Model,
    interface: &Interface,
    name: &str,
    payload: Option<&TypeExpr>,
    root_major: u64,
    dep_layout: Option<&DepLayout>,
) -> Result<String> {
    let value = match payload {
        Some(payload) => type_schema(model, interface, payload, root_major, dep_layout)?,
        None => "{\"type\":\"null\"}".to_string(),
    };
    let property = format!("{}:{value}", json_string(name));
    Ok(format!(
        "{{\"type\":\"object\",\"properties\":{{{property}}},\"required\":[{}],\"additionalProperties\":false}}",
        json_string(name)
    ))
}

fn integer_schema(minimum: i64, maximum: u64) -> String {
    format!("{{\"type\":\"integer\",\"minimum\":{minimum},\"maximum\":{maximum}}}")
}

fn with_metadata(description: &str, stability: &crate::model::Stability, schema: String) -> String {
    let stability_description = stability_doc(stability);
    let description = match (description.is_empty(), stability_description) {
        (true, None) => None,
        (false, None) => Some(description.to_string()),
        (true, Some(stability)) => Some(stability),
        (false, Some(stability)) => Some(format!("{description}\n\n{stability}")),
    };
    let mut metadata = Vec::new();
    if let Some(description) = description {
        metadata.push(format!("\"description\":{}", json_string(&description)));
    }
    if stability.deprecated().is_some() {
        metadata.push("\"deprecated\":true".to_string());
    }
    if metadata.is_empty() {
        schema
    } else {
        format!("{{{},{}", metadata.join(","), &schema[1..])
    }
}

fn dependency_schema_filename(dependency: &Dependency) -> String {
    format!(
        "{}.{}.v{}.schema.json",
        dependency.package.namespace.replace('-', "_"),
        dependency.package.name.replace('-', "_"),
        dependency.package.version.major
    )
}

fn pointer(value: &str) -> String {
    value.replace('~', "~0").replace('/', "~1")
}

fn json_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{08}' => out.push_str("\\b"),
            '\u{0c}' => out.push_str("\\f"),
            ch if ch.is_control() || matches!(ch, '\u{2028}' | '\u{2029}') => {
                let _ = write!(out, "\\u{:04x}", u32::from(ch));
            }
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}
