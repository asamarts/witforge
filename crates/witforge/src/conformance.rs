#[allow(clippy::struct_field_names)]
struct ScalarFields<'a> {
    a_f32: Option<(f32, &'static str)>,
    a_f64: Option<(f64, &'static str)>,
    a_bool: Option<bool>,
    a_char: Option<u32>,
    a_string: Option<&'a str>,
}

impl ScalarFields<'_> {
    fn encode(&self, w: &WireNums<'_>) -> Result<(Vec<u8>, String, JsonValue)> {
        let mut pb = ProtoBuf::new();
        let mut p3 = Vec::new();
        let mut plain = Vec::new();
        if let Some((v, json_repr)) = self.a_f32 {
            pb.f32_field(w.root("witforge:conformance/types/scalars.a-f32")?, v);
            let jv = if v.is_finite() {
                JsonValue::num(json_repr)
            } else {
                JsonValue::str(json_repr)
            };
            p3.push(("aF32".to_string(), jv.clone()));
            plain.push(("a-f32".to_string(), jv));
        }
        if let Some((v, json_repr)) = self.a_f64 {
            pb.f64_field(w.root("witforge:conformance/types/scalars.a-f64")?, v);
            let jv = if v.is_finite() {
                JsonValue::num(json_repr)
            } else {
                JsonValue::str(json_repr)
            };
            p3.push(("aF64".to_string(), jv.clone()));
            plain.push(("a-f64".to_string(), jv));
        }
        if let Some(v) = self.a_bool {
            pb.bool_field(w.root("witforge:conformance/types/scalars.a-bool")?, v);
            p3.push(("aBool".to_string(), JsonValue::Bool(v)));
            plain.push(("a-bool".to_string(), JsonValue::Bool(v)));
        }
        if let Some(cp) = self.a_char {
            pb.uint32(w.root("witforge:conformance/types/scalars.a-char")?, cp);
            p3.push(("aChar".to_string(), JsonValue::Uint(u64::from(cp))));
            if let Some(ch) = char::from_u32(cp) {
                plain.push(("a-char".to_string(), JsonValue::str(ch.to_string())));
            }
        }
        if let Some(s) = self.a_string {
            pb.string_field(w.root("witforge:conformance/types/scalars.a-string")?, s);
            p3.push(("aString".to_string(), JsonValue::str(s)));
            plain.push(("a-string".to_string(), JsonValue::str(s)));
        }
        Ok((
            pb.bytes,
            JsonValue::obj_owned(p3).render_compact(),
            JsonValue::obj_owned(plain),
        ))
    }
}

