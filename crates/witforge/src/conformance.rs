struct WireNums<'a> {
    root: &'a WireLock,
    dep: &'a WireLock,
}

impl WireNums<'_> {
    fn root(&self, key: &str) -> Result<u32> {
        Ok(self
            .root
            .get(key)
            .with_context(|| format!("missing conformance root wire number for `{key}`"))?
            .number)
    }

    fn dep(&self, key: &str) -> Result<u32> {
        Ok(self
            .dep
            .get(key)
            .with_context(|| format!("missing conformance dep wire number for `{key}`"))?
            .number)
    }

    fn root_enum(&self, key: &str) -> Result<i32> {
        i32::try_from(self.root(key)?).context("enum wire number out of i32 range")
    }

    fn dep_enum(&self, key: &str) -> Result<i32> {
        i32::try_from(self.dep(key)?).context("dependency enum wire number out of i32 range")
    }
}

struct VectorSpec {
    id: &'static str,
    category: &'static str,
    direction: &'static str,
    target_kind: &'static str,
    target: &'static str,
    proto_message: &'static str,
    expected: &'static str,
    error_kind: Option<&'static str>,
    error_target: Option<&'static str>,
    proto_binary: Option<Vec<u8>>,
    proto3_json: Option<String>,
    plain_json: JsonValue,
    description: &'static str,
}

impl VectorSpec {
    fn to_json(&self) -> JsonValue {
        JsonValue::obj([
            ("id", JsonValue::str(self.id)),
            ("category", JsonValue::str(self.category)),
            ("direction", JsonValue::str(self.direction)),
            ("target_kind", JsonValue::str(self.target_kind)),
            ("target", JsonValue::str(self.target)),
            ("proto_message", JsonValue::str(self.proto_message)),
            ("expected", JsonValue::str(self.expected)),
            (
                "error_kind",
                self.error_kind.map_or(JsonValue::Null, JsonValue::str),
            ),
            (
                "error_target",
                self.error_target.map_or(JsonValue::Null, JsonValue::str),
            ),
            (
                "proto_binary_base64",
                self.proto_binary
                    .as_deref()
                    .map_or(JsonValue::Null, |b| JsonValue::str(base64_encode(b))),
            ),
            (
                "proto3_json",
                self.proto3_json
                    .as_deref()
                    .map_or(JsonValue::Null, JsonValue::str),
            ),
            ("plain_json", self.plain_json.clone()),
            ("description", JsonValue::str(self.description)),
        ])
    }
}

