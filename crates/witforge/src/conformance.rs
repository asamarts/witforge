fn encode_shared_meta(
    w: &WireNums<'_>,
    id: u64,
    tag: u32,
    status: i32,
    status_json: JsonValue,
) -> Result<(ProtoBuf, JsonValue)> {
    let mut pb = ProtoBuf::new();
    pb.uint64(w.dep("witforge:conformance-dep/shared/shared-meta.id")?, id);
    pb.uint32(
        w.dep("witforge:conformance-dep/shared/shared-meta.tag")?,
        tag,
    );
    pb.enum_i32(
        w.dep("witforge:conformance-dep/shared/shared-meta.status")?,
        status,
    );
    let p3 = JsonValue::obj([
        ("id", JsonValue::str(id.to_string())),
        ("tag", JsonValue::Uint(u64::from(tag))),
        ("status", status_json),
    ]);
    Ok((pb, p3))
}

