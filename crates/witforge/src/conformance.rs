fn base_valid_collections(w: &WireNums<'_>) -> Result<(ProtoBuf, Vec<(String, JsonValue)>)> {
    let f_raw = w.root("witforge:conformance/types/collections.raw-bytes")?;
    let f_fixed_b = w.root("witforge:conformance/types/collections.fixed-bytes")?;
    let f_fixed_u16 = w.root("witforge:conformance/types/collections.fixed-u16s")?;
    let f_fixed_ch = w.root("witforge:conformance/types/collections.fixed-chars")?;

    let mut pb = ProtoBuf::new();
    pb.bytes_field(f_raw, &[]);
    pb.bytes_field(f_fixed_b, &[0, 0, 0, 0]);
    pb.packed_uint32(f_fixed_u16, &[0, 1, 65_535]);
    pb.packed_uint32(f_fixed_ch, &[0, 0x0001_F680]);

    let p3 = vec![
        ("rawBytes".to_string(), JsonValue::str("")),
        (
            "fixedBytes".to_string(),
            JsonValue::str(base64_encode(&[0, 0, 0, 0])),
        ),
        (
            "fixedU16s".to_string(),
            JsonValue::arr([
                JsonValue::Uint(0),
                JsonValue::Uint(1),
                JsonValue::Uint(65_535),
            ]),
        ),
        (
            "fixedChars".to_string(),
            JsonValue::arr([JsonValue::Uint(0), JsonValue::Uint(0x0001_F680)]),
        ),
    ];
    Ok((pb, p3))
}

