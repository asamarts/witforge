//! Cross-language protobuf conformance profile and deterministic fixture bundle (`W11-034`).
//!
//! Standard protobuf generators do not enforce witforge's narrow-integer bounds (`u8`, `u16`,
//! `s8`, `s16`), Unicode scalar `char` checks, required proto3 `optional` / message presence,
//! closed enums, selected variant/result oneofs, exact-length `list<T, N>`, `map<K, V>` key
//! validation, or synthesized wrapper state rules.
//!
//! This module emits a self-contained, deterministic, schema-versioned conformance bundle
//! (`CONFORMANCE_VERSION = 1`) containing:
//!
//! - `wit/v0.1/contract.wit`, `wit/v0.1/deps/conformance-dep/dep.wit`, and `wit/v0.1/wire.lock`:
//!   the canonical built-in WIT conformance contract exercising every row of the witforge protobuf
//!   decode/encode profile plus foreign `deps/` types and interface functions.
//! - `proto/v0.proto` and `proto/witforge.conformance_dep.v0.proto`: the exact protobuf schemas
//!   emitted by [`crate::emit::proto`] (honoring opt-in [`ProtoOptions`]).
//! - `vectors.json`: a deterministic manifest (`conformance_version: 1`) containing binary
//!   protobuf payloads (RFC 4648 base64), canonical proto3-JSON payloads, expected accept/reject
//!   outcomes, `GlueError` categories, and encode-side (`toProto`) boundary rejection vectors for
//!   host languages without native narrow/unsigned/scalar-char/fixed-array types.

