/// Options controlling cross-language conformance bundle generation.
///
/// By default (`ConformanceOptions::new()` / `Default`), emitted `.proto` files carry no
/// language-specific file options so output remains neutral across every protobuf toolchain.
/// Use [`Self::with_proto`] or [`Self::polyglot`] to embed Go, Java, and C# protobuf file options
/// in the conformance bundle's `proto/` directory.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
#[non_exhaustive]
pub struct ConformanceOptions {
    /// Optional protobuf file-level language options forwarded to [`crate::emit::proto`].
    pub proto: ProtoOptions,
}

impl ConformanceOptions {
    /// Create default conformance bundle options (neutral `.proto` files with no file options).
    #[must_use]
    pub const fn new() -> Self {
        Self {
            proto: ProtoOptions::new(),
        }
    }

    /// Create conformance bundle options populated with canonical Go, Java, and C# protobuf file
    /// options suitable for cross-language conformance harnesses.
    #[must_use]
    pub fn polyglot() -> Self {
        Self {
            proto: Self::polyglot_proto_options(),
        }
    }

    /// Return the canonical Go, Java, and C# [`ProtoOptions`] for the built-in conformance
    /// contract.
    #[must_use]
    pub fn polyglot_proto_options() -> ProtoOptions {
        ProtoOptions::new()
            .with_go_package_prefix("example.com/witforge/conformance/gen/go")
            .with_java_package_prefix("io.witforge.conformance")
            .with_java_multiple_files(true)
            .with_csharp_namespace_prefix("Witforge.Conformance")
    }

    /// Configure explicit protobuf file options for the conformance bundle's `.proto` files.
    #[must_use]
    pub fn with_proto(mut self, proto: ProtoOptions) -> Self {
        self.proto = proto;
        self
    }
}

/// A planned cross-language conformance fixture bundle ready to inspect, write, check, or diff.
///
/// The bundle manages three disjoint generated-file roots under an output directory `<out>`:
///
/// - `<out>/vectors.json`: the versioned (`conformance_version = 1`) vector manifest.
/// - `<out>/proto/`: the emitted `.proto` files (`v0.proto` and
///   `witforge.conformance_dep.v0.proto`).
/// - `<out>/wit/`: the built-in canonical WIT conformance contract (`v0.1/contract.wit`,
///   `v0.1/deps/conformance-dep/dep.wit`, and `v0.1/wire.lock`).
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub struct ConformanceBundle {
    root: GeneratedFiles,
    proto: GeneratedFiles,
    wit: GeneratedFiles,
}

impl ConformanceBundle {
    /// Schema version of the emitted `vectors.json` manifest (`CONFORMANCE_VERSION`).
    #[must_use]
    pub const fn conformance_version(&self) -> u32 {
        CONFORMANCE_VERSION
    }

    /// Top-level bundle files (`vectors.json`) written directly inside `<out>`.
    #[must_use]
    pub fn root_files(&self) -> &GeneratedFiles {
        &self.root
    }

    /// Protobuf schema files written under `<out>/proto/`.
    #[must_use]
    pub fn proto_files(&self) -> &GeneratedFiles {
        &self.proto
    }

    /// Canonical WIT contract and lockfile written under `<out>/wit/`.
    #[must_use]
    pub fn wit_files(&self) -> &GeneratedFiles {
        &self.wit
    }

    /// The exact rendered `vectors.json` manifest contents.
    #[must_use]
    pub fn vectors_json(&self) -> &str {
        self.root
            .files()
            .get("vectors.json")
            .map_or("", String::as_str)
    }

    /// Write the full conformance bundle under `out`.
    ///
    /// Validates `out`, `out/proto`, and `out/wit` for empty paths, symlinks (including trailing-
    /// slash and dangling symlinks), non-directory blockers, foreign witforge headers, and unowned
    /// collisions before writing any file.
    ///
    /// # Errors
    ///
    /// Returns an operational error (`WF9004`) if `out` or any target path is empty, a symlink,
    /// a non-directory, a foreign-owned generated file, or an unowned colliding file, or an I/O
    /// error if writing fails.
    pub fn write(&self, out: &Path) -> Result<()> {
        let (out_norm, exists) = validate_bundle_root(out, false)?;
        if exists {
            let proto_dir = out_norm.join("proto");
            let wit_dir = out_norm.join("wit");
            let proto_exists = ensure_subdir_writable(&proto_dir)?;
            let wit_exists = ensure_subdir_writable(&wit_dir)?;
            preflight_check_owned(&self.root, &out_norm)?;
            if proto_exists {
                preflight_check_owned(&self.proto, &proto_dir)?;
            }
            if wit_exists {
                preflight_check_owned(&self.wit, &wit_dir)?;
            }
        }
        self.root.write(&out_norm)?;
        self.proto.write(&out_norm.join("proto"))?;
        self.wit.write(&out_norm.join("wit"))?;
        Ok(())
    }

    /// Check an existing conformance bundle under `out` without writing.
    ///
    /// # Errors
    ///
    /// Returns `WF9004` if `out` is empty, a symlink, or not a directory; `WF9002` if `out` does
    /// not exist; or an error if any directory contains foreign witforge-owned output or cannot be
    /// inspected.
    pub fn check(&self, out: &Path) -> Result<Vec<GeneratedFileFinding>> {
        self.check_inner(out, None)
    }

    /// Check an existing conformance bundle under `out` without writing, attaching
    /// `regenerate_command` to every reported drift finding.
    ///
    /// # Errors
    ///
    /// Returns the same errors as [`Self::check`].
    pub fn check_with_command(
        &self,
        out: &Path,
        regenerate_command: &str,
    ) -> Result<Vec<GeneratedFileFinding>> {
        self.check_inner(out, Some(regenerate_command))
    }

    fn check_inner(
        &self,
        out: &Path,
        regenerate_command: Option<&str>,
    ) -> Result<Vec<GeneratedFileFinding>> {
        let (out_norm, _) = validate_bundle_root(out, true)?;
        let mut findings = match regenerate_command {
            Some(cmd) => self.root.check_with_command(&out_norm, cmd)?,
            None => self.root.check(&out_norm)?,
        };
        let mut blocked_subdirs = std::collections::BTreeSet::new();
        for (subdir, files) in [("proto", &self.proto), ("wit", &self.wit)] {
            let sub_path = out_norm.join(subdir);
            match fs::symlink_metadata(&sub_path) {
                Ok(meta) if meta.file_type().is_symlink() => {
                    blocked_subdirs.insert(sub_path.clone());
                    findings.push(GeneratedFileFinding::new(
                        sub_path,
                        GeneratedFileStatus::Symlink,
                        regenerate_command,
                    ));
                }
                Ok(meta) if !meta.is_dir() => {
                    blocked_subdirs.insert(sub_path.clone());
                    findings.push(GeneratedFileFinding::new(
                        sub_path,
                        GeneratedFileStatus::NotDirectory,
                        regenerate_command,
                    ));
                }
                Ok(_) => {
                    let sub_findings = match regenerate_command {
                        Some(cmd) => files.check_with_command(&sub_path, cmd)?,
                        None => files.check(&sub_path)?,
                    };
                    findings.extend(sub_findings);
                }
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                    for rel in files.files().keys() {
                        findings.push(GeneratedFileFinding::new(
                            join_posix(&sub_path, rel),
                            GeneratedFileStatus::Missing,
                            regenerate_command,
                        ));
                    }
                }
                Err(err) => {
                    return Err(err)
                        .with_context(|| format!("failed to inspect {}", sub_path.display()));
                }
            }
        }
        if !blocked_subdirs.is_empty() {
            findings.retain(|finding| {
                !(finding.status == GeneratedFileStatus::Extra
                    && blocked_subdirs.contains(&finding.path))
            });
        }
        findings.sort_by(|left, right| {
            left.status
                .sort_rank()
                .cmp(&right.status.sort_rank())
                .then_with(|| left.path.cmp(&right.path))
        });
        Ok(findings)
    }

    /// Render unified diffs for every expected or extra conformance bundle file under `out`.
    ///
    /// # Errors
    ///
    /// Returns `WF9004` if `out` is empty, a symlink, or a non-directory, or an error if any
    /// directory contains foreign witforge-owned files or cannot be inspected.
    pub fn unified_diff(&self, out: &Path) -> Result<String> {
        let (out_norm, _) = validate_bundle_root(out, false)?;
        let mut diff = self.root.unified_diff(&out_norm)?;
        for (subdir, files) in [("proto", &self.proto), ("wit", &self.wit)] {
            let sub_path = out_norm.join(subdir);
            match fs::symlink_metadata(&sub_path) {
                Ok(meta) if meta.file_type().is_symlink() || !meta.is_dir() => {}
                Ok(_) => {
                    diff.push_str(&files.unified_diff(&sub_path)?);
                }
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                    diff.push_str(&files.unified_diff(&sub_path)?);
                }
                Err(err) => {
                    return Err(err)
                        .with_context(|| format!("failed to inspect {}", sub_path.display()));
                }
            }
        }
        Ok(diff)
    }
}

fn normalize_root_for_lstat(path: &Path) -> Result<PathBuf> {
    if path.as_os_str().is_empty() {
        return Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            "conformance output root must not be empty",
            None,
        ));
    }
    let raw = path.to_string_lossy();
    let trimmed = raw.trim_end_matches(|c| c == '/' || (cfg!(windows) && c == '\\'));
    if trimmed.is_empty() {
        return Ok(path.to_path_buf());
    }
    #[cfg(windows)]
    if trimmed.len() == 2 && trimmed.as_bytes()[1] == b':' {
        return Ok(path.to_path_buf());
    }
    Ok(PathBuf::from(trimmed))
}

fn validate_bundle_root(out: &Path, must_exist: bool) -> Result<(PathBuf, bool)> {
    let norm = normalize_root_for_lstat(out)?;
    match fs::symlink_metadata(&norm) {
        Ok(meta) if meta.file_type().is_symlink() => Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            format!(
                "refusing to use `{}` as conformance output root: it is a symlink, and \
                 generation never writes through one",
                norm.display()
            ),
            Some(norm.display().to_string()),
        )),
        Ok(meta) if !meta.is_dir() => Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            format!(
                "refusing to use `{}` as conformance output root: path exists and is not a \
                 directory",
                norm.display()
            ),
            Some(norm.display().to_string()),
        )),
        Ok(_) => Ok((norm, true)),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
            if must_exist {
                Err(crate::operational_error(
                    crate::diagnostic::codes::IO_ERROR,
                    format!("output root {} does not exist", norm.display()),
                    Some(norm.display().to_string()),
                ))
            } else {
                Ok((norm, false))
            }
        }
        Err(err) => Err(err).with_context(|| format!("failed to inspect {}", norm.display())),
    }
}

fn ensure_subdir_writable(path: &Path) -> Result<bool> {
    match fs::symlink_metadata(path) {
        Ok(meta) if meta.file_type().is_symlink() => Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            format!(
                "refusing to write into `{}`: it is a symlink, and generation never writes \
                 through one",
                path.display()
            ),
            Some(path.display().to_string()),
        )),
        Ok(meta) if !meta.is_dir() => Err(crate::operational_error(
            crate::diagnostic::codes::GUARD_REFUSED,
            format!(
                "refusing to write into `{}`: path exists and is not a directory",
                path.display()
            ),
            Some(path.display().to_string()),
        )),
        Ok(_) => Ok(true),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(err) => Err(err).with_context(|| format!("failed to inspect {}", path.display())),
    }
}

fn preflight_check_owned(files: &GeneratedFiles, dir: &Path) -> Result<()> {
    let findings = files.check(dir)?;
    for finding in findings {
        match finding.status {
            GeneratedFileStatus::Symlink
            | GeneratedFileStatus::NotRegular
            | GeneratedFileStatus::NotDirectory
            | GeneratedFileStatus::Unowned => {
                return Err(crate::operational_error(
                    crate::diagnostic::codes::GUARD_REFUSED,
                    finding.message(),
                    Some(finding.path.display().to_string()),
                ));
            }
            GeneratedFileStatus::Missing
            | GeneratedFileStatus::Changed { .. }
            | GeneratedFileStatus::Extra => {}
        }
    }
    Ok(())
}

fn join_posix(base: &Path, rel: &str) -> PathBuf {
    let mut path = base.to_path_buf();
    for seg in rel.split('/') {
        path.push(seg);
    }
    path
}

/// Plan the deterministic cross-language conformance bundle in memory without writing to disk.
///
/// # Errors
///
/// Returns an operational error (`WF9001`) if `options.proto` fails syntax/identifier validation
/// or contains unused per-package overrides, or a [`crate::ContractError`] (`WF1003`) if
/// configured protobuf file options cause a cross-file or same-file collision.
pub fn plan(options: &ConformanceOptions) -> Result<ConformanceBundle> {
    let loaded = load_sources(vec![
        SourceFile::new("contract.wit".to_string(), CONTRACT_WIT.to_string()),
        SourceFile::new(
            "deps/conformance-dep/dep.wit".to_string(),
            DEP_WIT.to_string(),
        ),
    ])?;
    let violations = subset::check(&loaded);
    anyhow::ensure!(
        violations.is_empty(),
        "built-in conformance contract violated subset rules: {violations:?}"
    );
    let model = model::build(&loaded)?;

    let members = model.members()?;
    let mut root_lock = WireLock::default();
    root_lock.reconcile(&members)?;
    let lock_text = root_lock.render();

    let dep = model
        .dependencies
        .first()
        .context("built-in conformance contract missing dependency package")?;
    let dep_model = Model {
        package: dep.package.clone(),
        interfaces: dep.interfaces.clone(),
        worlds: Vec::new(),
        dependencies: Vec::new(),
    };
    let dep_members = dep_model.members()?;
    let mut dep_lock = WireLock::default();
    dep_lock.reconcile(&dep_members)?;

    let version = Version {
        major: 0,
        directory: PathBuf::from("wit/v0.1"),
        model,
        lock: root_lock.clone(),
        locations: BTreeMap::new(),
    };
    let proto_files = proto::plan_versions_with_options(&[version], &options.proto)?;

    let vectors_json = build_vectors_json(&root_lock, &dep_lock)?;
    let root_header =
        HeaderStyle::JsonComment.format_header("conformance", ROOT_NAMESPACE, ROOT_NAME);
    let mut root_files = GeneratedFiles::new(root_header);
    root_files.insert("vectors.json", vectors_json)?;

    let wit_header =
        HeaderStyle::LineComment.format_header("conformance-wit", ROOT_NAMESPACE, ROOT_NAME);
    let mut wit_files = GeneratedFiles::new_nested(wit_header);
    wit_files.insert_relative("v0.1/contract.wit", CONTRACT_WIT)?;
    wit_files.insert_relative("v0.1/deps/conformance-dep/dep.wit", DEP_WIT)?;
    wit_files.insert_owned_lockfile("v0.1/wire.lock", ROOT_NAMESPACE, ROOT_NAME, lock_text)?;

    Ok(ConformanceBundle {
        root: root_files,
        proto: proto_files,
        wit: wit_files,
    })
}

/// Generate the cross-language conformance bundle under `out`.
///
/// # Errors
///
/// Returns the same errors as [`plan`] and [`ConformanceBundle::write`].
pub fn generate(out: &Path, options: &ConformanceOptions) -> Result<()> {
    plan(options)?.write(out)
}

/// Check an existing cross-language conformance bundle under `out` without writing.
///
/// # Errors
///
/// Returns the same errors as [`plan`] and [`ConformanceBundle::check`].
pub fn check(out: &Path, options: &ConformanceOptions) -> Result<Vec<GeneratedFileFinding>> {
    plan(options)?.check(out)
}

/// Check an existing cross-language conformance bundle under `out` without writing, attaching
/// `regenerate_command` to every drift finding.
///
/// # Errors
///
/// Returns the same errors as [`plan`] and [`ConformanceBundle::check_with_command`].
pub fn check_with_command(
    out: &Path,
    options: &ConformanceOptions,
    regenerate_command: &str,
) -> Result<Vec<GeneratedFileFinding>> {
    plan(options)?.check_with_command(out, regenerate_command)
}

/// Render unified diffs between an existing conformance bundle under `out` and the expected
/// bundle.
///
/// # Errors
///
/// Returns the same errors as [`plan`] and [`ConformanceBundle::unified_diff`].
pub fn unified_diff(out: &Path, options: &ConformanceOptions) -> Result<String> {
    plan(options)?.unified_diff(out)
}

/// Render the deterministic `vectors.json` conformance manifest (`conformance_version = 1`)
/// directly in memory.
///
/// # Errors
///
/// Returns an internal error only if the built-in conformance contract fails to lower.
pub fn vectors_json() -> Result<String> {
    Ok(plan(&ConformanceOptions::new())?.vectors_json().to_string())
}

// ---------------------------------------------------------------------------
// Minimal pure-Rust protobuf wire encoder, base64 encoder, and JSON renderer
// ---------------------------------------------------------------------------

#[derive(Default)]
struct ProtoBuf {
    bytes: Vec<u8>,
}

impl ProtoBuf {
    fn new() -> Self {
        Self::default()
    }

    fn varint(&mut self, mut value: u64) {
        loop {
            let mut byte = (value & 0x7f) as u8;
            value >>= 7;
            if value != 0 {
                byte |= 0x80;
            }
            self.bytes.push(byte);
            if value == 0 {
                break;
            }
        }
    }

    fn tag(&mut self, field: u32, wire_type: u32) {
        self.varint((u64::from(field) << 3) | u64::from(wire_type));
    }

    fn uint32(&mut self, field: u32, value: u32) {
        self.tag(field, 0);
        self.varint(u64::from(value));
    }

    fn uint64(&mut self, field: u32, value: u64) {
        self.tag(field, 0);
        self.varint(value);
    }

    fn sint32(&mut self, field: u32, value: i32) {
        self.tag(field, 0);
        let zz = ((value << 1) ^ (value >> 31)).cast_unsigned();
        self.varint(u64::from(zz));
    }

    fn sint64(&mut self, field: u32, value: i64) {
        self.tag(field, 0);
        let zz = ((value << 1) ^ (value >> 63)).cast_unsigned();
        self.varint(zz);
    }

    fn enum_i32(&mut self, field: u32, value: i32) {
        self.tag(field, 0);
        self.varint(i64::from(value).cast_unsigned());
    }

    fn bool_field(&mut self, field: u32, value: bool) {
        self.tag(field, 0);
        self.varint(u64::from(value));
    }

    fn f32_field(&mut self, field: u32, value: f32) {
        self.tag(field, 5);
        self.bytes.extend_from_slice(&value.to_bits().to_le_bytes());
    }

    fn f64_field(&mut self, field: u32, value: f64) {
        self.tag(field, 1);
        self.bytes.extend_from_slice(&value.to_bits().to_le_bytes());
    }

    fn bytes_field(&mut self, field: u32, payload: &[u8]) {
        self.tag(field, 2);
        self.varint(payload.len() as u64);
        self.bytes.extend_from_slice(payload);
    }

    fn string_field(&mut self, field: u32, text: &str) {
        self.bytes_field(field, text.as_bytes());
    }

    fn message(&mut self, field: u32, nested: &Self) {
        self.bytes_field(field, &nested.bytes);
    }

    fn empty_message(&mut self, field: u32) {
        self.bytes_field(field, &[]);
    }

    fn packed_uint32(&mut self, field: u32, values: &[u32]) {
        if values.is_empty() {
            return;
        }
        let mut inner = Self::new();
        for &v in values {
            inner.varint(u64::from(v));
        }
        self.bytes_field(field, &inner.bytes);
    }

    fn map_entry(&mut self, field: u32, build_entry: impl FnOnce(&mut Self)) {
        let mut entry = Self::new();
        build_entry(&mut entry);
        self.message(field, &entry);
    }
}

fn base64_encode(input: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(input.len().div_ceil(3) * 4);
    for chunk in input.chunks(3) {
        let b0 = u32::from(chunk[0]);
        let b1 = if chunk.len() > 1 {
            u32::from(chunk[1])
        } else {
            0
        };
        let b2 = if chunk.len() > 2 {
            u32::from(chunk[2])
        } else {
            0
        };
        let triple = (b0 << 16) | (b1 << 8) | b2;
        out.push(ALPHABET[((triple >> 18) & 0x3f) as usize] as char);
        out.push(ALPHABET[((triple >> 12) & 0x3f) as usize] as char);
        if chunk.len() > 1 {
            out.push(ALPHABET[((triple >> 6) & 0x3f) as usize] as char);
        } else {
            out.push('=');
        }
        if chunk.len() > 2 {
            out.push(ALPHABET[(triple & 0x3f) as usize] as char);
        } else {
            out.push('=');
        }
    }
    out
}

#[derive(Clone)]
enum JsonValue {
    Null,
    Bool(bool),
    Int(i64),
    Uint(u64),
    RawNumber(String),
    Str(String),
    Array(Vec<Self>),
    Object(Vec<(String, Self)>),
}

impl JsonValue {
    fn str(s: impl Into<String>) -> Self {
        Self::Str(s.into())
    }

    fn num(raw: impl Into<String>) -> Self {
        Self::RawNumber(raw.into())
    }

    fn obj(entries: impl IntoIterator<Item = (&'static str, Self)>) -> Self {
        Self::Object(
            entries
                .into_iter()
                .map(|(k, v)| (k.to_string(), v))
                .collect(),
        )
    }

    fn obj_owned(entries: Vec<(String, Self)>) -> Self {
        Self::Object(entries)
    }

    fn arr(items: impl IntoIterator<Item = Self>) -> Self {
        Self::Array(items.into_iter().collect())
    }

    fn render_compact(&self) -> String {
        let mut out = String::new();
        self.write_compact(&mut out);
        out
    }

    fn write_compact(&self, out: &mut String) {
        match self {
            Self::Null => out.push_str("null"),
            Self::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
            Self::Int(n) => {
                let _ = write!(out, "{n}");
            }
            Self::Uint(n) => {
                let _ = write!(out, "{n}");
            }
            Self::RawNumber(raw) => out.push_str(raw),
            Self::Str(s) => write_json_string(out, s),
            Self::Array(items) => {
                out.push('[');
                for (i, item) in items.iter().enumerate() {
                    if i > 0 {
                        out.push(',');
                    }
                    item.write_compact(out);
                }
                out.push(']');
            }
            Self::Object(entries) => {
                out.push('{');
                for (i, (k, v)) in entries.iter().enumerate() {
                    if i > 0 {
                        out.push(',');
                    }
                    write_json_string(out, k);
                    out.push(':');
                    v.write_compact(out);
                }
                out.push('}');
            }
        }
    }

    fn write_pretty(&self, out: &mut String, indent: usize) {
        match self {
            Self::Null
            | Self::Bool(_)
            | Self::Int(_)
            | Self::Uint(_)
            | Self::RawNumber(_)
            | Self::Str(_) => self.write_compact(out),
            Self::Array(items) => {
                if items.is_empty() {
                    out.push_str("[]");
                    return;
                }
                out.push_str("[\n");
                for (i, item) in items.iter().enumerate() {
                    push_indent(out, indent + 2);
                    item.write_pretty(out, indent + 2);
                    if i + 1 < items.len() {
                        out.push(',');
                    }
                    out.push('\n');
                }
                push_indent(out, indent);
                out.push(']');
            }
            Self::Object(entries) => {
                if entries.is_empty() {
                    out.push_str("{}");
                    return;
                }
                out.push_str("{\n");
                for (i, (k, v)) in entries.iter().enumerate() {
                    push_indent(out, indent + 2);
                    write_json_string(out, k);
                    out.push_str(": ");
                    v.write_pretty(out, indent + 2);
                    if i + 1 < entries.len() {
                        out.push(',');
                    }
                    out.push('\n');
                }
                push_indent(out, indent);
                out.push('}');
            }
        }
    }
}

fn push_indent(out: &mut String, spaces: usize) {
    for _ in 0..spaces {
        out.push(' ');
    }
}

fn write_json_string(out: &mut String, s: &str) {
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{08}' => out.push_str("\\b"),
            '\u{0C}' => out.push_str("\\f"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
}

